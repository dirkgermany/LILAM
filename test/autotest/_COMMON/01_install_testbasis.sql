    function t_logtext(p_manage boolean default true, p_parent number default null) return number is
        l_run    number;
        l_prefix varchar2(60);
        l_pid    number;
        l_n      number;
        l_len    number;
        l_bytes  number;
        l_ms     number;
        l_cases  number := 0;

        procedure run_case(p_mode varchar2, p_name varchar2, p_text varchar2) is
        begin
            if p_mode = c_insession then
                l_pid := lilam.new_session(p_processName => l_prefix || '_' || p_mode || '_' || p_name, p_logLevel => lilam.logLevelInfo);
            else
                l_pid := lilam.server_new_session(p_processName => l_prefix || '_' || p_mode || '_' || p_name,
                                                  p_groupName => c_group, p_logLevel => lilam.logLevelInfo);
            end if;
            lilam.info(l_pid, 'MARKER_VOR');
            lilam.info(l_pid, p_text);
            lilam.info(l_pid, 'MARKER_NACH');
            lilam.close_session(l_pid);
            l_cases := l_cases + 1;
        end;

        procedure check_case(p_mode varchar2, p_name varchar2, p_expect_len number) is
            l_p varchar2(200) := l_prefix || '_' || p_mode || '_' || p_name;
        begin
            execute immediate
              'select count(*), max(case when l.info like ''L=%'' then length(l.info) end),
                      max(case when l.info like ''L=%'' then lengthb(l.info) end)
                 from lilam_log l join lilam_proc p on p.id = l.process_id where p.process_name = :1'
              into l_n, l_len, l_bytes using l_p;
            check_that(l_run, rpad(p_mode || ' ' || p_name, 18) || ' 3 Zeilen, Text ' || p_expect_len || ' Zeichen, <= 2000 Bytes',
                       l_n = 3 and l_len = p_expect_len and l_bytes <= 2000,
                       'Zeilen ' || l_n || ', Zeichen ' || l_len || ', Bytes ' || l_bytes);
        end;
    begin
        l_run := begin_run('LOGTEXT_GRENZEN', 'INSESSION+SERVER', 'Laengen 1500..5000, Umlaute 2500', p_parent);
        l_prefix := 'LT_' || l_run || '_LEN';
        if p_manage then setup_servers(c_server, 1); end if;

        for m in (select column_value md from table(sys.odcivarchar2list(c_insession, c_server))) loop
            for i in 0 .. 7 loop
                run_case(m.md, to_char(1500 + i * 500), rpad('L=' || (1500 + i * 500) || '|', 1500 + i * 500, 'x'));
            end loop;
            run_case(m.md, 'UMLAUT', 'L=U|' || rpad('ä', 2500, 'ä'));
        end loop;

        l_ms := wait_count(l_prefix, 'LOG', l_cases * 3, 60);

        for m in (select column_value md from table(sys.odcivarchar2list(c_insession, c_server))) loop
            for i in 0 .. 7 loop
                check_case(m.md, to_char(1500 + i * 500), least(1500 + i * 500, 1900));
            end loop;
            check_case(m.md, 'UMLAUT', 1000);   -- 1000 Umlaute (+Praefix) = knapp 2000 Bytes
        end loop;

        l_n := internal_errors_since(run_started(l_run));
        check_that(l_run, 'Keine internen LILAM-Fehler', l_n = 0, l_n || ' Eintraege');
        if p_manage then stop_all_servers; end if;
        end_run(l_run);
        return l_run;
    exception
        when others then
            abort_run(l_run, p_manage, sqlerrm || ' ' || dbms_utility.format_error_backtrace);
            if p_manage then raise; end if;
            return l_run;
    end;

