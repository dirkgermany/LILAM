    procedure purge_prefix(p_prefix varchar2) is
        pragma autonomous_transaction;
        l_p varchar2(200) := replace(p_prefix, '_', '\_') || '%';
    begin
        execute immediate 'delete from lilam_log where process_id in (select id from lilam_proc where process_name like :1 escape ''\'')' using l_p;
        execute immediate 'delete from lilam_mon where process_id in (select id from lilam_proc where process_name like :1 escape ''\'')' using l_p;
        execute immediate 'delete from lilam_process_route where process_id in (select id from lilam_proc where process_name like :1 escape ''\'')' using l_p;
        execute immediate 'delete from lilam_baselines where scope_id in (select scope_id from lilam_scopes where scope_name like upper(:1) escape ''\'')' using l_p;
        execute immediate 'delete from lilam_scopes where scope_name like upper(:1) escape ''\''' using l_p;
        execute immediate 'delete from lilam_proc where process_name like :1 escape ''\''' using l_p;
        commit;
    exception
        when others then
            rollback;
            joblog(null, null, 'ERROR', 'purge_prefix ' || p_prefix || ': ' || sqlerrm);
    end;

    ----------------------------------------------------------------------
    -- Dauertest
    ----------------------------------------------------------------------
    -- Teiltest mit verkleinertem Umfang (laeuft als eigener Job = frische Session)
    procedure run_step(p_parent number, p_test varchar2, p_mode varchar2) is
        c_wait constant number := 60;
        l_run  number;
        l_var  varchar2(1);
    begin
        case p_test
            when 'LASTTEST'       then l_run := t_lasttest(p_mode, 1000, false, c_wait, p_parent);
            when 'MASSENTEST'     then l_run := t_massentest(p_mode, 50, 10, false, c_wait, p_parent);
            when 'PARALLELBETRIEB' then
                l_var := substr('ABCD', trunc(dbms_random.value(1, 5)), 1);
                l_run := t_parallel(p_mode, l_var, 4, 2, 50, false, c_wait, p_parent);
            when 'PROZESSZYKLEN'  then l_run := t_zyklen(p_mode, 4, 10, 10, 3, 20, false, c_wait, p_parent);
            when 'WAKEUP'         then l_run := t_wakeup(p_mode, sys.odcinumberlist(5, 20), false, p_parent);
            when 'LOGTEXT_GRENZEN' then l_run := t_logtext(false, p_parent);
            when 'BASELINE_SCOPE' then l_run := t_baseline_scope(false, p_parent);
            when 'LASTSPITZE'     then l_run := t_lastspitze(p_mode, 4, 20, false, 120, p_parent);
        end case;
    exception
        when others then
            joblog(p_parent, null, 'ERROR', 'Teiltest ' || p_test || ' (' || p_mode || '): ' || sqlerrm
                                            || ' | ' || dbms_utility.format_error_backtrace);
    end;

    function dauertest_start(p_hours number default 10, p_modes varchar2 default 'INSESSION,SERVER,DISPATCHER',
                             p_order varchar2 default 'RANDOM', p_bg_clients number default 2,
                             p_pause_max_s number default 120, p_lastspitze boolean default true) return number is
        l_run    number;
        l_end    timestamp := systimestamp + numtodsinterval(p_hours, 'HOUR');
        l_prefix varchar2(60);
        l_modes  sys.odcivarchar2list := sys.odcivarchar2list();
        l_list   sys.odcivarchar2list := sys.odcivarchar2list();
        l_ts     varchar2(200);
    begin
        for m in (select column_value md from table(sys.odcivarchar2list(c_insession, c_server, c_dispatcher))) loop
            if in_mode_list(m.md, p_modes) then l_modes.extend; l_modes(l_modes.count) := m.md; end if;
        end loop;
        if l_modes.count = 0 then raise_application_error(-20000, 'Keine gueltigen Modi in p_modes: ' || p_modes); end if;

        l_run := begin_run('DAUERTEST', upper(replace(p_modes, ' ')),
                   'hours=' || p_hours || ' order=' || upper(p_order) || ' bg_clients=' || p_bg_clients
                   || ' pause_max=' || p_pause_max_s || ' lastspitze=' || case when p_lastspitze then 'ja' else 'nein' end
                   || ' ende=' || to_char(l_end, 'DD.MM.YYYY HH24:MI'));
        l_prefix := 'LT_' || l_run || '_DAUER';

        -- Server laufen waehrend des gesamten Dauertests
        if in_mode_list(c_server, p_modes) or in_mode_list(c_dispatcher, p_modes) then
            start_server('LT_S1'); start_server('LT_S2');
            l_list.extend(2); l_list(1) := 'LT_S1'; l_list(2) := 'LT_S2';
            if in_mode_list(c_dispatcher, p_modes) then
                start_server(c_disp_pipe, 1);
                l_list.extend; l_list(l_list.count) := c_disp_pipe;
            end if;
            wait_servers_ready(l_list);
        end if;

        l_ts := 'to_timestamp(''' || to_char(l_end, 'YYYY-MM-DD HH24:MI:SS') || ''', ''YYYY-MM-DD HH24:MI:SS'')';

        -- Hintergrund: kurze Prozesszyklen mit Pausen, reihum auf die Modi verteilt
        for c in 1 .. p_bg_clients loop
            run_job('LT_C' || l_run || '_' || c,
              'begin lt.endurance(' || l_run || ', ' || c || ', ''' || l_modes(mod(c - 1, l_modes.count) + 1) || ''', '''
              || l_prefix || ''', ' || l_ts || ', 20, 30, 10); end;');
        end loop;

        -- Steuer-Job
        run_job('LT_CDAUER_' || l_run,
          'begin lt.dauertest_run(' || l_run || ', ' || l_ts || ', ''' || upper(replace(p_modes, ' ')) || ''', '''
          || upper(p_order) || ''', ' || p_pause_max_s || ', ' || case when p_lastspitze then 1 else 0 end || '); end;');

        dbms_output.put_line('Dauertest laeuft bis ' || to_char(l_end, 'DD.MM.YYYY HH24:MI') || ' (run_id=' || l_run || ')');
        return l_run;
    end;

    procedure dauertest_run(p_run_id number, p_end_ts timestamp, p_modes varchar2, p_order varchar2,
                            p_pause_max_s number, p_lastspitze number) is
        type t_step is record (test varchar2(30), md varchar2(20), weight number);
        type t_steps is table of t_step index by pls_integer;
        l_cat    t_steps;
        l_total  number := 0;
        l_idx    pls_integer := 0;
        l_pick   number;
        l_child  number;
        l_status varchar2(10);
        l_ok     boolean;
        l_n      pls_integer := 0;
        l_decoupled boolean := in_mode_list(c_server, p_modes) or in_mode_list(c_dispatcher, p_modes);

        procedure add(p_test varchar2, p_md varchar2, p_weight number) is
        begin
            l_cat(l_cat.count + 1).test := p_test;
            l_cat(l_cat.count).md       := p_md;
            l_cat(l_cat.count).weight   := p_weight;
            l_total := l_total + p_weight;
        end;
    begin
        -- Katalog und Gewichte (fuer RANDOM)
        for m in (select column_value md from table(sys.odcivarchar2list(c_insession, c_server, c_dispatcher))) loop
            if in_mode_list(m.md, p_modes) then
                add('PROZESSZYKLEN', m.md, 4);
                add('PARALLELBETRIEB', m.md, 3);
                add('LASTTEST', m.md, 2);
                add('MASSENTEST', m.md, 2);
                if m.md != c_insession then
                    add('WAKEUP', m.md, 1);
                    if p_lastspitze = 1 then add('LASTSPITZE', m.md, 1); end if;
                end if;
            end if;
        end loop;
        if l_decoupled then
            add('LOGTEXT_GRENZEN', 'INSESSION+SERVER', 1);
            add('BASELINE_SCOPE', 'INSESSION+SERVER', 1);
        end if;

        while systimestamp < p_end_ts loop
            if p_order = 'SEQ' then
                l_idx := mod(l_idx, l_cat.count) + 1;
            else
                l_pick := dbms_random.value(0, l_total);
                l_idx := 0;
                loop
                    l_idx := l_idx + 1;
                    l_pick := l_pick - l_cat(l_idx).weight;
                    exit when l_pick < 0 or l_idx = l_cat.count;
                end loop;
            end if;

            l_n := l_n + 1;
            run_job('LT_CSTEP_' || p_run_id || '_' || l_n,
              'begin lt.run_step(' || p_run_id || ', ''' || l_cat(l_idx).test || ''', '''
              || case when l_cat(l_idx).md like '%+%' then c_server else l_cat(l_idx).md end || '''); end;');
            l_ok := wait_jobs('LT_CSTEP_' || p_run_id || '_' || l_n, 3600);
            if not l_ok then
                joblog(p_run_id, null, 'ERROR', 'Teiltest ' || l_cat(l_idx).test || ' nach 1 h nicht beendet');
            end if;

            -- Daten bestandener Teiltests loeschen (Speicherplatz; Ergebnisse bleiben in LT_RUN/LT_CHECK/LT_METRIC)
            for r in (select run_id, status from lt_run where parent_run_id = p_run_id and run_id > nvl(l_child, 0)
                       order by run_id) loop
                if r.status = 'PASSED' then purge_prefix('LT_' || r.run_id || '_'); end if;
                l_child := r.run_id;
            end loop;

            exit when systimestamp >= p_end_ts;
            -- Pause: meist kurz, gelegentlich lang (Ruhezustand der Server)
            if dbms_random.value < 0.7 then
                dbms_session.sleep(round(dbms_random.value(0, 10), 1));
            else
                dbms_session.sleep(round(dbms_random.value(20, greatest(p_pause_max_s, 21)), 1));
            end if;
        end loop;
        joblog(p_run_id, null, 'END', l_n || ' Teiltests ausgefuehrt');
    exception
        when others then
            joblog(p_run_id, null, 'ERROR', 'Steuer-Job: ' || sqlerrm || ' | ' || dbms_utility.format_error_backtrace);
    end;

    procedure dauertest_auswertung(p_run_id number default null) is
        l_run    number := p_run_id;
        l_prefix varchar2(60);
        l_jobs   number;
        l_first  number;
        l_last   number;
        l_n      number;
        l_fail   number;
        l_procs  number;
        l_ops    number;
    begin
        if l_run is null then
            select max(run_id) into l_run from lt_run where test_name = 'DAUERTEST';
        end if;
        if l_run is null then raise_application_error(-20000, 'Kein Dauertest gefunden'); end if;
        l_prefix := 'LT_' || l_run || '_DAUER';
        dbms_output.put_line('=== Auswertung DAUERTEST run_id=' || l_run);

        select count(*) into l_jobs from user_scheduler_jobs
         where job_name like 'LT\_C' || l_run || '\_%' escape '\'
            or job_name = 'LT_CDAUER_' || l_run
            or job_name like 'LT\_CSTEP\_' || l_run || '\_%' escape '\';
        if l_jobs > 0 then
            dbms_output.put_line('Der Dauertest laeuft noch (' || l_jobs || ' Jobs aktiv). Auswertung abgebrochen.');
            return;
        end if;

        -- 1. Teiltests
        dbms_output.put_line('--- Teiltests');
        dbms_output.put_line('    ' || rpad('Test', 18) || rpad('Modus', 18) || lpad('Laeufe', 7) || lpad('bestanden', 11)
                             || lpad('Dauer 1. Drittel', 18) || lpad('Dauer 3. Drittel', 18));
        for t in (select test_name, mode_name, count(*) n, sum(case when status = 'PASSED' then 1 else 0 end) ok,
                         round(avg(case when tertile = 1 then dur end), 1) d1, round(avg(case when tertile = 3 then dur end), 1) d3
                    from (select test_name, mode_name, status,
                                 extract(day from ended - started) * 86400 + extract(hour from ended - started) * 3600
                                 + extract(minute from ended - started) * 60 + extract(second from ended - started) dur,
                                 ntile(3) over (partition by test_name, mode_name order by run_id) tertile
                            from lt_run where parent_run_id = l_run and ended is not null)
                   group by test_name, mode_name order by test_name, mode_name) loop
            dbms_output.put_line('    ' || rpad(t.test_name, 18) || rpad(t.mode_name, 18) || lpad(t.n, 7) || lpad(t.ok, 11)
                                 || lpad(nvl(to_char(t.d1), '-') || ' s', 18) || lpad(nvl(to_char(t.d3), '-') || ' s', 18));
            if t.d1 is not null and t.d3 is not null and t.n >= 3 then
                check_that(l_run, 'Dauer ' || t.test_name || ' ' || t.mode_name || ': letztes Drittel hoechstens doppelt so lang',
                           t.d3 <= 2 * t.d1, t.d1 || ' s -> ' || t.d3 || ' s');
            end if;
        end loop;

        select count(*), nvl(sum(case when status != 'PASSED' then 1 else 0 end), 0) into l_n, l_fail
          from lt_run where parent_run_id = l_run;
        metric(l_run, 'teiltests', l_n, 'count');
        check_that(l_run, 'Teiltests ausgefuehrt', l_n > 0, l_n);
        check_that(l_run, 'Alle Teiltests bestanden', l_fail = 0, l_fail || ' von ' || l_n || ' nicht bestanden');
        for f in (select r.run_id, r.test_name, r.mode_name,
                         (select listagg(c.check_name || ' [' || c.detail || ']', '; ') within group (order by c.check_no)
                            from lt_check c where c.run_id = r.run_id and c.ok = 0) fehler
                    from lt_run r where r.parent_run_id = l_run and r.status != 'PASSED'
                   order by r.run_id fetch first 20 rows only) loop
            dbms_output.put_line('    NICHT BESTANDEN run_id=' || f.run_id || ' ' || f.test_name || ' ' || f.mode_name
                                 || ': ' || substr(f.fehler, 1, 400));
        end loop;

        select count(*) into l_n from lt_joblog where run_id = l_run and phase = 'ERROR';
        check_that(l_run, 'Keine Fehler im Steuer-Job und in den Hintergrund-Clients', l_n = 0, l_n || ' Fehler');

        -- 2. Stabilitaet der Hintergrund-Clients (Mittel der ersten und letzten 6 Messpunkte, je 10 min)
        select avg(value) into l_first from (
            select value from lt_metric where run_id = l_run and metric = 'cycle_avg_ms' order by ts fetch first 6 rows only);
        select avg(value) into l_last from (
            select value from lt_metric where run_id = l_run and metric = 'cycle_avg_ms' order by ts desc fetch first 6 rows only);
        if l_first is not null then
            check_that(l_run, 'Hintergrund: Zyklusdauer am Ende hoechstens doppelt so lang wie am Anfang',
                       nvl(l_last, 0) <= 2 * l_first, 'Anfang ' || round(l_first) || ' ms, Ende ' || round(l_last) || ' ms');
        end if;

        select avg(value) into l_first from (
            select value from lt_metric where run_id = l_run and metric = 'server_pga_kb' and value is not null order by ts fetch first 6 rows only);
        select avg(value) into l_last from (
            select value from lt_metric where run_id = l_run and metric = 'server_pga_kb' and value is not null order by ts desc fetch first 6 rows only);
        if l_first is not null then
            check_that(l_run, 'Server-PGA am Ende hoechstens doppelt so gross wie am Anfang',
                       l_last <= 2 * l_first, 'Anfang ' || round(l_first) || ' KB, Ende ' || round(l_last) || ' KB');
        else
            dbms_output.put_line('    Hinweis: keine PGA-Werte (Grants aus _COMMON/00_grants_als_sys.sql fehlen oder nur INSESSION)');
        end if;

        -- 3. Vollstaendigkeit der Hintergrund-Daten
        l_procs := count_lilam(l_prefix, 'PROC');
        metric(l_run, 'bg_processes_total', l_procs, 'count');
        if l_procs > 0 then
            -- Routen gibt es nur im Decoupled-Mode; fuer INSESSION-Prozesse ist die Pruefung immer erfuellt
            verify_standard(l_run, l_prefix, l_procs, 20, true, 120);
        end if;

        stop_all_servers;
        end_run(l_run);
    end;

end lt;
