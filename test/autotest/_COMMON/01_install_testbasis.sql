    -- Server je Modus starten: SERVER p_workers Worker, DISPATCHER mind. 2 Worker + Dispatcher
    procedure setup_servers(p_mode varchar2, p_workers pls_integer default 1) is
        l_list sys.odcivarchar2list := sys.odcivarchar2list();
        l_n    pls_integer := case when p_mode = c_dispatcher then greatest(p_workers, 2) else p_workers end;
    begin
        if p_mode = c_insession then return; end if;
        for i in 1 .. l_n loop
            start_server('LT_S' || i);
            l_list.extend; l_list(l_list.count) := 'LT_S' || i;
        end loop;
        if p_mode = c_dispatcher then
            start_server(c_disp_pipe, 1);
            l_list.extend; l_list(l_list.count) := c_disp_pipe;
        end if;
        wait_servers_ready(l_list);
    end;

    -- Durchsatz aus Sicht der Clients
    procedure throughput_metrics(p_run number, p_clients number, p_avg_per_call boolean) is
        l_calls number; l_ms number;
    begin
        select sum(value) into l_calls from lt_metric where run_id = p_run and metric = 'client_api_calls';
        select max(value) into l_ms    from lt_metric where run_id = p_run and metric = 'client_elapsed_ms';
        if l_calls > 0 and l_ms > 0 then
            metric(p_run, 'api_calls_total', l_calls, 'calls');
            metric(p_run, 'throughput', round(l_calls / (l_ms / 1000)), 'calls/s');
            if p_avg_per_call then
                metric(p_run, 'avg_per_call', round(l_ms * 1000 / (l_calls / p_clients)), 'us');
            end if;
        end if;
    end;

    -- Abbruch eines Tests: als Fehler festhalten; Server nur im Einzeltest stoppen
    procedure abort_run(p_run number, p_manage boolean, p_msg varchar2) is
    begin
        dbms_output.put_line('ABBRUCH: ' || p_msg);
        if p_run is not null then
            check_that(p_run, 'Testablauf ohne Abbruch', false, substr(p_msg, 1, 900));
            end_run(p_run);
        end if;
        if p_manage then stop_all_servers; end if;
    end;

    function in_mode_list(p_mode varchar2, p_list varchar2) return boolean is
    begin
        return instr(',' || upper(replace(p_list, ' ')) || ',', ',' || p_mode || ',') > 0;
    end;

    -- Pipes der laufenden Test-Server
    function running_servers return sys.odcivarchar2list is
        l_list sys.odcivarchar2list;
    begin
        select job_name bulk collect into l_list from user_scheduler_jobs
         where job_name like 'LT\_%' escape '\' and job_name not like 'LT\_C%' escape '\';
        return l_list;
    end;

    ----------------------------------------------------------------------
    function t_lasttest(p_mode varchar2, p_ops number default 5000,
                        p_manage boolean default true, p_max_wait number default 300, p_parent number default null) return number is
        l_run    number;
        l_prefix varchar2(60);
    begin
        l_run := begin_run('LASTTEST', p_mode, 'clients=1 processes=1 ops=' || p_ops || ' interleave=false', p_parent);
        l_prefix := 'LT_' || l_run || '_LASTTE';
        if p_manage then setup_servers(p_mode, 1); end if;

        run_job('LT_C' || l_run || '_1',
          'begin lt.workload(' || l_run || ', 1, ''' || p_mode || ''', ''' || l_prefix || ''', 1, ' || p_ops || ', 0, false); end;');
        check_that(l_run, 'Client-Jobs innerhalb ' || c_job_wait || ' s beendet', wait_jobs('LT_C' || l_run || '_', c_job_wait));
        throughput_metrics(l_run, 1, true);

        verify_standard(l_run, l_prefix, 1, p_ops, p_mode != c_insession, p_max_wait);
        if p_manage then stop_all_servers; end if;
        end_run(l_run);
        return l_run;
    exception
        when others then
            abort_run(l_run, p_manage, sqlerrm || ' ' || dbms_utility.format_error_backtrace);
            if p_manage then raise; end if;
            return l_run;
    end;

    ----------------------------------------------------------------------
    function t_massentest(p_mode varchar2, p_processes number default 200, p_ops number default 20,
                          p_manage boolean default true, p_max_wait number default 300, p_parent number default null) return number is
        l_run    number;
        l_prefix varchar2(60);
    begin
        l_run := begin_run('MASSENTEST', p_mode,
