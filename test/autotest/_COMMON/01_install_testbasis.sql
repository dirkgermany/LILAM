    -- ==================================================================
    function dauertest_start(p_hours number default 10, p_modes varchar2 default 'INSESSION,SERVER,DISPATCHER',
                             p_order varchar2 default 'RANDOM', p_bg_clients number default 2,
                             p_pause_max_s number default 120, p_lastspitze boolean default true) return number;
    procedure dauertest_run(p_run_id number, p_end_ts timestamp, p_modes varchar2, p_order varchar2,
                            p_pause_max_s number, p_lastspitze number);
    procedure dauertest_auswertung(p_run_id number default null);

    -- Teiltest im Dauertest (laeuft als Job)
    procedure run_step(p_parent number, p_test varchar2, p_mode varchar2);

    -- LILAM-Daten aller Prozesse mit Namenspraefix loeschen (inkl. Routen, Scopes, Baselines)
    procedure purge_prefix(p_prefix varchar2);
end lt;
