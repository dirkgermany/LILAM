    function t_wakeup(p_mode varchar2, p_idle sys.odcinumberlist default sys.odcinumberlist(5, 16, 30, 65),
                      p_manage boolean default true, p_parent number default null) return number is
        l_run    number;
        l_prefix varchar2(60);
        l_pid    number;
        l_exp    number := 1;
        l_ms     number;
        l_n      number;
        l_ok     boolean;
        l_srv    sys.odcivarchar2list;
        l_idle   varchar2(200);
    begin
        for i in 1 .. p_idle.count loop l_idle := l_idle || case when i > 1 then ',' end || p_idle(i); end loop;
        l_run := begin_run('WAKEUP', p_mode, 'idle=' || l_idle || ' s', p_parent);
        l_prefix := 'LT_' || l_run || '_WAKE';
        if p_mode = c_insession then
            raise_application_error(-20000, 'WAKEUP ist nur im Decoupled-Mode sinnvoll');
        end if;
        if p_manage then setup_servers(p_mode, 1); end if;
        l_srv := running_servers;

        if p_mode = c_dispatcher then
            -- DISPATCHER: jeder Schritt in einem eigenen Job (frische Session, wie APEX); die
            -- aufrufende Session behaelt so auch keine Dispatcher-Einstellung (wichtig im Dauertest)
            run_job('LT_CW' || l_run || '_0',
              'declare l_pid number; begin lilam.set_dispatcher_pipe(''' || c_disp_pipe || '''); '
              || 'l_pid := lilam.server_new_session(p_processName => ''' || l_prefix || ''', p_groupName => ''' || c_group
              || ''', p_logLevel => lilam.logLevelInfo); lilam.info(l_pid, ''start''); '
              || 'lt.metric(' || l_run || ', ''wake_pid'', l_pid); end;');
            l_ok := wait_jobs('LT_CW' || l_run || '_0', 60);
            select max(value) into l_pid from lt_metric where run_id = l_run and metric = 'wake_pid';
        else
            -- SERVER: alles in der aufrufenden Session (ohne Dispatcher kennt nur sie den Prozess)
            l_pid := lilam.server_new_session(p_processName => l_prefix, p_groupName => c_group, p_logLevel => lilam.logLevelInfo);
            lilam.info(l_pid, 'start');
        end if;

        for i in 1 .. p_idle.count loop
            dbms_output.put_line('    Ruhephase ' || p_idle(i) || ' s ...');
            dbms_session.sleep(p_idle(i));

            execute immediate
              'select count(*) from lilam_server_registry where is_active = 1
                  and last_activity > systimestamp - interval ''15'' second
                  and pipe_name in (select column_value from table(:1))' into l_n using l_srv;
            check_that(l_run, 'Nach ' || p_idle(i) || ' s Ruhe: alle Server aktiv registriert', l_n = l_srv.count,
                       l_n || '/' || l_srv.count || ' aktiv');

            if p_mode = c_dispatcher then
                run_job('LT_CW' || l_run || '_' || i,
                  'begin lt.wake_call(' || l_run || ', ''' || p_mode || ''', ' || l_pid || ', ' || p_idle(i) || ', ''' || l_prefix || '''); end;');
                l_ok := wait_jobs('LT_CW' || l_run || '_' || i, 60);
            else
                wake_call(l_run, p_mode, l_pid, p_idle(i), l_prefix);
            end if;
            l_exp := l_exp + 2;   -- INFO am bestehenden Prozess + INFO am neuen Prozess
            l_ms := wait_count(l_prefix, 'LOG', l_exp, 30);
            check_that(l_run, 'Nach ' || p_idle(i) || ' s Ruhe: Logs persistiert', l_ms >= 0, l_ms || ' ms');
            if l_ms >= 0 then metric(l_run, 'wake_persist_ms_' || p_idle(i) || 's', l_ms, 'ms'); end if;
        end loop;

        if p_mode = c_dispatcher then
            run_job('LT_CW' || l_run || '_E',
              'begin lilam.set_dispatcher_pipe(''' || c_disp_pipe || '''); lilam.close_session(' || l_pid || '); end;');
            l_ok := wait_jobs('LT_CW' || l_run || '_E', 60);
        else
            lilam.close_session(l_pid);
        end if;

        l_ms := wait_count(l_prefix, 'PROC_CLOSED', 1 + p_idle.count, 30);
        l_n  := count_lilam(l_prefix, 'PROC_CLOSED');
        check_that(l_run, 'Alle Prozesse geschlossen', l_n = 1 + p_idle.count, l_n || '/' || (1 + p_idle.count));
        l_n := count_lilam(l_prefix, 'EVENT');
        check_that(l_run, 'Alle Weck-Events angekommen', l_n = p_idle.count, l_n || '/' || p_idle.count);
        select count(*) into l_n from lt_joblog where run_id = l_run and phase = 'ERROR';
        check_that(l_run, 'Keine Fehler bei den Weck-Aufrufen', l_n = 0, l_n || ' Fehler');
        l_n := internal_errors_since(run_started(l_run));
        check_that(l_run, 'Keine internen LILAM-Fehler', l_n = 0, l_n || ' Eintraege');

        if p_manage then stop_all_servers; end if;
        end_run(l_run);
        return l_run;
    exception
        when others then
            abort_run(l_run, p_manage, sqlerrm || ' ' || dbms_utility.format_error_backtrace);
            if p_manage then raise; end if;
            return l_run;
    end;

