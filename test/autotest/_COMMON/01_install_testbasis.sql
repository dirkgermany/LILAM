    function t_baseline_scope(p_manage boolean default true, p_parent number default null) return number is
        c_action  constant varchar2(30) := 'BS_ACTION';
        c_sleep_s constant number       := 0.2;
        l_run     number;

        function run_app(p_mode varchar2, p_name varchar2, p_scope varchar2, p_traces pls_integer) return number is
            l_pid number;
        begin
            if p_mode = c_insession then
                l_pid := lilam.new_session(p_processName => p_name, p_logLevel => lilam.logLevelInfo, p_baselineScope => p_scope);
            else
                l_pid := lilam.server_new_session(p_processName => p_name, p_groupName => c_group,
                                                  p_logLevel => lilam.logLevelInfo, p_baselineScope => p_scope);
            end if;
            for i in 1 .. p_traces loop
                lilam.trace_start(l_pid, c_action);
                dbms_session.sleep(c_sleep_s);
                lilam.trace_stop(l_pid, c_action);
            end loop;
            lilam.close_session(l_pid);
            return l_pid;
        end;

        function scope_count(p_scope varchar2) return number is
            l_cnt number;
        begin
            execute immediate 'select count(*) from lilam_scopes where scope_name = upper(:1)' into l_cnt using p_scope;
            return l_cnt;
        end;

        function base_count(p_scope varchar2) return number is
            l_cnt number;
        begin
            execute immediate 'select nvl(sum(b.action_count), 0) from lilam_baselines b join lilam_scopes s on s.scope_id = b.scope_id
                                where s.scope_name = upper(:1) and b.action_name = :2' into l_cnt using p_scope, c_action;
            return l_cnt;
        end;

        function base_avg(p_scope varchar2) return number is
            l_avg number;
        begin
            execute immediate 'select max(b.avg_ms) from lilam_baselines b join lilam_scopes s on s.scope_id = b.scope_id
                                where s.scope_name = upper(:1) and b.action_name = :2' into l_avg using p_scope, c_action;
            return l_avg;
        end;

        -- im SERVER-Modus wird die Baseline asynchron abgeglichen
        procedure wait_base(p_scope varchar2, p_expected number, p_max_s number default 15) is
            l_waited number := 0;
        begin
            while base_count(p_scope) < p_expected and l_waited < p_max_s loop
                dbms_session.sleep(0.5); l_waited := l_waited + 0.5;
            end loop;
        end;

        procedure run_mode(p_mode varchar2, p_tag varchar2) is
            l_prefix varchar2(60) := 'LT_' || l_run || '_' || p_tag;
            l_app    varchar2(80) := l_prefix || '_APP';
            l_shared varchar2(80) := l_prefix || '_SHARED';
            l_pid    number;
            l_cnt    number;
            l_avg    number;
            l_mon    number;
            l_servers number;
            l_tol    number;
        begin
            -- B1: Default-Scope, drei Neustarts mit je 2 Traces
            for r in 1 .. 3 loop l_pid := run_app(p_mode, l_app, null, 2); end loop;
            wait_base(l_app, 6);
            l_cnt := base_count(l_app);
            l_avg := base_avg(l_app);
            check_that(l_run, p_tag || ' B1 Default-Scope: genau 1 Scope fuer den Prozessnamen', scope_count(l_app) = 1, scope_count(l_app));
            check_that(l_run, p_tag || ' B1 Baseline zaehlt alle 6 Messungen aus 3 Prozessen', l_cnt = 6, l_cnt);
            check_that(l_run, p_tag || ' B1 Mittel der Baseline plausibel (150..500 ms)', l_avg between 150 and 500, round(l_avg, 1) || ' ms');
            metric(l_run, lower(p_tag) || '_baseline_avg_ms', l_avg, 'ms');

            -- B2: ACTION_COUNT in _MON zaehlt je Prozess (1, 2), nicht ueber den Scope
            execute immediate 'select nvl(max(m.action_count), 0) from lilam_mon m join lilam_proc p on p.id = m.process_id
                                where p.process_name = :1 and m.action = :2' into l_cnt using l_app, c_action;
            check_that(l_run, p_tag || ' B2 _MON zaehlt prozesslokal (max. 2 je Prozess)', l_cnt = 2, l_cnt);

            -- B3: AVG_MILLIS des letzten Eintrags = Baseline des Scopes
            -- Mit mehreren Servern (z. B. im Dauertest) haelt jeder Server die Baseline in seiner PGA und gleicht sie
            -- nur alle 1,5 s ab. _MON zeigt dann den Stand eines Servers, die Tabelle den zusammengefuehrten Stand.
            -- Deshalb gilt dort eine Toleranz von 20 % der Baseline, sonst +-1 ms.
            l_servers := 1;
            if p_mode != c_insession then
                execute immediate 'select count(*) from lilam_server_registry where is_active = 1 and nvl(is_dispatcher, 0) = 0
                                      and upper(group_name) = upper(:1) and last_activity > systimestamp - interval ''15'' second'
                                 into l_servers using c_group;
            end if;
            l_tol := case when l_servers > 1 then greatest(1, 0.2 * l_avg) else 1 end;
            execute immediate 'select max(m.avg_millis) keep (dense_rank last order by m.stop_time)
                                 from lilam_mon m where m.process_id = :1 and m.action = :2' into l_mon using l_pid, c_action;
            check_that(l_run, p_tag || ' B3 _MON.AVG_MILLIS des letzten Prozesses = Baseline', abs(nvl(l_mon, -1) - l_avg) <= l_tol,
                       'MON ' || l_mon || ' / Baseline ' || round(l_avg, 1) || ' / Toleranz ' || round(l_tol, 1)
                       || ' ms / Server ' || l_servers);

            -- B4: #NONE aendert die Baseline nicht
            l_pid := run_app(p_mode, l_app, '#NONE', 2);
            if p_mode != c_insession then dbms_session.sleep(3); end if;
            check_that(l_run, p_tag || ' B4 Scope #NONE: Baseline unveraendert', base_count(l_app) = 6, base_count(l_app));
            check_that(l_run, p_tag || ' B4 Scope #NONE: kein Scope "#NONE" angelegt', scope_count('#NONE') = 0, scope_count('#NONE'));

            -- B5: frei gewaehlter Scope, zwei verschiedene Prozessnamen
            l_pid := run_app(p_mode, l_prefix || '_X', l_shared, 2);
            l_pid := run_app(p_mode, l_prefix || '_Y', l_shared, 2);
            wait_base(l_shared, 4);
            check_that(l_run, p_tag || ' B5 gemeinsamer Scope zaehlt beide Prozesse (4)', base_count(l_shared) = 4, base_count(l_shared));
            check_that(l_run, p_tag || ' B5 keine eigenen Scopes fuer _X/_Y',
                       scope_count(l_prefix || '_X') + scope_count(l_prefix || '_Y') = 0,
                       scope_count(l_prefix || '_X') + scope_count(l_prefix || '_Y'));
        end;
    begin
        l_run := begin_run('BASELINE_SCOPE', 'INSESSION+SERVER', null, p_parent);
        run_mode(c_insession, 'IS');
        if p_manage then setup_servers(c_server, 1); end if;
        run_mode(c_server, 'SV');
        if p_manage then stop_all_servers; end if;
        check_that(l_run, 'B6 Keine internen LILAM-Fehler', internal_errors_since(run_started(l_run)) = 0,
                   internal_errors_since(run_started(l_run)));
        end_run(l_run);
        return l_run;
    exception
        when others then
            abort_run(l_run, p_manage, sqlerrm || ' ' || dbms_utility.format_error_backtrace);
            if p_manage then raise; end if;
            return l_run;
    end;

    ----------------------------------------------------------------------
    -- Rueckschreibung: Sichtbarkeit vor CLOSE_SESSION
    ----------------------------------------------------------------------
    -- Laeuft als Job (fremde Session): liest den Tabellenstand der Testprozesse mit Praefix p_prefix
    -- und haelt ihn als Messwerte <p_key>_<was> fest. Die pruefende Session liest sie aus LT_METRIC.
    procedure rs_peek(p_run_id number, p_prefix varchar2, p_key varchar2) is
        l_n number;

        function q(p_sql varchar2, p_bind varchar2) return number is
            l_v number;
        begin
            execute immediate p_sql into l_v using p_bind;
            return l_v;
        exception when others then return -1;
        end;
    begin
        metric(p_run_id, p_key || '_sid', to_number(sys_context('userenv', 'sid')));
        l_n := q('select count(*) from lilam_mon m join lilam_proc p on p.id = m.process_id
                   where p.process_name = :1 and m.mon_type = 1', p_prefix || '_TRC');
        metric(p_run_id, p_key || '_trc', l_n);
        l_n := q('select nvl(max(m.action_count), 0) from lilam_mon m join lilam_proc p on p.id = m.process_id
                   where p.process_name = :1 and m.mon_type = 1', p_prefix || '_TRC');
        metric(p_run_id, p_key || '_trccnt', l_n);
        l_n := q('select count(*) from lilam_proc where process_name = :1 and process_end is null', p_prefix || '_TRC');
        metric(p_run_id, p_key || '_trcopen', l_n);
        l_n := q('select count(*) from lilam_mon m join lilam_proc p on p.id = m.process_id
                   where p.process_name = :1 and m.mon_type = 0', p_prefix || '_EVT');
        metric(p_run_id, p_key || '_evt', l_n);
        l_n := q('select nvl(max(steps_done), -1) from lilam_proc where process_name = :1', p_prefix || '_STP');
        metric(p_run_id, p_key || '_stp', l_n);
        l_n := q('select nvl(max(status), -1) from lilam_proc where process_name = :1', p_prefix || '_STP');
        metric(p_run_id, p_key || '_sts', l_n);
        l_n := q('select nvl(sum(b.action_count), 0) from lilam_baselines b join lilam_scopes s on s.scope_id = b.scope_id
                   where s.scope_name = upper(:1)', p_prefix || '_SCOPE');
        metric(p_run_id, p_key || '_bas', l_n);
    end;

    -- Je Modus vier Prozesse ohne Log-Aufruf: nur Traces, nur Events, nur Fortschritt, nur Baseline.
    -- Jeweils ein Aufruf, Pause > 1,5 s, ein weiterer Aufruf; danach prueft ein Job aus fremder Session,
    -- dass auch der Stand des letzten Aufrufs in der Tabelle steht, bevor CLOSE_SESSION laeuft.
    function t_rueckschreibung(p_manage boolean default true, p_parent number default null) return number is
        c_action  constant varchar2(30) := 'RS_ACTION';
        c_pause_s constant number       := 2;     -- > 1,5 s Schwelle je Prozess und Baseline, > 500 ms Sperre
        c_server_wait_s constant number := 15;    -- SERVER: hoechstens so lange auf den Server-Loop warten (Dauertest: Last)
        l_run     number;
        l_peeks   pls_integer := 0;

        procedure trace(p_pid number) is
        begin
            lilam.trace_start(p_pid, c_action);
            dbms_session.sleep(0.05);
            lilam.trace_stop(p_pid, c_action);
        end;

        -- Tabellenstand aus fremder Session (Job) festhalten
        procedure peek(p_prefix varchar2, p_key varchar2) is
            l_job varchar2(60);
        begin
            l_peeks := l_peeks + 1;
            l_job := 'LT_C' || l_run || '_PEEK' || l_peeks;
            run_job(l_job, 'begin lt.rs_peek(' || l_run || ', ''' || p_prefix || ''', ''' || p_key || '''); end;');
            if not wait_jobs(l_job, 30) then
                raise_application_error(-20001, 'Job ' || l_job || ' nicht beendet');
            end if;
        end;

        function val(p_key varchar2, p_what varchar2) return number is
            l_v number;
        begin
            select max(value) into l_v from lt_metric where run_id = l_run and metric = p_key || '_' || p_what;
            return l_v;
        end;

        procedure check_foreign(p_key varchar2) is
        begin
            check_that(l_run, p_key || ' Pruefung lief in fremder Session',
                       val(p_key, 'sid') != to_number(sys_context('userenv', 'sid')),
                       'SID ' || val(p_key, 'sid') || ' / eigene ' || sys_context('userenv', 'sid'));
        end;

        procedure run_mode(p_mode varchar2, p_tag varchar2) is
            l_prefix varchar2(60) := 'LT_' || l_run || '_' || p_tag;
            l_ins    boolean      := p_mode = c_insession;
            l_trc    number;
            l_evt    number;
            l_stp    number;
            l_bas    number;
            l_key    varchar2(30);

            -- INSESSION: genau eine Pruefung, der Stand muss sofort sichtbar sein.
            -- SERVER: der Server schreibt asynchron; wiederholen, bis p_what den Wert p_expected erreicht.
            procedure peek_wait(p_key varchar2, p_what varchar2, p_expected number) is
                l_t0 timestamp := systimestamp;
            begin
                loop
                    if not l_ins then dbms_session.sleep(1); end if;
                    peek(l_prefix, p_key);
                    exit when l_ins or nvl(val(p_key, p_what), -1) >= p_expected
                              or ms_since(l_t0) > c_server_wait_s * 1000;
                end loop;
            end;
        begin
            -- R1 nur Traces
            l_key := p_tag || '_R1';
            l_trc := open_process(p_mode, l_prefix || '_TRC');
            trace(l_trc);
            dbms_session.sleep(c_pause_s);
            trace(l_trc);
            peek_wait(l_key, 'trc', 2);
            check_foreign(l_key);
            check_that(l_run, l_key || ' nur Traces: beide Traces vor CLOSE_SESSION in LILAM_MON',
                       val(l_key, 'trc') = 2, val(l_key, 'trc'));

            -- R2 nur Events
            l_key := p_tag || '_R2';
            l_evt := open_process(p_mode, l_prefix || '_EVT');
            lilam.mark_event(l_evt, c_action);
            dbms_session.sleep(c_pause_s);
            lilam.mark_event(l_evt, c_action);
            peek_wait(l_key, 'evt', 2);
            check_that(l_run, l_key || ' nur Events: beide Events vor CLOSE_SESSION in LILAM_MON',
                       val(l_key, 'evt') = 2, val(l_key, 'evt'));

            -- R3 nur Fortschritt (PROC_STEP_DONE, SET_PROCESS_STATUS)
            l_key := p_tag || '_R3';
            l_stp := open_process(p_mode, l_prefix || '_STP');
            lilam.proc_step_done(l_stp);
            dbms_session.sleep(c_pause_s);
            lilam.proc_step_done(l_stp);
            dbms_session.sleep(c_pause_s);
            lilam.set_process_status(l_stp, 2, 'PHASE 2');
            peek_wait(l_key, 'sts', 2);
            check_that(l_run, l_key || ' nur Fortschritt: STEPS_DONE = 2 vor CLOSE_SESSION in LILAM_PROC',
                       val(l_key, 'stp') = 2, val(l_key, 'stp'));
            check_that(l_run, l_key || ' nur Fortschritt: STATUS = 2 vor CLOSE_SESSION in LILAM_PROC',
                       val(l_key, 'sts') = 2, val(l_key, 'sts'));

            -- R4 nur Baseline (eigener Scope)
            l_key := p_tag || '_R4';
            l_bas := open_process(p_mode, l_prefix || '_BAS', l_prefix || '_SCOPE');
            trace(l_bas);
            dbms_session.sleep(c_pause_s);
            trace(l_bas);
            peek_wait(l_key, 'bas', 2);
            check_that(l_run, l_key || ' nur Baseline: 2 Messungen vor CLOSE_SESSION in LILAM_BASELINES',
                       val(l_key, 'bas') = 2, val(l_key, 'bas'));

            -- R5 (nur INSESSION) Gegenprobe: ohne Timer bleibt nach dem letzten Aufruf etwas im Puffer.
            -- PROC_STEP_DONE schreibt (letzter Abgleich > 1,5 s her); der Trace direkt danach faellt in die
            -- 500-ms-Sperre und bleibt im Puffer, bis CLOSE_SESSION ihn schreibt.
            if l_ins then
                l_key := p_tag || '_R5';
                dbms_session.sleep(c_pause_s);
                lilam.proc_step_done(l_stp);
                trace(l_trc);
                peek(l_prefix, l_key);
                check_that(l_run, l_key || ' Gegenprobe: PROC_STEP_DONE geschrieben (STEPS_DONE = 3)',
                           val(l_key, 'stp') = 3, val(l_key, 'stp'));
                check_that(l_run, l_key || ' Gegenprobe: Trace direkt danach noch im Puffer (2 statt 3)',
                           val(l_key, 'trc') = 2, val(l_key, 'trc'));

                -- R6 FLUSH schreibt sofort (auch innerhalb der 500-ms-Sperre), der Prozess bleibt offen
                l_key := p_tag || '_R6';
                lilam.flush;
                peek(l_prefix, l_key);
                check_that(l_run, l_key || ' FLUSH: gepufferter Trace sofort geschrieben (3)',
                           val(l_key, 'trc') = 3, val(l_key, 'trc'));
                check_that(l_run, l_key || ' FLUSH: Prozess bleibt offen (PROCESS_END leer)',
                           val(l_key, 'trcopen') = 1, val(l_key, 'trcopen'));

                -- R7 FLUSH per CALL_BY_JSON; der Prozess zaehlt nach dem FLUSH weiter
                l_key := p_tag || '_R7';
                lilam.flush;       -- startet die 500-ms-Sperre: der folgende Trace bleibt im Puffer
                trace(l_trc);
                declare
                    l_resp lilam.JSON_OBJ_LILAM;
                begin
                    lilam.call_by_json('{"header":{"api_call":"FLUSH"},"params":{}}', l_resp);
                    check_that(l_run, l_key || ' CALL_BY_JSON FLUSH: SUCCESS',
                               instr(l_resp, '"status":"SUCCESS"') > 0, substr(l_resp, 1, 200));
                end;
                peek(l_prefix, l_key);
                check_that(l_run, l_key || ' CALL_BY_JSON FLUSH: vierter Trace sofort geschrieben (4)',
                           val(l_key, 'trc') = 4, val(l_key, 'trc'));
                check_that(l_run, l_key || ' nach FLUSH zaehlt der Prozess weiter (ACTION_COUNT 4)',
                           val(l_key, 'trccnt') = 4, val(l_key, 'trccnt'));
            end if;

            lilam.close_session(l_trc);
            lilam.close_session(l_evt);
            lilam.close_session(l_stp);
            lilam.close_session(l_bas);

            if l_ins then
                l_key := p_tag || '_R8';
                peek(l_prefix, l_key);
                check_that(l_run, l_key || ' nach CLOSE_SESSION: alle 4 Traces in LILAM_MON, Prozess geschlossen',
                           val(l_key, 'trc') = 4 and val(l_key, 'trcopen') = 0,
                           val(l_key, 'trc') || ' Traces / offen ' || val(l_key, 'trcopen'));
            end if;
        end;
    begin
        l_run := begin_run('RUECKSCHREIBUNG', 'INSESSION+SERVER', null, p_parent);
        run_mode(c_insession, 'IS');
        if p_manage then setup_servers(c_server, 1); end if;
        run_mode(c_server, 'SV');
        if p_manage then stop_all_servers; end if;
        check_that(l_run, 'R9 Keine internen LILAM-Fehler', internal_errors_since(run_started(l_run)) = 0,
                   internal_errors_since(run_started(l_run)));
        -- Testdaten nur bei Erfolg loeschen (sonst zur Analyse stehen lassen)
        if g_check_no > 0 then
            declare
                l_fail number;
            begin
                select count(*) into l_fail from lt_check where run_id = l_run and ok = 0;
                if l_fail = 0 then purge_prefix('LT_' || l_run || '_'); end if;
            end;
        end if;
        end_run(l_run);
        return l_run;
    exception
        when others then
            abort_run(l_run, p_manage, sqlerrm || ' ' || dbms_utility.format_error_backtrace);
            if p_manage then raise; end if;
            return l_run;
    end;

    ----------------------------------------------------------------------
    -- Speicher
    ----------------------------------------------------------------------
    -- PGA in Byte: eigene Session (p_module NULL) oder Summe aller Sessions mit passendem MODULE
    function pga_bytes(p_module varchar2 default null) return number is
        l_n number;
    begin
        if p_module is null then
            execute immediate 'select p.pga_used_mem from v$process p join v$session s on s.paddr = p.addr
                                where s.sid = sys_context(''userenv'', ''sid'')' into l_n;
        else
            execute immediate 'select sum(p.pga_used_mem) from v$session s join v$process p on p.addr = s.paddr
                                where s.module like :1' into l_n using p_module;
        end if;
        return l_n;
    exception when others then return null;
    end;

    function t_speicher(p_procs number default 5000, p_manage boolean default true, p_parent number default null) return number is
        -- Der PGA-Heap eines Servers waechst anfangs in 64-KB-Schritten und pendelt sich nach einigen
        -- tausend Prozessen ein; erst danach wird gemessen. Bloecke zu 1.000 Prozessen: 64 KB = 64 Byte je Prozess.
        c_warm    constant pls_integer := 2000;  -- Aufwaermen (Caches, Cursor, Tabellen-Pruefung, Heap)
        c_blocks  constant pls_integer := 5;     -- Messbloecke; bewertet wird der Median der Blockzuwaechse
        c_ops     constant pls_integer := 4;     -- je Prozess: c_ops x (info, trace, event, step)
        c_max_b   constant number      := 100;   -- erlaubtes PGA-Wachstum in Byte je Prozess (Median)
        c_workers constant varchar2(30) := 'LILAM_SERVER LT_S%';
        c_disp    constant varchar2(30) := 'LILAM_SERVER ' || c_disp_pipe;
        c_master  constant varchar2(30) := 'LT_SPM';   -- eigene Tabellen LT_SPM_PROC/_LOG/_MON fuer den Fallback
        l_run     number;
        l_prefix  varchar2(60);
        l_block   pls_integer := ceil(p_procs / c_blocks);

        procedure load(p_mode varchar2, p_tag varchar2, p_n pls_integer) is
            l_pid number;
        begin
            for p in 1 .. p_n loop
                l_pid := open_process(p_mode, l_prefix || '_' || p_tag);
                for o in 1 .. c_ops loop one_op(l_pid, 0, o); end loop;
                lilam.close_session(l_pid);
            end loop;
        end;

        -- warten, bis alle Logs geschrieben sind; danach kurze Ruhe (Server-Flush, Baseline-Abgleich)
        procedure settle(p_tag varchar2, p_expected number) is
            l_n number;
        begin
            l_n := wait_count(l_prefix || '_' || p_tag, 'LOG', p_expected, 60);
            if p_tag <> 'IS' then dbms_session.sleep(3); end if;
        end;

        -- Bewertung: Median der Zuwaechse je Block (Byte je Prozess).
        -- Ein einmaliger Sprung des Oracle-Heaps trifft nur einen Block, ein Leck dagegen jeden.
        procedure check_growth(p_name varchar2, p_vals sys.odcinumberlist, p_metric varchar2) is
            l_d   sys.odcinumberlist := sys.odcinumberlist();
            l_med number;
            l_txt varchar2(400);
        begin
            for i in 1 .. p_vals.count loop
                if p_vals(i) is null then
                    check_that(l_run, p_name, false, 'keine PGA-Werte (Grants aus _COMMON/00_grants_als_sys.sql fehlen)');
                    return;
                end if;
            end loop;
            for i in 2 .. p_vals.count loop
                l_d.extend; l_d(l_d.count) := round((p_vals(i) - p_vals(i - 1)) / l_block);
                l_txt := l_txt || case when i > 2 then ', ' end || l_d(l_d.count);
            end loop;
            select median(column_value) into l_med from table(l_d);
            metric(l_run, p_metric, l_med, 'B/Prozess');
            check_that(l_run, p_name || ' (Median max. ' || c_max_b || ' Byte je Prozess)', l_med <= c_max_b,
                       'Median ' || l_med || ' B; je Block ' || l_txt || '; ' || round(p_vals(1) / 1024) || ' -> '
                       || round(p_vals(p_vals.count) / 1024) || ' KB');
        end;

        -- Speichermessung eines Modus: Aufwaermen, dann c_blocks Bloecke mit je l_block Prozessen
        procedure run_mem(p_mode varchar2, p_tag varchar2) is
            l_self  sys.odcinumberlist := sys.odcinumberlist();
            l_work  sys.odcinumberlist := sys.odcinumberlist();
            l_disp  sys.odcinumberlist := sys.odcinumberlist();
            l_total pls_integer := c_warm + c_blocks * l_block;
            l_n     number;
            l_label varchar2(10) := p_tag || ' ';

            procedure snap is
            begin
                l_self.extend; l_self(l_self.count) := pga_bytes;
                l_work.extend; l_work(l_work.count) := pga_bytes(c_workers);
                l_disp.extend; l_disp(l_disp.count) := pga_bytes(c_disp);
            end;
        begin
            load(p_mode, p_tag, c_warm);
            settle(p_tag, c_warm * c_ops);
            snap;
            for b in 1 .. c_blocks loop
                load(p_mode, p_tag, l_block);
                settle(p_tag, (c_warm + b * l_block) * c_ops);
                snap;
            end loop;

            l_n := count_lilam(l_prefix || '_' || p_tag, 'LOG');
            check_that(l_run, l_label || 'Alle Logs geschrieben', l_n = l_total * c_ops, l_n || '/' || l_total * c_ops);
            l_n := count_lilam(l_prefix || '_' || p_tag, 'PROC_CLOSED');
            check_that(l_run, l_label || 'Alle Prozesse geschlossen', l_n = l_total, l_n || '/' || l_total);

            if p_mode = c_insession then
                check_growth(l_label || 'PGA der Session', l_self, lower(p_tag) || '_session_b');
            else
                check_growth(l_label || 'PGA des Clients', l_self, lower(p_tag) || '_client_b');
                check_growth(l_label || 'PGA der Worker', l_work, lower(p_tag) || '_worker_b');
                if p_mode = c_dispatcher then
                    check_growth(l_label || 'PGA des Dispatchers', l_disp, lower(p_tag) || '_dispatcher_b');
                end if;
            end if;
        end;

        -- Fallback: eine Zeile verletzt einen Check-Constraint; sie wird uebersprungen und protokolliert,
        -- die uebrigen Zeilen desselben Flushs werden geschrieben
        procedure run_fallback(p_mode varchar2, p_tag varchar2) is
            l_pid   number;
            l_ts    timestamp := systimestamp;
            l_ok    number;
            l_bad   number;
            l_err   number;
            l_wait  number := 0;
            l_label varchar2(10) := p_tag || ' ';
        begin
            if p_mode = c_insession then
                l_pid := lilam.new_session(p_processName => l_prefix || '_F' || p_tag, p_logLevel => lilam.logLevelInfo,
                                           p_tabNameMaster => c_master);
            else
                l_pid := lilam.server_new_session(p_processName => l_prefix || '_F' || p_tag, p_groupName => c_group,
                                                  p_logLevel => lilam.logLevelInfo, p_tabNameMaster => c_master);
            end if;

            -- Check-Constraint einmalig anlegen (die Tabelle legt LILAM beim ersten NEW_SESSION an)
            select count(*) into l_ok from user_constraints where constraint_name = c_master || '_LOG_CK';
            if l_ok = 0 then
                execute immediate 'alter table ' || c_master || '_LOG add constraint ' || c_master
                                  || '_LOG_CK check (info is null or info <> ''LT_SPM_BAD'')';
            end if;

            lilam.info(l_pid, 'LT_SPM_OK_1');
            lilam.info(l_pid, 'LT_SPM_OK_2');
            lilam.info(l_pid, 'LT_SPM_BAD');
            lilam.info(l_pid, 'LT_SPM_OK_4');
            lilam.info(l_pid, 'LT_SPM_OK_5');
            lilam.close_session(l_pid);

            loop
                execute immediate 'select count(*) from ' || c_master || '_LOG where process_id = :1 and info like ''LT\_SPM\_OK%'' escape ''\'''
                    into l_ok using l_pid;
                exit when l_ok >= 4 or l_wait >= 30;
                dbms_session.sleep(0.5); l_wait := l_wait + 0.5;
            end loop;
            execute immediate 'select count(*) from ' || c_master || '_LOG where process_id = :1 and info = ''LT_SPM_BAD'''
                into l_bad using l_pid;
            begin
                execute immediate 'select count(*) from lilam_log_internal where log_timestamp >= :1 and error_code = -2290
                                     and log_operation like ''row % skipped''' into l_err using l_ts;
            exception when others then l_err := 0;
            end;

            check_that(l_run, l_label || 'Fallback: gueltige Zeilen geschrieben', l_ok = 4, l_ok || '/4');
            check_that(l_run, l_label || 'Fallback: fehlerhafte Zeile uebersprungen', l_bad = 0, 'ist ' || l_bad);
            check_that(l_run, l_label || 'Fallback: Fehler einmal protokolliert (ORA-02290, row skipped)', l_err = 1, l_err || ' Eintraege');
        end;
    begin
        l_run := begin_run('SPEICHER', 'INSESSION+SERVER+DISPATCHER', 'warm=' || c_warm || ' procs=' || c_blocks || 'x' || l_block
                           || ' ops=' || c_ops || ' max=' || c_max_b || ' B (Median)', p_parent);
        l_prefix := 'LT_' || l_run || '_SPM';

        run_mem(c_insession, 'IS');
        run_fallback(c_insession, 'IS');

        if p_manage then setup_servers(c_dispatcher, 1); end if;
        run_mem(c_server, 'SV');
        run_fallback(c_server, 'SV');
        run_mem(c_dispatcher, 'DP');   -- zuletzt: setzt den Dispatcher fuer diese Session
        if p_manage then stop_all_servers; end if;

        -- erwartet: genau die zwei Fallback-Eintraege, sonst nichts
        declare
            l_n number;
        begin
            execute immediate 'select count(*) from lilam_log_internal where log_timestamp >= :1
                                 and not (error_code = -2290 and log_operation like ''row % skipped'')'
                into l_n using run_started(l_run);
            check_that(l_run, 'Keine weiteren internen LILAM-Fehler', l_n = 0, l_n || ' Eintraege');
        exception
            when others then check_that(l_run, 'Keine weiteren internen LILAM-Fehler', true, 'keine Tabelle');
        end;
        end_run(l_run);
        return l_run;
    exception
        when others then
            abort_run(l_run, p_manage, sqlerrm || ' ' || dbms_utility.format_error_backtrace);
            if p_manage then raise; end if;
            return l_run;
    end;

    ----------------------------------------------------------------------
    -- Lastspitze
    ----------------------------------------------------------------------
    procedure burst(p_run_id number, p_client number, p_mode varchar2, p_proc_name varchar2, p_end_ts timestamp) is
        l_pid number;
        l_ops number := 0;
        l_t0  timestamp;
    begin
        joblog(p_run_id, p_client, 'START', p_mode || ' burst bis ' || to_char(p_end_ts, 'HH24:MI:SS'));
        l_pid := open_process(p_mode, p_proc_name);
        l_t0 := systimestamp;
        while systimestamp < p_end_ts loop
            l_ops := l_ops + 1;
            one_op(l_pid, p_client, l_ops);
        end loop;
        lilam.close_session(l_pid);
        metric(p_run_id, 'client_ops', l_ops, 'ops', p_client);
        metric(p_run_id, 'client_api_calls', l_ops * 5, 'calls', p_client);
        metric(p_run_id, 'client_elapsed_ms', ms_since(l_t0), 'ms', p_client);
        joblog(p_run_id, p_client, 'END', 'ok');
    exception
        when others then
            joblog(p_run_id, p_client, 'ERROR', sqlerrm || ' | ' || dbms_utility.format_error_backtrace);
    end;

    procedure probe(p_run_id number, p_mode varchar2, p_proc_name varchar2, p_ops number) is
        l_pid number;
        l_t0  timestamp := systimestamp;
    begin
        l_pid := open_process(p_mode, p_proc_name);
        metric(p_run_id, 'probe_new_session_ms', ms_since(l_t0), 'ms');
        for i in 1 .. p_ops loop
            one_op(l_pid, 0, i);
        end loop;
        lilam.close_session(l_pid);
        metric(p_run_id, 'probe_ms', ms_since(l_t0), 'ms');
    exception
        when others then
            joblog(p_run_id, 0, 'ERROR', 'Probe: ' || sqlerrm || ' | ' || dbms_utility.format_error_backtrace);
    end;

    function t_lastspitze(p_mode varchar2, p_clients number default 6, p_seconds number default 30,
                          p_manage boolean default true, p_max_wait number default 300, p_parent number default null) return number is
        c_probe_ops constant number := 100;
        l_run    number;
        l_burst  varchar2(60);
        l_probe  varchar2(60);
        l_end    timestamp;
        l_ops    number;
        l_ms     number;
        l_n      number;
        l_t      timestamp;
    begin
        l_run := begin_run('LASTSPITZE', p_mode, 'clients=' || p_clients || ' seconds=' || p_seconds, p_parent);
        l_burst := 'LT_' || l_run || '_SPITZE';
        l_probe := 'LT_' || l_run || '_PROBE';
        if p_mode = c_insession then
            raise_application_error(-20000, 'LASTSPITZE ist nur im Decoupled-Mode sinnvoll');
        end if;
        if p_manage then setup_servers(p_mode, 2); end if;

        -- Spitze: alle Clients senden bis l_end ohne Pause (3 s Vorlauf fuer den Start der Jobs)
        l_end := systimestamp + numtodsinterval(p_seconds + 3, 'SECOND');
        l_t := systimestamp;
        for c in 1 .. p_clients loop
            run_job('LT_C' || l_run || '_' || c,
              'begin lt.burst(' || l_run || ', ' || c || ', ''' || p_mode || ''', ''' || l_burst || ''', '
              || 'to_timestamp(''' || to_char(l_end, 'YYYY-MM-DD HH24:MI:SS.FF3') || ''', ''YYYY-MM-DD HH24:MI:SS.FF3'')); end;');
        end loop;
        check_that(l_run, 'Client-Jobs beendet', wait_jobs('LT_C' || l_run || '_', p_seconds + c_job_wait));
        throughput_metrics(l_run, p_clients, false);
        select nvl(sum(value), 0) into l_ops from lt_metric where run_id = l_run and metric = 'client_ops';

        -- Erholung 1: trotz Ueberlast kommen alle Daten vollstaendig an
        for w in (select column_value what from table(sys.odcivarchar2list('LOG', 'TRACE', 'EVENT'))) loop
            l_ms := wait_count(l_burst, w.what, l_ops, p_max_wait);
            l_n  := count_lilam(l_burst, w.what);
            check_that(l_run, 'Lastspitze: Anzahl ' || w.what || ' = gesendete Operationen', l_n = l_ops, l_n || '/' || l_ops);
            if l_ms >= 0 then metric(l_run, 'drain_' || lower(w.what) || '_ms', l_ms, 'ms'); end if;
        end loop;
        l_n := count_lilam(l_burst, 'PROC_CLOSED');
        check_that(l_run, 'Lastspitze: alle Prozesse geschlossen', l_n = p_clients, l_n || '/' || p_clients);

        -- Erholung 2: ein neuer Prozess arbeitet danach wieder normal (eigene Session)
        run_job('LT_CP' || l_run, 'begin lt.probe(' || l_run || ', ''' || p_mode || ''', ''' || l_probe || ''', ' || c_probe_ops || '); end;');
        check_that(l_run, 'Probe nach der Spitze beendet', wait_jobs('LT_CP' || l_run, 120));
        select max(value) into l_ms from lt_metric where run_id = l_run and metric = 'probe_ms';
        check_that(l_run, 'Probe: neuer Prozess mit ' || c_probe_ops || ' Operationen < 3 s', nvl(l_ms, 99999) < 3000, l_ms || ' ms');
        l_ms := wait_count(l_probe, 'LOG', c_probe_ops, 30);
        check_that(l_run, 'Probe: Daten innerhalb 30 s persistiert', l_ms >= 0, l_ms || ' ms');

        l_n := count_lilam(l_burst, 'ROUTES') + count_lilam(l_probe, 'ROUTES');
        check_that(l_run, 'Keine Prozess-Routen uebrig', l_n = 0, 'ist ' || l_n);
        select count(*) into l_n from lt_joblog where run_id = l_run and phase = 'ERROR';
        check_that(l_run, 'Keine Fehler in den Client-Jobs', l_n = 0, l_n || ' Fehler');
        l_n := internal_errors_since(run_started(l_run));
        check_that(l_run, 'Keine internen LILAM-Fehler', l_n = 0, l_n || ' Eintraege');

        if p_manage then stop_all_servers; end if;
        end_run(l_run);
        return l_run;
    exception
        when others then
            abort_run(l_run, p_manage, sqlerrm || ' ' || dbms_utility.format_error_backtrace);
            if p_manage then raise; end if;
            return l_run;
    end;

    ----------------------------------------------------------------------
    -- REGELN: Rules Engine im SERVER- und INSESSION-Modus (Laden, Operatoren, Alerts)
    -- Rule Set LT_REGELN, Versionen 1 (vollstaendig), 2 (klein), 3-6 ungueltig.
    -- #P# wird durch den Prozess-Praefix des Laufs ersetzt (Prozess-Regeln haengen am Prozessnamen).
    -- INSESSION nutzt eigene Gruppen je Lauf: die Session prueft nur Name und Version des aktiven
    -- Rule Sets, ein zweiter Lauf in derselben DB-Session saehe sonst die Regeln mit dem alten Praefix.
    ----------------------------------------------------------------------
    function t_regeln(p_manage boolean default true, p_parent number default null) return number is
        c_set     constant varchar2(30) := 'LT_REGELN';
        c_handler constant varchar2(30) := 'LT_REGELN_ALERT';
        l_run     number;
        l_p       varchar2(60);   -- Prozess-Praefix, z.B. LT_700_RG
        l_s       varchar2(10);   -- Zusatz im Prozessnamen je Modus: SERVER leer, INSESSION '_IS'
        l_is_grp  varchar2(50);   -- INSESSION-Gruppe fuer die Szenarien (Rule Set v1 mit Praefix l_p || '_IS')
        l_is_grp2 varchar2(50);   -- INSESSION-Gruppe fuer Versionswechsel, ungueltiges und fehlendes Rule Set
        l_pid     number;
        l_ok      boolean;
        l_msg     varchar2(1800);
        l_st      integer;
        l_n       number;
        l_t       timestamp;
        l_pipes   sys.odcivarchar2list;

        -- eine Regel als JSON
        function r(p_id varchar2, p_trig varchar2, p_action varchar2, p_op varchar2, p_val varchar2,
                   p_ctx varchar2 default null, p_thr number default 0, p_handler varchar2 default c_handler) return varchar2 is
        begin
            return '{"id":"' || p_id || '","trigger_type":"' || p_trig || '"'
                || case when p_action is not null then ',"action":"' || p_action || '"' end
                || case when p_ctx is not null then ',"context":"' || p_ctx || '"' end
                || ',"condition":{"operator":"' || p_op || '","value":"' || p_val || '"}'
                || ',"alert":{' || case when p_handler is not null then '"handler":"' || p_handler || '",' end
                || '"severity":"WARN","throttle_seconds":' || p_thr || '}}';
        end;

        function rule_set(p_ver number, p_rules clob, p_pp varchar2) return clob is
        begin
            return '{"header":{"rule_set":"' || c_set || '","rule_set_version":' || p_ver
                || ',"description":"Test FEATURES/REGELN"},"rules":[' || replace(p_rules, '#P#', p_pp) || ']}';
        end;

        -- p_pp: Prozess-Praefix fuer #P# (INSESSION: l_p || '_IS')
        procedure ins(p_ver number, p_rules clob, p_group varchar2 default c_group, p_pp varchar2 default null) is
            l_json clob := rule_set(p_ver, p_rules, nvl(p_pp, l_p));
        begin
            execute immediate 'insert into lilam_rules(group_name, set_name, version, is_active, created, author, rule_set)
                               values (:1, :2, :3, 0, systimestamp, ''LT'', :4)' using p_group, c_set, p_ver, l_json;
        end;

        procedure put_rules is
            l clob;
        begin
            -- Version 1: alle Szenarien
            l :=          r('VG-01', 'MARK_EVENT',  'RG_B',  'PRECEDED_BY', 'RG_A');
            l := l || ',' || r('VG-02', 'MARK_EVENT',  'RG_B2', 'PRECEDED_BY', 'RG_A|C1');
            l := l || ',' || r('VG-03', 'MARK_EVENT',  'RG_D',  'PRECEDED_BY_WITHIN_SECS', 'RG_C|1');
            l := l || ',' || r('VG-04', 'TRACE_START', 'RG_T',  'PRECEDED_BY', 'RG_A');
            l := l || ',' || r('NF-01', 'MARK_EVENT',  'RG_NF_B', 'PRECEDED_BY_WITHIN_SECS', 'RG_NF_A|1');
            l := l || ',' || r('GP-01', 'MARK_EVENT',  'RG_G',  'MAX_GAP_SECONDS', '0.8');
            l := l || ',' || r('GP-02', 'TRACE_START', 'RG_GT', 'MAX_GAP_SECONDS', '0.8');
            l := l || ',' || r('DU-01', 'TRACE_STOP',  'RG_DT', 'MAX_DURATION_MS', '100');
            l := l || ',' || r('DU-02', 'MARK_EVENT',  'RG_DE', 'MAX_DURATION_MS', '500');
            l := l || ',' || r('OC-01', 'MARK_EVENT',  'RG_OC', 'MAX_OCCURRENCE', '3');
            l := l || ',' || r('AV-01', 'TRACE_STOP',  'RG_AV', 'AVG_DEVIATION_PCT', '50|3|0.5');
            l := l || ',' || r('PR-01', 'PROCESS_START',  '#P#_PS', 'ON_START', '');
            l := l || ',' || r('PR-02', 'PROCESS_UPDATE', '#P#_ST', 'STATUS_EQUALS', '3');
            l := l || ',' || r('PR-03', 'PROCESS_UPDATE', '#P#_IN', 'INFO_CONTAINS', 'kaputt');
            l := l || ',' || r('PR-04', 'PROCESS_STOP',   '#P#_SD', 'STEPS_LEFT_HIGH', '2');
            l := l || ',' || r('PR-05', 'PROCESS_STOP',   '#P#_SD', 'SUCCESS_RATE_LOW', '80');
            l := l || ',' || r('PR-06', 'PROCESS_UPDATE', '#P#_SD', 'MAX_OCCURRENCE', '3');
            l := l || ',' || r('PR-07', 'PROCESS_STOP',   '#P#_RT', 'MAX_RUNTIME_EXCEEDED', '500');
            l := l || ',' || r('PR-08', 'PROCESS_UPDATE', '#P#_RT', 'RUNTIME_EXCEEDED', '500');
            l := l || ',' || r('LG-01', 'LOGGING', 'LOGGING', 'SEVERITY', 'ERROR');
            l := l || ',' || r('LG-02', 'LOGGING', null, 'SEVERITY', 'WARN');
            l := l || ',' || r('KX-01', 'MARK_EVENT',  'RG_K',  'ON_EVENT', '', 'C1');
            l := l || ',' || r('KX-02', 'MARK_EVENT',  'RG_K',  'ON_EVENT', '');
            l := l || ',' || r('TF-01', 'TRACE_STOP',  'RG_TF', 'ON_STOP', '');
            l := l || ',' || r('TH-01', 'MARK_EVENT',  'RG_TH', 'ON_EVENT', '', null, 2);
            l := l || ',' || r('L-01',  'MARK_EVENT',  'RG_L',  'ON_EVENT', '');
            -- vorher: Rule Sets des Tests entfernen, Testgruppe ohne aktives Rule Set
            execute immediate 'delete from lilam_rules where set_name = :1' using c_set;
            execute immediate 'update lilam_rules set is_active = 0 where upper(group_name) = :1 and is_active = 1' using c_group;
            ins(1, l);
            -- Version 2: klein, ersetzt Version 1 vollstaendig
            ins(2, r('V2-01', 'MARK_EVENT', 'RG_V2', 'ON_EVENT', ''));
            -- Versionen 3-6: ungueltig (fehlender Handler, unbekannter Operator, Operator passt nicht zum Trigger, leere Action)
            ins(3, r('X3-01', 'MARK_EVENT', 'RG_V2', 'ON_EVENT', '', null, 0, null));
            ins(4, r('X4-01', 'MARK_EVENT', 'RG_V2', 'PRECEDED_BY_WITHIN_MS', 'RG_A|1000'));
            ins(5, r('X5-01', 'TRACE_STOP', 'RG_V2', 'MAX_GAP_SECONDS', '1'));
            -- Version 6: ungueltig, leere "action" (Beispiel SEQ-009 der Analyse; r() laesst eine leere Action weg)
            ins(6, '{"id":"X6-01","trigger_type":"MARK_EVENT","action":"","condition":{"operator":"ON_EVENT","value":""}'
                || ',"alert":{"handler":"' || c_handler || '","severity":"WARN","throttle_seconds":0}}');
            -- Gruppe ohne Server: Aktivieren ist kein Fehler
            ins(1, r('E1-01', 'MARK_EVENT', 'RG_E', 'ON_EVENT', ''), 'LT_LEER');
            -- INSESSION: Szenarien (Version 1 mit Praefix der INSESSION-Prozesse) und IS-03..IS-05 (Versionen 1, 2, 6)
            ins(1, l, l_is_grp, l_p || '_IS');
            ins(1, l, l_is_grp2, l_p || '_IS');
            ins(2, r('V2-01', 'MARK_EVENT', 'RG_V2', 'ON_EVENT', ''), l_is_grp2);
            ins(6, '{"id":"X6-01","trigger_type":"MARK_EVENT","action":"","condition":{"operator":"ON_EVENT","value":""}'
                || ',"alert":{"handler":"' || c_handler || '","severity":"WARN","throttle_seconds":0}}', l_is_grp2);
            commit;
        end;

        function alerts(p_proc varchar2, p_rule varchar2) return number is
            l_cnt number;
        begin
            execute immediate 'select count(*) from lilam_alerts where process_name = :1 and rule_id = :2 and rule_set_name = :3'
               into l_cnt using l_p || l_s || p_proc, p_rule, c_set;
            return l_cnt;
        end;

        procedure expect(p_proc varchar2, p_rule varchar2, p_expected number, p_text varchar2) is
            l_cnt number := alerts(p_proc, p_rule);
        begin
            check_that(l_run, case when l_s is not null then 'IS ' end || p_rule || ' ' || p_text, l_cnt = p_expected,
                       'Alerts ' || l_cnt || ', erwartet ' || p_expected);
        end;

        -- SERVER: Server der Gruppe LT; INSESSION: Gruppe l_is_grp, bewusst klein geschrieben (IS-02)
        function proc(p_suffix varchar2, p_steps number default null) return number is
        begin
            if l_s is null then
                return lilam.server_new_session(l_p || p_suffix, c_group, lilam.logLevelInfo, p_procStepsToDo => p_steps);
            end if;
            return lilam.new_session(p_processName => l_p || l_s || p_suffix, p_logLevel => lilam.logLevelInfo,
                                     p_procStepsToDo => p_steps, p_groupName => lower(l_is_grp));
        end;

        -- aktives Rule Set einer Gruppe, z.B. 'LT_REGELN v1'
        function active(p_group varchar2 default c_group) return varchar2 is
            l_name varchar2(50);
            l_ver  number;
        begin
            execute immediate 'select set_name, version from lilam_rules where upper(group_name) = upper(:1) and is_active = 1'
               into l_name, l_ver using p_group;
            return l_name || ' v' || l_ver;
        exception
            when no_data_found then return 'keines';
        end;

        -- Rule Sets des Tests entfernen und die Testgruppe ohne aktives Rule Set lassen
        procedure reset_rules is
        begin
            execute immediate 'delete from lilam_rules where set_name = :1' using c_set;
            execute immediate 'update lilam_rules set is_active = 0 where upper(group_name) = :1 and is_active = 1' using c_group;
            commit;
        end;

        procedure update_rules(p_ver number) is
        begin
            lilam.server_update_rules(c_group, c_set, p_ver);
            dbms_session.sleep(1);
        end;

        -- SERVER_UPDATE_RULES mit erwarteter Ablehnung: 1 = abgelehnt mit NUM_ERR_RULE_SET
        function rejected(p_group varchar2, p_ver number) return pls_integer is
        begin
            lilam.server_update_rules(p_group, c_set, p_ver);
            return 0;
        exception
            when others then
                dbms_output.put_line('    abgelehnt: ' || substr(sqlerrm, 1, 150));
                return case when sqlcode = lilam.NUM_ERR_RULE_SET then 1 else 0 end;
        end;

    begin
        l_run := begin_run('REGELN', 'SERVER+INSESSION', 'Rule Set ' || c_set || ', Server LT_S1 und LT_S2', p_parent);
        l_p   := 'LT_' || l_run || '_RG';
        l_is_grp  := 'LT_RG_IS_' || l_run;
        l_is_grp2 := 'LT_RG_IS2_' || l_run;
        put_rules;
        if p_manage then
            stop_all_servers;
            setup_servers(c_server, 2);
        end if;

        -- ---------------------------------------------------------------
        -- L1: Laden per SERVER_UPDATE_RULES fuer die ganze Gruppe
        -- ---------------------------------------------------------------
        update_rules(1);
        -- ob beide Server die Regeln geladen haben, zeigen die folgenden Szenarien (Prozesse verteilen sich auf beide)
        check_that(l_run, 'L1 SERVER_UPDATE_RULES: Rule Set fuer die Gruppe aktiv', active = c_set || ' v1', active);

        -- INSESSION: Rule Set der Szenario-Gruppe aktivieren (Gruppe ohne Server ist kein Fehler)
        lilam.server_update_rules(l_is_grp, c_set, 1);

        -- Alert-Signal: diese Session lauscht auf den Handler
        dbms_alert.register(c_handler);

        -- ---------------------------------------------------------------
        -- Szenarien bis einschliesslich Drosselung in beiden Modi:
        -- 1. SERVER (Prozessnamen l_p || '_VG' ...), 2. INSESSION (l_p || '_IS_VG' ..., Pruefungen mit Praefix "IS").
        -- Die Erwartungswerte sind in beiden Modi gleich. (Bloecke in der Schleife bewusst nicht eingerueckt.)
        -- ---------------------------------------------------------------
        for m in 1 .. 2 loop
        l_s := case when m = 2 then '_IS' end;

        -- ---------------------------------------------------------------
        -- Vorgaenger (nur Events und Traces zaehlen)
        -- ---------------------------------------------------------------
        l_pid := proc('_VG');
        lilam.mark_event(l_pid, 'RG_A', 'C1'); lilam.mark_event(l_pid, 'RG_B');                       -- 0: Kontext des Vorgaengers egal
        lilam.mark_event(l_pid, 'RG_A'); lilam.info(l_pid, 'dazwischen'); lilam.mark_event(l_pid, 'RG_B'); -- 0: Log ist kein Vorgaenger
        lilam.mark_event(l_pid, 'RG_X'); lilam.mark_event(l_pid, 'RG_B');                             -- 1: falscher Vorgaenger
        lilam.mark_event(l_pid, 'RG_A', 'C1'); lilam.mark_event(l_pid, 'RG_B2');                      -- 0
        lilam.mark_event(l_pid, 'RG_A', 'C2'); lilam.mark_event(l_pid, 'RG_B2');                      -- 1: falscher Kontext
        lilam.mark_event(l_pid, 'RG_C'); lilam.mark_event(l_pid, 'RG_D');                             -- 0
        lilam.mark_event(l_pid, 'RG_C'); dbms_session.sleep(1.3); lilam.mark_event(l_pid, 'RG_D');    -- 1: zu spaet
        lilam.mark_event(l_pid, 'RG_X'); lilam.mark_event(l_pid, 'RG_D');                             -- 1: falscher Vorgaenger
        lilam.mark_event(l_pid, 'RG_A'); lilam.trace_start(l_pid, 'RG_T'); lilam.trace_stop(l_pid, 'RG_T');  -- 0
        lilam.mark_event(l_pid, 'RG_X'); lilam.trace_start(l_pid, 'RG_T'); lilam.trace_stop(l_pid, 'RG_T');  -- 1
        lilam.close_session(l_pid);
        expect('_VG', 'VG-01', 1, 'PRECEDED_BY: Kontext egal, Log kein Vorgaenger, falscher Vorgaenger');
        expect('_VG', 'VG-02', 1, 'PRECEDED_BY mit Kontext RG_A|C1');
        expect('_VG', 'VG-03', 2, 'PRECEDED_BY_WITHIN_SECS: zu spaet und falscher Vorgaenger');
        expect('_VG', 'VG-04', 1, 'PRECEDED_BY bei TRACE_START');

        -- ---------------------------------------------------------------
        -- Nachfolger: "B folgt A innerhalb 1 s" (Pruefung beim Eintreffen von B)
        -- ---------------------------------------------------------------
        l_pid := proc('_NF');
        lilam.mark_event(l_pid, 'RG_NF_A'); lilam.mark_event(l_pid, 'RG_NF_B');                          -- 0
        lilam.mark_event(l_pid, 'RG_NF_A'); dbms_session.sleep(1.3); lilam.mark_event(l_pid, 'RG_NF_B'); -- 1
        lilam.close_session(l_pid);
        expect('_NF', 'NF-01', 1, 'Nachfolger zu spaet');
        dbms_output.put_line('    Hinweis: ein ganz ausbleibender Nachfolger wird nicht erkannt (keine zeitgesteuerte Pruefung)');

        -- ---------------------------------------------------------------
        -- Abstand, Dauer, Haeufigkeit, Abweichung
        -- ---------------------------------------------------------------
        l_pid := proc('_MON');
        lilam.mark_event(l_pid, 'RG_G'); lilam.mark_event(l_pid, 'RG_G');                           -- 0
        dbms_session.sleep(1.2); lilam.mark_event(l_pid, 'RG_G');                                   -- 1
        lilam.trace_start(l_pid, 'RG_GT'); lilam.trace_stop(l_pid, 'RG_GT');
        lilam.trace_start(l_pid, 'RG_GT'); lilam.trace_stop(l_pid, 'RG_GT');                        -- 0
        dbms_session.sleep(1.2); lilam.trace_start(l_pid, 'RG_GT'); lilam.trace_stop(l_pid, 'RG_GT'); -- 1
        lilam.trace_start(l_pid, 'RG_DT'); dbms_session.sleep(0.01); lilam.trace_stop(l_pid, 'RG_DT'); -- 0
        lilam.trace_start(l_pid, 'RG_DT'); dbms_session.sleep(0.25); lilam.trace_stop(l_pid, 'RG_DT'); -- 1
        lilam.mark_event(l_pid, 'RG_DE'); lilam.mark_event(l_pid, 'RG_DE');                         -- 0
        dbms_session.sleep(0.7); lilam.mark_event(l_pid, 'RG_DE');                                  -- 1
        for i in 1 .. 5 loop lilam.mark_event(l_pid, 'RG_OC'); end loop;                            -- 2 (4. und 5.)
        for i in 1 .. 4 loop
            lilam.trace_start(l_pid, 'RG_AV'); dbms_session.sleep(0.1); lilam.trace_stop(l_pid, 'RG_AV');
        end loop;
        lilam.trace_start(l_pid, 'RG_AV'); dbms_session.sleep(0.11); lilam.trace_stop(l_pid, 'RG_AV');  -- 0: +10 %
        lilam.trace_start(l_pid, 'RG_AV'); dbms_session.sleep(0.4);  lilam.trace_stop(l_pid, 'RG_AV');  -- 1: +300 %
        lilam.close_session(l_pid);
        expect('_MON', 'GP-01', 1, 'MAX_GAP_SECONDS 0.8 bei Events (Dezimalpunkt)');
        expect('_MON', 'GP-02', 1, 'MAX_GAP_SECONDS 0.8 bei TRACE_START');
        expect('_MON', 'DU-01', 1, 'MAX_DURATION_MS bei TRACE_STOP');
        expect('_MON', 'DU-02', 1, 'MAX_DURATION_MS bei Events (Abstand)');
        expect('_MON', 'OC-01', 2, 'MAX_OCCURRENCE 3 bei 5 Events');
        expect('_MON', 'AV-01', 1, 'AVG_DEVIATION_PCT 50 % nach Warm-up');

        -- ---------------------------------------------------------------
        -- Prozess-Regeln (je ein Prozess, die Werte bleiben im Prozess stehen)
        -- ---------------------------------------------------------------
        l_pid := proc('_PS'); lilam.close_session(l_pid);
        expect('_PS', 'PR-01', 1, 'ON_START bei PROCESS_START');

        l_pid := proc('_ST');
        lilam.set_process_status(l_pid, 2); lilam.set_process_status(l_pid, 3);
        lilam.close_session(l_pid);
        expect('_ST', 'PR-02', 1, 'STATUS_EQUALS 3');

        l_pid := proc('_IN');
        lilam.set_process_status(l_pid, 1, 'alles gut'); lilam.set_process_status(l_pid, 1, 'Teil KAPUTT');
        lilam.close_session(l_pid);
        expect('_IN', 'PR-03', 1, 'INFO_CONTAINS (ohne Gross/Klein)');

        l_pid := proc('_SD', 10);
        for i in 1 .. 5 loop lilam.proc_step_done(l_pid); end loop;
        lilam.close_session(l_pid, p_procStepsDone => 7);
        expect('_SD', 'PR-06', 2, 'MAX_OCCURRENCE 3 bei 5 Schritten');
        expect('_SD', 'PR-04', 1, 'STEPS_LEFT_HIGH mit Endstand aus CLOSE_SESSION (7 von 10)');
        expect('_SD', 'PR-05', 1, 'SUCCESS_RATE_LOW 80 % mit Endstand 70 %');

        l_pid := proc('_RT');
        lilam.set_process_status(l_pid, 1);                                                 -- 0
        dbms_session.sleep(0.7); lilam.set_process_status(l_pid, 1);                        -- 1
        lilam.close_session(l_pid);
        expect('_RT', 'PR-08', 1, 'RUNTIME_EXCEEDED 500 ms (laufender Prozess)');
        expect('_RT', 'PR-07', 1, 'MAX_RUNTIME_EXCEEDED 500 ms (bei PROCESS_STOP)');

        -- ---------------------------------------------------------------
        -- Log-Regeln: zwei SEVERITY-Regeln, viele nicht passende Logs
        -- ---------------------------------------------------------------
        l_pid := proc('_LG');
        for i in 1 .. 10 loop lilam.info(l_pid, 'info ' || i); end loop;
        lilam.warn(l_pid, 'Warnung'); lilam.error(l_pid, 'Fehler');
        lilam.close_session(l_pid);
        expect('_LG', 'LG-01', 1, 'SEVERITY ERROR');
        expect('_LG', 'LG-02', 1, 'SEVERITY WARN als zweite Log-Regel (ohne "action")');

        -- ---------------------------------------------------------------
        -- Kontext- und Action-Regel, Trigger-Filter, Drosselung
        -- ---------------------------------------------------------------
        l_pid := proc('_KX');
        lilam.mark_event(l_pid, 'RG_K', 'C1'); lilam.mark_event(l_pid, 'RG_K', 'C2');
        lilam.mark_event(l_pid, 'RG_TF'); lilam.trace_start(l_pid, 'RG_TF'); lilam.trace_stop(l_pid, 'RG_TF');
        for i in 1 .. 3 loop lilam.mark_event(l_pid, 'RG_TH'); end loop;
        dbms_session.sleep(2.5); lilam.mark_event(l_pid, 'RG_TH');
        lilam.close_session(l_pid);
        expect('_KX', 'KX-01', 1, 'Kontext-Regel nur fuer C1');
        expect('_KX', 'KX-02', 2, 'Action-Regel zusaetzlich fuer alle Kontexte');
        expect('_KX', 'TF-01', 1, 'Trigger-Filter: nur TRACE_STOP, kein MARK_EVENT');
        expect('_KX', 'TH-01', 2, 'Drosselung 2 s: 3 Events, Pause, 1 Event');

        end loop;
        l_s := null;

        -- ---------------------------------------------------------------
        -- Alert-Zeile und Signal
        -- ---------------------------------------------------------------
        execute immediate 'select count(*) from lilam_alerts where process_name = :1 and rule_id = ''PR-02''
                              and rule_set_name = :2 and rule_set_version = 1 and handler_type = :3 and alert_severity = ''WARN''
                              and status = ''PENDING'' and process_id is not null and action_name = :4
                              and master_table_name = ''LILAM_PROC'' and monitor_table_name = ''LILAM_MON'' and logging_table_name = ''LILAM_LOG'''
            into l_n using l_p || '_ST', c_set, c_handler, l_p || '_ST';
        check_that(l_run, 'A1 Alert-Zeile vollstaendig (Rule Set, Version, Handler, Severity, Tabellen, PENDING)', l_n = 1, l_n);
        dbms_alert.waitone(c_handler, l_msg, l_st, 2);
        if l_st = 0 then
            execute immediate 'select count(*) from lilam_alerts where alert_id = :1 and rule_set_name = :2'
               into l_n using json_value(l_msg, '$.alert_id' returning number), c_set;
        else
            l_n := 0;
        end if;
        check_that(l_run, 'A2 DBMS_ALERT-Signal mit gueltiger alert_id', l_st = 0 and l_n = 1,
                   'Status ' || l_st || ', ' || substr(l_msg, 1, 120));
        dbms_alert.remove(c_handler);

        -- ---------------------------------------------------------------
        -- L2: Neustart laedt das aktive Rule Set der Gruppe
        -- ---------------------------------------------------------------
        if p_manage then
            l_ok := stop_server('LT_S1');
            start_server('LT_S1');
            wait_servers_ready(sys.odcivarchar2list('LT_S1'));
            -- zwei Prozesse, damit mit hoher Wahrscheinlichkeit beide Server beteiligt sind
            l_pid := proc('_L2'); lilam.mark_event(l_pid, 'RG_L'); lilam.close_session(l_pid);
            l_pid := proc('_L2'); lilam.mark_event(l_pid, 'RG_L'); lilam.close_session(l_pid);
            expect('_L2', 'L-01', 2, 'L2 nach Neustart aktiv');

            -- L2b: ein neuer Server der Gruppe laedt das aktive Rule Set der Gruppe (allein laufend)
            l_ok := stop_server('LT_S1'); l_ok := stop_server('LT_S2');
            start_server('LT_S3');
            wait_servers_ready(sys.odcivarchar2list('LT_S3'));
            l_pid := proc('_L2B'); lilam.mark_event(l_pid, 'RG_L'); lilam.close_session(l_pid);
            expect('_L2B', 'L-01', 1, 'L2b neuer Server LT_S3 laedt das Rule Set der Gruppe');
            l_ok := stop_server('LT_S3');
            execute immediate 'delete from lilam_server_registry where pipe_name = ''LT_S3''';
            commit;
            start_server('LT_S1'); start_server('LT_S2');
            wait_servers_ready(sys.odcivarchar2list('LT_S1', 'LT_S2'));
        end if;

        -- ---------------------------------------------------------------
        -- L3: SERVER_UPDATE_RULES lehnt ungueltige/fehlende Rule Sets ab, nichts aendert sich
        -- ---------------------------------------------------------------
        l_n := rejected(c_group, 3) + rejected(c_group, 4) + rejected(c_group, 5) + rejected(c_group, 6)
             + rejected(c_group, 9);                -- Version 9 gibt es nicht
        check_that(l_run, 'L3 SERVER_UPDATE_RULES lehnt 5 Faelle mit NUM_ERR_RULE_SET ab', l_n = 5, l_n);
        check_that(l_run, 'L3 aktives Rule Set der Gruppe unveraendert', active = c_set || ' v1', active);
        l_pid := proc('_L3'); lilam.mark_event(l_pid, 'RG_L'); lilam.close_session(l_pid);
        expect('_L3', 'L-01', 1, 'L3 Regeln aus Version 1 bleiben aktiv');

        -- L3a: Gruppe ohne Server ist kein Fehler; das Rule Set wird aktiv
        l_n := rejected('LT_LEER', 1);
        check_that(l_run, 'L3a Gruppe ohne Server: kein Fehler, Rule Set aktiv',
                   l_n = 0 and active('LT_LEER') = c_set || ' v1', active('LT_LEER'));

        -- L3c: laufende Server erhalten UPDATE_RULE fuer ein von Hand aktiviertes ungueltiges Rule Set (Version 6)
        --      und behalten ihre bisherigen Regeln (Version 1). Die Nachricht geht wie bei SERVER_UPDATE_RULES
        --      direkt in die Pipes der Server, weil die API das ungueltige Rule Set gar nicht erst aktiviert.
        l_t := systimestamp;
        execute immediate 'update lilam_rules set is_active = 0 where upper(group_name) = :1 and is_active = 1' using c_group;
        execute immediate 'update lilam_rules set is_active = 1 where upper(group_name) = :1 and set_name = :2 and version = 6'
           using c_group, c_set;
        commit;
        execute immediate 'select pipe_name from lilam_server_registry
                            where upper(group_name) = :1 and nvl(is_dispatcher, 0) = 0 and is_active = 1'
           bulk collect into l_pipes using c_group;
        for i in 1 .. l_pipes.count loop
            dbms_pipe.reset_buffer;
            dbms_pipe.pack_message('{"header":{"msg_type":"API_CALL","request":"UPDATE_RULE"}}');
            l_st := dbms_pipe.send_message(l_pipes(i), timeout => 1);
        end loop;
        dbms_session.sleep(1);
        execute immediate 'select count(*) from lilam_log_internal where log_timestamp >= :1
                              and module_name = ''refreshGroupRules'' and error_code = ''-20130'''
           into l_n using l_t;
        check_that(l_run, 'L3c laufende Server lehnen ungueltiges Rule Set ab (1 interner Fehler je Server)',
                   l_pipes.count > 0 and l_n = l_pipes.count, l_n || ' von ' || l_pipes.count);
        -- zwei Prozesse, damit mit hoher Wahrscheinlichkeit beide Server beteiligt sind
        for i in 1 .. 2 loop
            l_pid := proc('_L3C'); lilam.mark_event(l_pid, 'RG_L'); lilam.close_session(l_pid);
        end loop;
        expect('_L3C', 'L-01', 2, 'L3c Regeln aus Version 1 bleiben aktiv');
        -- Version 1 wieder aktiv (die Server haben sie ohnehin noch geladen)
        execute immediate 'update lilam_rules set is_active = 0 where upper(group_name) = :1 and is_active = 1' using c_group;
        execute immediate 'update lilam_rules set is_active = 1 where upper(group_name) = :1 and set_name = :2 and version = 1'
           using c_group, c_set;
        commit;

        -- L3b: der Server selbst lehnt ein ungueltiges aktives Rule Set beim Start ab
        l_t := systimestamp;
        if p_manage then
            l_ok := stop_server('LT_S1');
            execute immediate 'update lilam_rules set is_active = 0 where group_name = :1' using c_group;
            execute immediate 'update lilam_rules set is_active = 1 where group_name = :1 and set_name = :2 and version = 3'
               using c_group, c_set;
            commit;
            start_server('LT_S1');
            wait_servers_ready(sys.odcivarchar2list('LT_S1'));
            execute immediate 'select count(*) from lilam_log_internal where log_timestamp >= :1
                                  and module_name = ''refreshGroupRules'' and error_code = ''-20130'''
               into l_n using l_t;
            check_that(l_run, 'L3b Server lehnt ungueltiges Rule Set beim Start ab (1 interner Fehler)', l_n = 1, l_n);
        end if;

        -- ---------------------------------------------------------------
        -- L4: Wechsel auf Version 2 ersetzt alle Regeln auf allen Servern
        -- ---------------------------------------------------------------
        update_rules(2);
        check_that(l_run, 'L4 Wechsel auf Version 2: aktives Rule Set der Gruppe', active = c_set || ' v2', active);
        for i in 1 .. 2 loop
            l_pid := proc('_L4'); lilam.mark_event(l_pid, 'RG_L'); lilam.mark_event(l_pid, 'RG_V2'); lilam.close_session(l_pid);
        end loop;
        expect('_L4', 'L-01', 0, 'L4 Regel aus Version 1 entfernt');
        expect('_L4', 'V2-01', 2, 'L4 Regel aus Version 2 aktiv');

        -- ---------------------------------------------------------------
        -- IS: Besonderheiten des INSESSION-Modus (Pruefungen mit Praefix "IS")
        -- ---------------------------------------------------------------
        l_s := '_IS';

        -- IS-01: Prozess ohne Gruppe hat keine Regeln
        l_pid := lilam.new_session(p_processName => l_p || '_IS_NG', p_logLevel => lilam.logLevelInfo);
        lilam.mark_event(l_pid, 'RG_L'); lilam.mark_event(l_pid, 'RG_K', 'C1'); lilam.error(l_pid, 'Fehler ohne Gruppe');
        lilam.close_session(l_pid);
        execute immediate 'select count(*) from lilam_alerts where process_name = :1' into l_n using l_p || '_IS_NG';
        check_that(l_run, 'IS-01 Prozess ohne Gruppe: keine Alerts', l_n = 0, 'Alerts ' || l_n);

        -- IS-02: Gruppe in NEW_SESSION klein geschrieben; GROUP_NAME im Alert wie angegeben
        execute immediate 'select count(*) from lilam_alerts where process_name = :1 and rule_id = ''PR-02'' and group_name = :2'
           into l_n using l_p || '_IS_ST', lower(l_is_grp);
        check_that(l_run, 'IS-02 Gruppe klein geschrieben: Regeln greifen, GROUP_NAME wie angegeben', l_n = 1, 'Alerts ' || l_n);

        -- IS-03: Versionswechsel per SERVER_UPDATE_RULES; die Session prueft hoechstens alle 15 s.
        --        Der erste Prozess der Gruppe laedt Version 1 (PROCESS_START), das Update direkt danach wirkt noch nicht.
        l_pid := lilam.new_session(p_processName => l_p || '_IS_3A', p_logLevel => lilam.logLevelInfo, p_groupName => l_is_grp2);
        lilam.server_update_rules(l_is_grp2, c_set, 2);
        lilam.mark_event(l_pid, 'RG_L'); lilam.mark_event(l_pid, 'RG_V2');
        lilam.close_session(l_pid);
        expect('_3A', 'L-01', 1, 'IS-03 direkt nach dem Update noch Version 1');
        expect('_3A', 'V2-01', 0, 'IS-03 direkt nach dem Update Version 2 noch nicht aktiv');
        dbms_session.sleep(16);
        l_pid := lilam.new_session(p_processName => l_p || '_IS_3B', p_logLevel => lilam.logLevelInfo, p_groupName => l_is_grp2);
        lilam.mark_event(l_pid, 'RG_L'); lilam.mark_event(l_pid, 'RG_V2');
        lilam.close_session(l_pid);
        expect('_3B', 'L-01', 0, 'IS-03 nach 16 s Regel aus Version 1 entfernt');
        expect('_3B', 'V2-01', 1, 'IS-03 nach 16 s Version 2 aktiv');

        -- IS-04: ungueltiges Rule Set (Version 6) von Hand aktiviert: abgelehnt, einmal protokolliert, Version 2 bleibt
        l_t := systimestamp;
        execute immediate 'update lilam_rules set is_active = 0 where upper(group_name) = :1 and is_active = 1' using l_is_grp2;
        execute immediate 'update lilam_rules set is_active = 1 where upper(group_name) = :1 and set_name = :2 and version = 6'
           using l_is_grp2, c_set;
        commit;
        dbms_session.sleep(16);
        l_pid := lilam.new_session(p_processName => l_p || '_IS_4', p_logLevel => lilam.logLevelInfo, p_groupName => l_is_grp2);
        lilam.mark_event(l_pid, 'RG_V2');
        lilam.close_session(l_pid);
        expect('_4', 'V2-01', 1, 'IS-04 ungueltiges Rule Set abgelehnt, Version 2 bleibt aktiv');
        execute immediate 'select count(*) from lilam_log_internal where log_timestamp >= :1
                              and module_name = ''refreshGroupRules'' and error_code = ''-20130'''
           into l_n using l_t;
        check_that(l_run, 'IS-04 Ablehnung einmal protokolliert (refreshGroupRules, -20130)', l_n = 1, l_n);

        -- IS-05: kein aktives Rule Set: nach 16 s keine Regeln mehr
        execute immediate 'update lilam_rules set is_active = 0 where upper(group_name) = :1' using l_is_grp2;
        commit;
        dbms_session.sleep(16);
        l_pid := lilam.new_session(p_processName => l_p || '_IS_5', p_logLevel => lilam.logLevelInfo, p_groupName => l_is_grp2);
        lilam.mark_event(l_pid, 'RG_V2'); lilam.mark_event(l_pid, 'RG_L');
        lilam.close_session(l_pid);
        execute immediate 'select count(*) from lilam_alerts where process_name = :1' into l_n using l_p || '_IS_5';
        check_that(l_run, 'IS-05 kein aktives Rule Set: nach 16 s keine Alerts', l_n = 0, 'Alerts ' || l_n);
        l_s := null;

        -- ---------------------------------------------------------------
        -- Abschluss
        -- ---------------------------------------------------------------
        if p_manage then
            stop_all_servers;
        end if;
        reset_rules;   -- sonst laden spaetere Server der Gruppe LT dieses Rule Set
        execute immediate 'select count(*) from lilam_log_internal where log_timestamp >= :1
                              and not (module_name = ''refreshGroupRules'' and error_code = ''-20130'')'
           into l_n using run_started(l_run);
        check_that(l_run, 'Keine weiteren internen LILAM-Fehler', l_n = 0, l_n);
        end_run(l_run);
        return l_run;

    exception
        when others then
            begin dbms_alert.remove(c_handler); exception when others then null; end;
            begin reset_rules; exception when others then null; end;
            abort_run(l_run, p_manage, sqlerrm || ' ' || dbms_utility.format_error_backtrace);
            if p_manage then raise; end if;
            return l_run;
    end;

    ----------------------------------------------------------------------
    -- REGELN_LAST: Kosten der Regelpruefung je Signaltyp im Server (LT_S1 ohne Drosselung) und INSESSION
    -- Signaltypen EVENT, TRACE (Start+Stop), LOG (INFO), STEP (PROC_STEP_DONE)
    -- Varianten NONE, OTHER50, MATCH20, FIRE_THR, FIRE_ALL; gemessen wird im Server bis zur Antwort einer
    -- abschliessenden synchronen Abfrage (der Server hat dann alle Signale davor verarbeitet),
    -- INSESSION die Aufrufzeit in der Session. INSESSION hat jede Messung eine eigene Gruppe, damit die
    -- erste Regelpruefung das Rule Set sofort laedt (die Session prueft sonst hoechstens alle 15 s).
    ----------------------------------------------------------------------
    function t_regeln_last(p_n number default 2000, p_n_fire number default 200, p_reps number default 5,
                           p_manage boolean default true, p_parent number default null) return number is
        c_set     constant varchar2(30) := 'LT_REGELN_LAST';
        c_handler constant varchar2(30) := 'LT_REGELN_LAST_ALERT';
        type t_names is table of varchar2(20);
        l_types   t_names := t_names('EVENT', 'TRACE', 'LOG', 'STEP');
        l_vars    t_names := t_names('NONE', 'OTHER50', 'MATCH20', 'FIRE_THR', 'FIRE_ALL');
        l_run     number;
        l_p       varchar2(60);
        l_msg     varchar2(4000);
        l_base    number;
        l_val     number;
        l_n       number;
        l_m       varchar2(10);   -- Praefix der Metriken je Modus: SERVER leer, INSESSION 'is_'
        l_mt      varchar2(10);   -- Praefix der Pruefungen je Modus: SERVER leer, INSESSION 'IS '

        function r(p_id varchar2, p_trig varchar2, p_action varchar2, p_op varchar2, p_val varchar2, p_thr number default 3600) return varchar2 is
        begin
            return '{"id":"' || p_id || '","trigger_type":"' || p_trig || '","action":"' || p_action
                || '","condition":{"operator":"' || p_op || '","value":"' || p_val
                || '"},"alert":{"handler":"' || c_handler || '","severity":"WARN","throttle_seconds":' || p_thr || '}}';
        end;

        -- Regeln einer Variante fuer einen Signaltyp (Action des Signals bzw. Prozessname bei STEP)
        function rules_for(p_type varchar2, p_var varchar2, p_proc varchar2) return clob is
            l     clob;
            l_trg varchar2(30) := case p_type when 'EVENT' then 'MARK_EVENT' when 'TRACE' then 'TRACE_STOP'
                                              when 'LOG' then 'LOGGING' else 'PROCESS_UPDATE' end;
            l_act varchar2(100) := case p_type when 'EVENT' then 'RL_EV' when 'TRACE' then 'RL_TR'
                                               when 'LOG' then 'LOGGING' else p_proc end;
            l_op  varchar2(40);
            l_v   varchar2(40);
            l_t   varchar2(30);
            procedure add(p_rule varchar2) is
            begin
                l := l || case when l is not null then ',' end || p_rule;
            end;
        begin
            if p_var = 'OTHER50' then
                -- Regeln auf andere Actions: fuer LOG gibt es nur die Action LOGGING, daher Event-Regeln
                for i in 1 .. 50 loop
                    add(r('O' || i, case when p_type = 'LOG' then 'MARK_EVENT' else l_trg end, 'RL_OTHER_' || i,
                          case when p_type = 'STEP' then 'ON_UPDATE' when p_type = 'TRACE' then 'ON_STOP' else 'ON_EVENT' end, ''));
                end loop;
            elsif p_var = 'MATCH20' then
                for i in 1 .. 20 loop
                    l_t := l_trg;
                    case p_type
                        when 'EVENT' then
                            l_op := case mod(i, 5) when 0 then 'MAX_DURATION_MS' when 1 then 'MAX_GAP_SECONDS' when 2 then 'MAX_OCCURRENCE'
                                                   when 3 then 'PRECEDED_BY' else 'PRECEDED_BY_WITHIN_SECS' end;
                            l_v  := case mod(i, 5) when 0 then '999999999' when 1 then '999999' when 2 then '999999999'
                                                   when 3 then 'RL_EV' else 'RL_EV|999999' end;
                        when 'TRACE' then
                            l_t  := case when mod(i, 2) = 0 then 'TRACE_STOP' else 'TRACE_START' end;
                            l_op := case when l_t = 'TRACE_START' then case mod(i, 4) when 1 then 'MAX_GAP_SECONDS' else 'PRECEDED_BY' end
                                         else case mod(i, 3) when 0 then 'MAX_DURATION_MS' when 1 then 'MAX_OCCURRENCE' else 'AVG_DEVIATION_PCT' end end;
                            l_v  := case l_op when 'MAX_GAP_SECONDS' then '999999' when 'PRECEDED_BY' then 'RL_TR'
                                              when 'AVG_DEVIATION_PCT' then '100000|3|0.1' else '999999999' end;
                        when 'LOG' then
                            l_op := 'SEVERITY';
                            l_v  := case mod(i, 4) when 0 then 'ERROR' when 1 then 'WARN' when 2 then 'DEBUG' else 'MONITOR' end;
                        else
                            l_op := case mod(i, 5) when 0 then 'STATUS_EQUALS' when 1 then 'INFO_CONTAINS' when 2 then 'MAX_OCCURRENCE'
                                                   when 3 then 'RUNTIME_EXCEEDED' else 'STEPS_LEFT_HIGH' end;
                            l_v  := case l_op when 'STATUS_EQUALS' then '999' when 'INFO_CONTAINS' then 'xyz_nie' else '999999999' end;
                    end case;
                    add(r('M' || i, l_t, l_act, l_op, l_v));
                end loop;
            elsif p_var in ('FIRE_THR', 'FIRE_ALL') then
                add(r('F1', l_trg, l_act,
                      case p_type when 'LOG' then 'SEVERITY' when 'TRACE' then 'ON_STOP' when 'STEP' then 'ON_UPDATE' else 'ON_EVENT' end,
                      case when p_type = 'LOG' then 'INFO' end,
                      case when p_var = 'FIRE_THR' then 3600 else 0 end));
            end if;
            return '{"header":{"rule_set":"' || c_set || '"},"rules":[' || l || ']}';
        end;

        procedure activate(p_ver number, p_rules clob, p_group varchar2 default c_group) is
        begin
            execute immediate 'delete from lilam_rules where group_name = :1 and set_name = :2 and version = :3' using p_group, c_set, p_ver;
            execute immediate 'insert into lilam_rules(group_name, set_name, version, is_active, created, author, rule_set)
                               values (:1, :2, :3, 0, systimestamp, ''LT'', :4)' using p_group, c_set, p_ver, p_rules;
            commit;
            lilam.server_update_rules(p_group, c_set, p_ver);
        end;

        procedure signals(p_pid number, p_type varchar2, p_count number) is
        begin
            for i in 1 .. p_count loop
                case p_type
                    when 'EVENT' then lilam.mark_event(p_pid, 'RL_EV');
                    when 'TRACE' then if mod(i, 2) = 1 then lilam.trace_start(p_pid, 'RL_TR'); else lilam.trace_stop(p_pid, 'RL_TR'); end if;
                    when 'LOG'   then lilam.info(p_pid, 'rl ' || i);
                    else              lilam.proc_step_done(p_pid);
                end case;
            end loop;
        end;

        -- INSESSION: eigene Gruppe je Messung
        function is_group(p_ver number, p_rep number) return varchar2 is
        begin
            return 'LT_RL_IS_' || l_run || '_' || p_ver || '_' || p_rep;
        end;

        -- eine Messung im Server: liefert Mikrosekunden je Signal (Server-Verarbeitung), -1 bei Zeitueberschreitung
        function measure(p_type varchar2, p_var varchar2, p_rep number, p_ver number) return number is
            l_proc  varchar2(80) := l_p || '_' || p_type || '_' || p_var || '_' || p_rep;
            l_pid   number;
            l_cnt   number := case when p_var = 'FIRE_ALL' then p_n_fire else p_n end;
            l_t0    timestamp;
            l_ms    number;
            l_sync  number;
        begin
            activate(p_ver, rules_for(p_type, p_var, l_proc));
            l_pid := lilam.server_new_session(l_proc, c_group, lilam.logLevelInfo);
            dbms_session.sleep(0.5);
            -- Aufwaermen (Baseline, Caches), dann synchronisieren
            signals(l_pid, p_type, 100);
            l_sync := lilam.get_proc_steps_done(l_pid);
            l_t0 := systimestamp;
            signals(l_pid, p_type, l_cnt);
            l_sync := lilam.get_proc_steps_done(l_pid);   -- Antwort erst nach allen Signalen davor
            l_ms := ms_since(l_t0);
            lilam.close_session(l_pid);
            if l_sync is null then
                return -1;
            end if;
            return round(l_ms * 1000 / l_cnt, 1);
        end;

        -- eine Messung INSESSION: liefert Mikrosekunden je Signal (Aufrufzeit in der Session)
        function measure_is(p_type varchar2, p_var varchar2, p_rep number, p_ver number) return number is
            l_proc  varchar2(80) := l_p || '_IS_' || p_type || '_' || p_var || '_' || p_rep;
            l_pid   number;
            l_cnt   number := case when p_var = 'FIRE_ALL' then p_n_fire else p_n end;
            l_t0    timestamp;
            l_ms    number;
        begin
            activate(p_ver, rules_for(p_type, p_var, l_proc), is_group(p_ver, p_rep));
            -- PROCESS_START laedt das Rule Set der (neuen) Gruppe
            l_pid := lilam.new_session(p_processName => l_proc, p_logLevel => lilam.logLevelInfo,
                                       p_groupName => is_group(p_ver, p_rep));
            -- Aufwaermen (Baseline, Caches)
            signals(l_pid, p_type, 100);
            l_t0 := systimestamp;
            signals(l_pid, p_type, l_cnt);
            l_ms := ms_since(l_t0);
            lilam.close_session(l_pid);
            return round(l_ms * 1000 / l_cnt, 1);
        end;

        function med(p_name varchar2) return number is
            l number;
        begin
            select median(value) into l from lt_metric where run_id = l_run and metric = p_name and value >= 0;
            return l;
        end;

        procedure reset_rules is
        begin
            execute immediate 'delete from lilam_rules where set_name = :1' using c_set;
            execute immediate 'update lilam_rules set is_active = 0 where upper(group_name) = :1 and is_active = 1' using c_group;
            commit;
        end;

    begin
        l_run := begin_run('REGELN_LAST', 'SERVER+INSESSION', 'n=' || p_n || ' n_fire=' || p_n_fire || ' reps=' || p_reps
                           || ', LT_S1 ohne Drosselung', p_parent);
        l_p   := 'LT_' || l_run || '_RL';
        if p_manage then
            stop_all_servers;
            reset_rules;
            l_msg := lilam.create_server('LT_S1', c_group, c_pw, 0, p_perfServer => 0);
            dbms_output.put_line('    ' || l_msg);
            wait_servers_ready(sys.odcivarchar2list('LT_S1'));
        end if;

        -- Varianten je Lauf abwechselnd, damit Schwankungen alle Varianten gleich treffen
        for rep in 1 .. p_reps loop
            for t in 1 .. l_types.count loop
                for v in 1 .. l_vars.count loop
                    l_val := measure(l_types(t), l_vars(v), rep, t * 10 + v);
                    metric(l_run, lower(l_types(t) || '_' || l_vars(v)), l_val, 'us/Signal');
                    l_val := measure_is(l_types(t), l_vars(v), rep, t * 10 + v);
                    metric(l_run, lower('is_' || l_types(t) || '_' || l_vars(v)), l_val, 'us/Signal');
                end loop;
            end loop;
        end loop;

        -- Auswertung je Modus und Signaltyp: Median im Verhaeltnis zu NONE; kleine absolute Unterschiede (< 100 us) gelten als gleich.
        -- Metriken und Pruefungen INSESSION mit Praefix is_ bzw. "IS". (Block in der Schleife bewusst nicht eingerueckt.)
        for md in 1 .. 2 loop
        l_m  := case when md = 2 then 'is_' end;
        l_mt := case when md = 2 then 'IS ' end;
        for t in 1 .. l_types.count loop
            l_base := med(l_m || lower(l_types(t)) || '_none');
            dbms_output.put_line('    ' || rpad(l_mt || l_types(t), 9) || ' NONE ' || l_base || ' us, OTHER50 ' || med(l_m || lower(l_types(t)) || '_other50')
                                 || ', MATCH20 ' || med(l_m || lower(l_types(t)) || '_match20') || ', FIRE_THR ' || med(l_m || lower(l_types(t)) || '_fire_thr')
                                 || ', FIRE_ALL ' || med(l_m || lower(l_types(t)) || '_fire_all') || ' us/Signal');
            l_val := med(l_m || lower(l_types(t)) || '_other50');
            check_that(l_run, l_mt || l_types(t) || ' 50 Regeln auf andere Actions: hoechstens 1,5 x ohne Regeln',
                       l_val <= greatest(1.5 * l_base, l_base + 100), l_val || ' / ' || l_base || ' us');
            l_val := med(l_m || lower(l_types(t)) || '_match20');
            check_that(l_run, l_mt || l_types(t) || ' 20 passende Regeln ohne Alarm: hoechstens 2 x ohne Regeln',
                       l_val <= greatest(2 * l_base, l_base + 100), l_val || ' / ' || l_base || ' us');
            l_val := med(l_m || lower(l_types(t)) || '_fire_thr');
            check_that(l_run, l_mt || l_types(t) || ' Regel schlaegt immer an, gedrosselt: hoechstens 1,5 x ohne Regeln',
                       l_val <= greatest(1.5 * l_base, l_base + 100), l_val || ' / ' || l_base || ' us');
            -- ungedrosselt: Korrektheit pruefen, Kosten nur messen
            execute immediate 'select count(*) from lilam_alerts where process_name like :1 and rule_id = ''F1'''
               into l_n using l_p || '_' || upper(l_m) || l_types(t) || '_FIRE_ALL_%';
            check_that(l_run, l_mt || l_types(t) || ' ungedrosselt: ein Alert je Signal inkl. Aufwaermen',
                       l_n = p_reps * (p_n_fire + 100)
                            / case when l_types(t) = 'TRACE' then 2 else 1 end,
                       l_n || ' Alerts');
        end loop;

        end loop;

        select count(*) into l_n from lt_metric where run_id = l_run and value < 0;
        check_that(l_run, 'Alle Messungen synchronisiert (keine Zeitueberschreitung)', l_n = 0, l_n);

        if p_manage then
            stop_all_servers;
        end if;
        reset_rules;
        check_that(l_run, 'Keine internen LILAM-Fehler', internal_errors_since(run_started(l_run)) = 0,
                   internal_errors_since(run_started(l_run)));
        end_run(l_run);
        return l_run;

    exception
        when others then
            begin reset_rules; exception when others then null; end;
            abort_run(l_run, p_manage, sqlerrm || ' ' || dbms_utility.format_error_backtrace);
            if p_manage then raise; end if;
            return l_run;
    end;

