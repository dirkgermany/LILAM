    function open_process(p_mode varchar2, p_proc_name varchar2, p_scope varchar2 default null) return number is
    begin
        if p_mode = c_insession then
            return lilam.new_session(p_proc_name, lilam.logLevelInfo, p_baselineScope => p_scope);
        else
            if p_mode = c_dispatcher then
                lilam.set_dispatcher_pipe(c_disp_pipe);
            end if;
            return lilam.server_new_session(p_proc_name, c_group, lilam.logLevelInfo, p_baselineScope => p_scope);
        end if;
    end;

    procedure one_op(p_pid number, p_client number, p_op number) is
    begin
        lilam.info(p_pid, 'c' || p_client || ' op ' || p_op);
        lilam.trace_start(p_pid, 'LT_ACTION');
        lilam.trace_stop(p_pid, 'LT_ACTION');
        lilam.mark_event(p_pid, 'LT_EVENT');
        lilam.proc_step_done(p_pid);
    end;

    procedure workload(
        p_run_id      number,
        p_client      number,
        p_mode        varchar2,
        p_proc_name   varchar2,
        p_processes   number,
        p_ops         number,
        p_sleep_ms    number  default 0,
        p_interleave  boolean default false,
        p_scope       varchar2 default null)
    is
        type t_pids is table of number index by pls_integer;
        l_pids  t_pids;
        l_t0    timestamp := systimestamp;
        l_open  number := 0;
        l_calls number := 0;
        l_t     timestamp;
    begin
        joblog(p_run_id, p_client, 'START', p_mode || ' name=' || p_proc_name || ' scope=' || nvl(p_scope, '(default)')
                                            || ' processes=' || p_processes || ' ops=' || p_ops);
        if p_interleave then
            l_t := systimestamp;
            for p in 1 .. p_processes loop
                l_pids(p) := open_process(p_mode, p_proc_name, p_scope);
            end loop;
            l_open := ms_since(l_t);
            for o in 1 .. p_ops loop
                for p in 1 .. p_processes loop
                    one_op(l_pids(p), p_client, o);
                    l_calls := l_calls + 5;
                end loop;
                if p_sleep_ms > 0 then dbms_session.sleep(p_sleep_ms / 1000); end if;
            end loop;
            for p in 1 .. p_processes loop
                lilam.close_session(l_pids(p));
            end loop;
        else
            for p in 1 .. p_processes loop
                l_t := systimestamp;
                l_pids(p) := open_process(p_mode, p_proc_name, p_scope);
                l_open := l_open + ms_since(l_t);
                for o in 1 .. p_ops loop
                    one_op(l_pids(p), p_client, o);
                    l_calls := l_calls + 5;
                    if p_sleep_ms > 0 then dbms_session.sleep(p_sleep_ms / 1000); end if;
                end loop;
                lilam.close_session(l_pids(p));
            end loop;
        end if;
        metric(p_run_id, 'client_elapsed_ms', ms_since(l_t0), 'ms', p_client);
        metric(p_run_id, 'client_api_calls', l_calls, 'calls', p_client);
        metric(p_run_id, 'client_open_ms_total', l_open, 'ms', p_client);
        joblog(p_run_id, p_client, 'END', 'ok');
    exception
        when others then
            joblog(p_run_id, p_client, 'ERROR', sqlerrm || ' | ' || dbms_utility.format_error_backtrace);
    end;

    procedure endurance(
        p_run_id       number,
        p_client       number,
        p_mode         varchar2,
        p_proc_name    varchar2,
        p_end_ts       timestamp,
        p_ops          number default 20,
        p_max_pause_s  number default 30,
        p_metric_min   number default 10)
    is
        l_pid      number;
        l_t        timestamp;
        l_last_m   timestamp := systimestamp;
        l_cycles   number := 0;
        l_sum_ms   number := 0;
        l_max_ms   number := 0;
        l_cycle_ms number;
        l_pause    number;
    begin
        joblog(p_run_id, p_client, 'START', p_mode || ' bis ' || to_char(p_end_ts, 'DD.MM. HH24:MI'));
        while systimestamp < p_end_ts loop
            begin
                l_t := systimestamp;
                l_pid := open_process(p_mode, p_proc_name);
                for o in 1 .. p_ops loop
                    one_op(l_pid, p_client, o);
                end loop;
                lilam.close_session(l_pid);
                l_cycle_ms := ms_since(l_t);
                l_cycles := l_cycles + 1;
                l_sum_ms := l_sum_ms + l_cycle_ms;
                l_max_ms := greatest(l_max_ms, l_cycle_ms);
            exception
                when others then
                    joblog(p_run_id, p_client, 'ERROR', sqlerrm || ' | ' || dbms_utility.format_error_backtrace);
            end;

            if ms_since(l_last_m) >= p_metric_min * 60000 then
                metric(p_run_id, 'cycles', l_cycles, 'count', p_client);
                metric(p_run_id, 'cycle_avg_ms', round(l_sum_ms / greatest(l_cycles, 1), 1), 'ms', p_client);
                metric(p_run_id, 'cycle_max_ms', l_max_ms, 'ms', p_client);
                metric(p_run_id, 'client_pga_kb', my_pga_kb, 'KB', p_client);
                metric(p_run_id, 'server_pga_kb', server_pga_kb, 'KB', p_client);
                l_cycles := 0; l_sum_ms := 0; l_max_ms := 0; l_last_m := systimestamp;
            end if;

            -- zufaellige Pause, gelegentlich laenger als 15 s (Ruhezustand des Servers)
            l_pause := round(dbms_random.value(0, p_max_pause_s), 1);
            dbms_session.sleep(l_pause);
        end loop;
        joblog(p_run_id, p_client, 'END', 'ok');
    exception
        when others then
            joblog(p_run_id, p_client, 'ERROR', sqlerrm || ' | ' || dbms_utility.format_error_backtrace);
    end;

    procedure lifecycle(
        p_run_id        number,
        p_client        number,
        p_mode          varchar2,
        p_proc_name     varchar2,
        p_processes     number,
        p_ops           number,
        p_window        number default 3,
        p_max_pause_ms  number default 20)
    is
        type t_slot is record (pid number, proc_no number, ops_done number := 0);
        type t_slots is table of t_slot index by pls_integer;
        l_slots    t_slots;
        l_started  number := 0;
        l_closed   number := 0;
        l_open     number := 0;
        l_t0       timestamp := systimestamp;
        l_t        timestamp;
        l_open_ms  number := 0;
        l_close_ms number := 0;
        l_read_ms  number := 0;
        l_idx      pls_integer;
        l_steps    number;

        procedure start_in(p_slot pls_integer) is
        begin
            l_started := l_started + 1;
            l_t := systimestamp;
            if p_mode = c_insession then
                l_slots(p_slot).pid := lilam.new_session(p_processName => p_proc_name, p_logLevel => lilam.logLevelInfo,
                                                      p_procStepsToDo => p_ops, p_daysToKeep => null);
            else
                if p_mode = c_dispatcher then lilam.set_dispatcher_pipe(c_disp_pipe); end if;
                l_slots(p_slot).pid := lilam.server_new_session(p_proc_name, c_group, lilam.logLevelInfo, p_ops, null, 'LILAM');
            end if;
            l_open_ms := l_open_ms + ms_since(l_t);
            l_slots(p_slot).proc_no  := l_started;
            l_slots(p_slot).ops_done := 0;
            lilam.set_process_status(l_slots(p_slot).pid, 1, 'RUNNING');
            l_open := l_open + 1;
        end;

        procedure finish(p_slot pls_integer) is
            l_pid number := l_slots(p_slot).pid;
        begin
            l_t := systimestamp;
            l_steps := lilam.get_proc_steps_done(l_pid);
            l_read_ms := l_read_ms + ms_since(l_t);
            if nvl(l_steps, -1) != p_ops then
                joblog(p_run_id, p_client, 'MISMATCH', 'pid=' || l_pid || ' GET_PROC_STEPS_DONE=' || l_steps || ' erwartet ' || p_ops);
            end if;
            l_t := systimestamp;
            lilam.close_session(l_pid, 'DONE c' || p_client || ' p' || l_slots(p_slot).proc_no, 2, p_ops);
            l_close_ms := l_close_ms + ms_since(l_t);
            l_slots(p_slot).pid := null;
            l_closed := l_closed + 1;
            l_open := l_open - 1;
        end;
    begin
        joblog(p_run_id, p_client, 'START', p_mode || ' processes=' || p_processes || ' ops=' || p_ops || ' window=' || p_window);
        for i in 1 .. least(p_window, p_processes) loop
            start_in(i);
        end loop;

        while l_open > 0 loop
            -- zufaelligen offenen Slot waehlen
            loop
                l_idx := trunc(dbms_random.value(1, least(p_window, p_processes) + 1));
                exit when l_slots(l_idx).pid is not null;
            end loop;

            l_slots(l_idx).ops_done := l_slots(l_idx).ops_done + 1;
            one_op(l_slots(l_idx).pid, p_client, l_slots(l_idx).ops_done);
            if l_slots(l_idx).ops_done = trunc(p_ops / 2) then
                lilam.set_process_status(l_slots(l_idx).pid, 1, 'HALF');
            end if;

            if l_slots(l_idx).ops_done >= p_ops then
                finish(l_idx);
                if l_started < p_processes then
                    start_in(l_idx);
                end if;
            end if;

            if p_max_pause_ms > 0 then
                dbms_session.sleep(round(dbms_random.value(0, p_max_pause_ms)) / 1000);
            end if;
        end loop;

        metric(p_run_id, 'client_elapsed_ms', ms_since(l_t0), 'ms', p_client);
        metric(p_run_id, 'client_processes', l_closed, 'count', p_client);
        metric(p_run_id, 'avg_new_session_ms', round(l_open_ms / greatest(l_started, 1), 1), 'ms', p_client);
        metric(p_run_id, 'avg_close_session_ms', round(l_close_ms / greatest(l_closed, 1), 1), 'ms', p_client);
        metric(p_run_id, 'avg_get_steps_ms', round(l_read_ms / greatest(l_closed, 1), 1), 'ms', p_client);
        joblog(p_run_id, p_client, 'END', 'ok');
    exception
        when others then
            joblog(p_run_id, p_client, 'ERROR', sqlerrm || ' | ' || dbms_utility.format_error_backtrace);
    end;

    procedure wake_call(p_run_id number, p_mode varchar2, p_pid number, p_idle_s number,
                        p_proc_name varchar2, p_new_session boolean default true) is
        l_t   timestamp := systimestamp;
        l_pid number;
    begin
        if p_mode = c_dispatcher then
            lilam.set_dispatcher_pipe(c_disp_pipe);
        end if;
        lilam.info(p_pid, 'wake after ' || p_idle_s || ' s');
        lilam.mark_event(p_pid, 'LT_WAKE');
        metric(p_run_id, 'wake_call_ms_' || p_idle_s || 's', ms_since(l_t), 'ms');

        -- Sichtbarkeit: ab dem Ende des Aufrufs, bis das INFO in LILAM_LOG steht (alle 10 ms, max. 30 s)
        declare
            l_tv timestamp := systimestamp;
            l_n  number := 0;
        begin
            loop
                execute immediate 'select count(*) from lilam_log where process_id = :1 and info = :2'
                    into l_n using p_pid, 'wake after ' || p_idle_s || ' s';
                exit when l_n > 0 or ms_since(l_tv) > 30000;
                dbms_session.sleep(0.01);
            end loop;
            metric(p_run_id, 'wake_visible_ms_' || p_idle_s || 's', case when l_n > 0 then ms_since(l_tv) else -1 end, 'ms');
        end;
        if p_new_session then
            l_t := systimestamp;
            l_pid := open_process(p_mode, p_proc_name || '_N');
            metric(p_run_id, 'wake_new_session_ms_' || p_idle_s || 's', ms_since(l_t), 'ms');
            if nvl(l_pid, -1) <= 0 then
                joblog(p_run_id, p_idle_s, 'ERROR', 'NEW_SESSION nach ' || p_idle_s || ' s Ruhe lieferte ' || l_pid);
            else
                lilam.info(l_pid, 'new after ' || p_idle_s || ' s');
                lilam.close_session(l_pid);
            end if;
        end if;
    exception
        when others then
            joblog(p_run_id, p_idle_s, 'ERROR', sqlerrm || ' | ' || dbms_utility.format_error_backtrace);
    end;

    procedure verify_standard(
        p_run_id          number,
        p_prefix          varchar2,
        p_processes       number,
        p_ops             number,
        p_check_routes    boolean default false,
        p_max_wait_sec    number  default 120,
        p_baseline_scopes number  default 1)
    is
        l_exp  number := p_processes * p_ops;
        l_ms   number;
        l_n    number;
        l_sc   number;
        l_min  number;
        l_max  number;
        l_per  number;
    begin
        l_ms := wait_count(p_prefix, 'PROC_CLOSED', p_processes, p_max_wait_sec);
        l_n  := count_lilam(p_prefix, 'PROC_CLOSED');
        check_that(p_run_id, 'Alle Prozesse angelegt und geschlossen', l_n = p_processes, l_n || '/' || p_processes);

        for w in (select column_value what from table(sys.odcivarchar2list('LOG', 'TRACE', 'EVENT'))) loop
            l_ms := wait_count(p_prefix, w.what, l_exp, p_max_wait_sec);
            l_n  := count_lilam(p_prefix, w.what);
            check_that(p_run_id, 'Anzahl ' || w.what || ' = ' || l_exp, l_n = l_exp, 'ist ' || l_n);
            if l_ms >= 0 then metric(p_run_id, 'drain_' || lower(w.what) || '_ms', l_ms, 'ms'); end if;
        end loop;

        l_n := count_lilam(p_prefix, 'STEPS');
        check_that(p_run_id, 'Summe steps_done = ' || l_exp, l_n = l_exp, 'ist ' || l_n);

        -- Baseline: Anzahl Scopes und Zaehlung je Scope
        if p_baseline_scopes > 0 then
            l_ms := wait_count(p_prefix, 'BASELINE', l_exp, 10);
        else
            dbms_session.sleep(2);   -- etwaige Baseline-Abgleiche abwarten
        end if;
        execute immediate
           'select count(*), min(cnt), max(cnt), nvl(sum(cnt), 0)
              from (select s.scope_name, sum(b.action_count) cnt
                      from lilam_baselines b join lilam_scopes s on s.scope_id = b.scope_id
                     where s.scope_name like upper(:1) escape ''\'' and b.action_name = ''LT_ACTION''
                     group by s.scope_name)'
           into l_sc, l_min, l_max, l_n using replace(p_prefix, '_', '\_') || '%';
        if p_baseline_scopes = 0 then
            check_that(p_run_id, 'Keine Baseline entstanden (Scope abgeschaltet)', l_sc = 0, l_sc || ' Scopes, ' || l_n || ' Traces');
        else
            l_per := l_exp / p_baseline_scopes;
            check_that(p_run_id, 'Baseline: ' || p_baseline_scopes || ' Scope(s), je ' || l_per || ' Traces',
                       l_sc = p_baseline_scopes and l_min = l_per and l_max = l_per,
                       l_sc || ' Scopes, je ' || l_min || '..' || l_max || ', Summe ' || l_n);
        end if;

        if p_check_routes then
            l_n := count_lilam(p_prefix, 'ROUTES');
            check_that(p_run_id, 'Keine Prozess-Routen uebrig', l_n = 0, 'ist ' || l_n);
        end if;

        select count(*) into l_n from lt_joblog where run_id = p_run_id and phase = 'ERROR';
        check_that(p_run_id, 'Keine Fehler in den Client-Jobs', l_n = 0, l_n || ' Fehler');

        l_n := internal_errors_since(run_started(p_run_id));
        check_that(p_run_id, 'Keine internen LILAM-Fehler', l_n = 0, l_n || ' Eintraege');
    end;

    procedure verify_lifecycle(
        p_run_id       number,
        p_prefix       varchar2,
        p_processes    number,
        p_ops          number,
        p_check_routes boolean default false,
        p_min_servers  number  default 0,
        p_max_wait_sec number  default 180)
    is
        l_exp number := p_processes * p_ops;
        l_ms  number;
        l_n   number;
        l_p   varchar2(200) := replace(p_prefix, '_', '\_') || '%';
        l_det varchar2(4000);
    begin
        l_ms := wait_count(p_prefix, 'PROC_CLOSED', p_processes, p_max_wait_sec);
        l_n  := count_lilam(p_prefix, 'PROC_CLOSED');
        check_that(p_run_id, 'Alle ' || p_processes || ' Prozesse angelegt und geschlossen', l_n = p_processes, 'ist ' || l_n);

        -- Endzustand jedes Prozesses in _PROC
        execute immediate
           'select count(*) from lilam_proc where process_name like :1 escape ''\''
               and status = 2 and steps_todo = :2 and steps_done = :3 and info like ''DONE c%'' and process_end is not null'
           into l_n using l_p, p_ops, p_ops;
        check_that(p_run_id, 'Endzustand korrekt (status 2, steps_todo/done ' || p_ops || ', info DONE)', l_n = p_processes,
                   l_n || '/' || p_processes);
        if l_n != p_processes then
            execute immediate
               'select listagg(id || '':'' || status || ''/'' || steps_todo || ''/'' || steps_done || ''/'' || substr(info, 1, 20), '', '')
                       within group (order by id)
                  from (select id, status, steps_todo, steps_done, info from lilam_proc where process_name like :1 escape ''\''
                           and not (nvl(status, -1) = 2 and nvl(steps_todo, -1) = :2 and nvl(steps_done, -1) = :3
                                    and info like ''DONE c%'' and process_end is not null)
                         fetch first 5 rows only)' into l_det using l_p, p_ops, p_ops;
            dbms_output.put_line('       Beispiele (id:status/todo/done/info): ' || l_det);
        end if;

        for w in (select column_value what from table(sys.odcivarchar2list('LOG', 'TRACE', 'EVENT'))) loop
            l_ms := wait_count(p_prefix, w.what, l_exp, p_max_wait_sec);
            l_n  := count_lilam(p_prefix, w.what);
            check_that(p_run_id, 'Anzahl ' || w.what || ' = ' || l_exp, l_n = l_exp, 'ist ' || l_n);
        end loop;

        select count(*) into l_n from lt_joblog where run_id = p_run_id and phase = 'MISMATCH';
        check_that(p_run_id, 'Rueckleseprobe GET_PROC_STEPS_DONE stimmt immer', l_n = 0, l_n || ' Abweichungen');

        l_n := count_lilam(p_prefix, 'BASELINE');
        check_that(p_run_id, 'Baseline zaehlt alle Traces = ' || l_exp, l_n = l_exp, 'ist ' || l_n);

        if p_check_routes then
            l_n := count_lilam(p_prefix, 'ROUTES');
            check_that(p_run_id, 'Keine Prozess-Routen uebrig', l_n = 0, 'ist ' || l_n);
        end if;

        if p_min_servers > 0 then
            execute immediate 'select count(distinct server_pipe) from lilam_proc where process_name like :1 escape ''\'''
               into l_n using l_p;
            check_that(p_run_id, 'Prozesse auf mindestens ' || p_min_servers || ' Server verteilt', l_n >= p_min_servers, l_n || ' Server');
        end if;

        select count(*) into l_n from lt_joblog where run_id = p_run_id and phase = 'ERROR';
        check_that(p_run_id, 'Keine Fehler in den Client-Jobs', l_n = 0, l_n || ' Fehler');

        l_n := internal_errors_since(run_started(p_run_id));
        check_that(p_run_id, 'Keine internen LILAM-Fehler', l_n = 0, l_n || ' Eintraege');
    end;


