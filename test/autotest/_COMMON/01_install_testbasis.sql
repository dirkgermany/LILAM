-- =====================================================================
-- LILAM Testbasis: Tabellen und Package LT
-- Ausfuehren als Testschema (z.B. LILAM_TEST), nach der Installation von LILAM.
-- Mehrfach ausfuehrbar (Tabellen bleiben erhalten, Package wird ersetzt).
--
-- LT_RUN     ein Testlauf (Name, Modus, Parameter, Status)
-- LT_CHECK   Pruefungen eines Laufs (OK / FEHLER)
-- LT_METRIC  Messwerte eines Laufs (z.B. Laufzeiten, Durchsatz, Speicher)
-- LT_JOBLOG  Meldungen und Fehler der Client-Jobs
-- =====================================================================
set serveroutput on size unlimited

declare
  l_cnt number;
  procedure ddl(p_name varchar2, p_sql varchar2) is
    l_cnt number;
  begin
    select count(*) into l_cnt from user_tables where table_name = p_name;
    if l_cnt = 0 then execute immediate p_sql; dbms_output.put_line('angelegt: ' || p_name); end if;
  end;
begin
  ddl('LT_RUN', 'create table lt_run (
      run_id     number generated by default as identity primary key,
      test_name  varchar2(100) not null,
      mode_name  varchar2(30),
      params     varchar2(1000),
      started    timestamp(6) default systimestamp,
      ended      timestamp(6),
      status     varchar2(10) default ''RUNNING'')');
  ddl('LT_CHECK', 'create table lt_check (
      run_id     number not null,
      check_no   number,
      check_name varchar2(200),
      ok         number(1),
      detail     varchar2(1000),
      ts         timestamp(6) default systimestamp)');
  ddl('LT_METRIC', 'create table lt_metric (
      run_id     number not null,
      metric     varchar2(100),
      value      number,
      unit       varchar2(20),
      client_no  number,
      ts         timestamp(6) default systimestamp)');
  ddl('LT_JOBLOG', 'create table lt_joblog (
      run_id     number,
      client_no  number,
      phase      varchar2(30),
      info       varchar2(4000),
      ts         timestamp(6) default systimestamp)');

  -- Teiltests eines Dauertests verweisen auf den Dauertest-Lauf
  select count(*) into l_cnt from user_tab_columns where table_name = 'LT_RUN' and column_name = 'PARENT_RUN_ID';
  if l_cnt = 0 then
    execute immediate 'alter table lt_run add parent_run_id number';
    dbms_output.put_line('ergaenzt: LT_RUN.PARENT_RUN_ID');
  end if;
end;
/

create or replace package lt authid definer as
    -- Gemeinsame Konstanten
    c_group     constant varchar2(10) := 'LT';        -- Servergruppe aller Tests
    c_pw        constant varchar2(20) := 'LtTestPw';  -- Shutdown-Passwort aller Testserver
    c_disp_pipe constant varchar2(20) := 'LT_DISP';   -- Pipe des Test-Dispatchers

    -- Modi fuer die Workloads
    c_insession  constant varchar2(20) := 'INSESSION';
    c_server     constant varchar2(20) := 'SERVER';
    c_dispatcher constant varchar2(20) := 'DISPATCHER';

    -- Testlauf
    function  begin_run(p_test varchar2, p_mode varchar2, p_params varchar2 default null, p_parent number default null) return number;
    procedure check_that(p_run_id number, p_name varchar2, p_ok boolean, p_detail varchar2 default null);
    procedure metric(p_run_id number, p_name varchar2, p_value number, p_unit varchar2 default null, p_client number default null);
    procedure joblog(p_run_id number, p_client number, p_phase varchar2, p_info varchar2);
    procedure end_run(p_run_id number);
    function  run_started(p_run_id number) return timestamp;

    -- Server
    procedure start_server(p_pipe varchar2, p_dispatcher pls_integer default 0);
    procedure wait_servers_ready(p_pipes sys.odcivarchar2list, p_max_sec number default 20);
    function  stop_server(p_pipe varchar2) return boolean;
    procedure stop_all_servers;

    -- Jobs (parallele Clients, jeder Job = eigene Session mit leerem PGA)
    procedure run_job(p_name varchar2, p_plsql varchar2);
    function  wait_jobs(p_prefix varchar2, p_max_sec number) return boolean;

    -- Zaehlen in den LILAM-Tabellen (Prozesse ueber Namenspraefix)
    --   p_what: PROC, PROC_CLOSED, LOG, TRACE, EVENT, STEPS, ROUTES, BASELINE
    function  count_lilam(p_prefix varchar2, p_what varchar2) return number;
    function  wait_count(p_prefix varchar2, p_what varchar2, p_expected number, p_max_sec number) return number;
    function  internal_errors_since(p_ts timestamp) return number;

    -- Hilfen
    function  ms_since(p_ts timestamp) return number;
    function  my_pga_kb return number;           -- NULL ohne Grants (siehe 00_grants_als_sys.sql)
    function  server_pga_kb return number;       -- Summe PGA aller LILAM-Server; NULL ohne Grants

    -- Standard-Workload je Prozess und Operation:
    --   INFO, TRACE_START/TRACE_STOP (LT_ACTION), MARK_EVENT (LT_EVENT), PROC_STEP_DONE
    -- Erwartung je Prozess: LOG = TRACE = EVENT = STEPS = p_ops
    procedure workload(
        p_run_id      number,
        p_client      number,
        p_mode        varchar2,
        p_proc_name   varchar2,
        p_processes   number,
        p_ops         number,
        p_sleep_ms    number  default 0,
        p_interleave  boolean default false,   -- TRUE: erst alle Prozesse oeffnen, dann Operationen reihum
        p_scope       varchar2 default null);  -- p_baselineScope fuer NEW_SESSION (NULL = Default: Prozessname)

    -- Dauerlauf: wiederholt kurze Prozesszyklen bis p_end_ts, mit Pausen und Messwerten
    procedure endurance(
        p_run_id       number,
        p_client       number,
        p_mode         varchar2,
        p_proc_name    varchar2,
        p_end_ts       timestamp,
        p_ops          number default 20,
        p_max_pause_s  number default 30,
        p_metric_min   number default 10);

    -- Prozesszyklen: viele Prozesse mit vollstaendigem Lebenszyklus, p_window davon gleichzeitig offen.
    -- Je Prozess: NEW_SESSION (steps_todo = p_ops), SET_PROCESS_STATUS 'RUNNING',
    --   p_ops Operationen (INFO, TRACE, EVENT, PROC_STEP_DONE), zur Haelfte Status 'HALF',
    --   am Ende Rueckleseprobe GET_PROC_STEPS_DONE = p_ops, CLOSE_SESSION mit Steps, Info 'DONE ...', Status 2.
    -- Operationen werden zufaellig auf die offenen Prozesse verteilt, mit kurzen Zufallspausen.
    procedure lifecycle(
        p_run_id        number,
        p_client        number,
        p_mode          varchar2,
        p_proc_name     varchar2,
        p_processes     number,
        p_ops           number,
        p_window        number default 3,
        p_max_pause_ms  number default 20);

    -- Pruefung nach lifecycle: alle Prozesse mit korrektem Endzustand in _PROC,
    -- vollstaendige Logs/Traces/Events, keine Abweichungen beim Rueckleseprobe,
    -- optional Verteilung auf mindestens p_min_servers Server
    procedure verify_lifecycle(
        p_run_id       number,
        p_prefix       varchar2,
        p_processes    number,
        p_ops          number,
        p_check_routes boolean default false,
        p_min_servers  number  default 0,
        p_max_wait_sec number  default 180);

    -- Ein einzelner "Weck-Aufruf" nach einer Ruhephase des Servers:
    --   INFO + MARK_EVENT fuer einen bestehenden Prozess, optional neuer Prozess (oeffnen/schliessen)
    --   Laeuft im Modus DISPATCHER als Job (frische Session), im Modus SERVER in der aufrufenden Session
    procedure wake_call(p_run_id number, p_mode varchar2, p_pid number, p_idle_s number,
                        p_proc_name varchar2, p_new_session boolean default true);

    -- Standard-Pruefung nach einer Workload (wartet, bis alle Daten persistiert sind):
    --   Prozesse vorhanden und geschlossen, LOG/TRACE/EVENT/STEPS je = processes * ops,
    --   Baseline: genau p_baseline_scopes Scopes (Name beginnt mit p_prefix), jeder zaehlt
    --   processes * ops / p_baseline_scopes Traces; 0 = es darf keine Baseline entstehen,
    --   keine Routen uebrig (decoupled), keine Job- und internen Fehler
    procedure verify_standard(
        p_run_id          number,
        p_prefix          varchar2,
        p_processes       number,
        p_ops             number,
        p_check_routes    boolean default false,
        p_max_wait_sec    number  default 120,
        p_baseline_scopes number  default 1);

    -- ==================================================================
    -- Tests als Funktionen (die Skripte unter INSESSION/, DECOUPLED/, FEATURES/ rufen diese auf)
    --
    -- Gemeinsame Parameter:
    --   p_mode      c_insession | c_server | c_dispatcher
    --   p_manage    TRUE: der Test startet und stoppt seine Server selbst (Einzeltest)
    --               FALSE: die Server laufen bereits (z.B. im Dauertest)
    --   p_max_wait  max. Wartezeit in s je Pruefung auf vollstaendige Daten
    --   p_parent    run_id eines uebergeordneten Laufs (Dauertest), sonst NULL
    -- Rueckgabe: run_id des Testlaufs (bei PARALLELBETRIEB die der letzten Variante)
    -- ==================================================================
    function t_lasttest(p_mode varchar2, p_ops number default 5000,
                        p_manage boolean default true, p_max_wait number default 300, p_parent number default null) return number;

    function t_massentest(p_mode varchar2, p_processes number default 200, p_ops number default 20,
                          p_manage boolean default true, p_max_wait number default 300, p_parent number default null) return number;

    -- p_variants: Folge aus A, B, C, D; p_clients NULL = 8 (INSESSION) bzw. 10 (decoupled)
    function t_parallel(p_mode varchar2, p_variants varchar2 default 'ABCD', p_clients number default null,
                        p_processes number default 2, p_ops number default 200,
                        p_manage boolean default true, p_max_wait number default 300, p_parent number default null) return number;

    -- p_clients NULL = 8 (INSESSION) bzw. 10 (decoupled)
    function t_zyklen(p_mode varchar2, p_clients number default null, p_processes number default 30, p_ops number default 20,
                      p_window number default 3, p_pause_ms number default 20,
                      p_manage boolean default true, p_max_wait number default 300, p_parent number default null) return number;

    -- nur decoupled
    function t_wakeup(p_mode varchar2, p_idle sys.odcinumberlist default sys.odcinumberlist(5, 16, 30, 65),
                      p_manage boolean default true, p_parent number default null) return number;

    -- INSESSION und SERVER in einem Lauf
    function t_logtext(p_manage boolean default true, p_parent number default null) return number;
    function t_baseline_scope(p_manage boolean default true, p_parent number default null) return number;

    -- Speicher: PGA-Wachstum je Prozess in Client, Workern und Dispatcher (INSESSION, SERVER, DISPATCHER)
    -- sowie Fallback beim Schreiben (fehlerhafte Zeile wird uebersprungen, die uebrigen bleiben erhalten)
    function t_speicher(p_procs number default 5000, p_manage boolean default true, p_parent number default null) return number;

    -- Lastspitze: p_clients senden p_seconds lang so schnell wie moeglich; danach muessen alle Daten
    -- vollstaendig ankommen und ein neuer Prozess wieder normal arbeiten (Erholung). Nur decoupled.
    function t_lastspitze(p_mode varchar2, p_clients number default 6, p_seconds number default 30,
                          p_manage boolean default true, p_max_wait number default 300, p_parent number default null) return number;

    -- Bausteine der Lastspitze (laufen als Jobs)
    procedure burst(p_run_id number, p_client number, p_mode varchar2, p_proc_name varchar2, p_end_ts timestamp);
    procedure probe(p_run_id number, p_mode varchar2, p_proc_name varchar2, p_ops number);

    -- ==================================================================
    -- Dauertest als Kombination der Tests
    --   dauertest_start  startet Server, Hintergrund-Clients und den Steuer-Job; kehrt sofort zurueck
    --   dauertest_run    Steuer-Job: fuehrt bis p_end_ts Teiltests aus (je als eigener Job),
    --                    loescht die LILAM-Daten bestandener Teiltests, legt Pausen ein
    --   dauertest_auswertung  nach Ablauf: Teiltests, Stabilitaet, Hintergrund-Clients
    --
    --   p_modes   Komma-Liste aus INSESSION, SERVER, DISPATCHER
    --   p_order   'RANDOM' (gewichtet zufaellig) oder 'SEQ' (Katalog der Reihe nach, dann von vorn)
    -- ==================================================================
    function dauertest_start(p_hours number default 10, p_modes varchar2 default 'INSESSION,SERVER,DISPATCHER',
                             p_order varchar2 default 'RANDOM', p_bg_clients number default 2,
                             p_pause_max_s number default 120, p_lastspitze boolean default true) return number;
    procedure dauertest_run(p_run_id number, p_end_ts timestamp, p_modes varchar2, p_order varchar2,
                            p_pause_max_s number, p_lastspitze number);
    procedure dauertest_auswertung(p_run_id number default null);

    -- Teiltest im Dauertest (laeuft als Job)
    procedure run_step(p_parent number, p_test varchar2, p_mode varchar2);

    -- LILAM-Daten aller Prozesse mit Namenspraefix loeschen (inkl. Routen, Scopes, Baselines)
    procedure purge_prefix(p_prefix varchar2);
end lt;
/

create or replace package body lt as

    g_check_no pls_integer := 0;
    c_job_wait constant number := 900;   -- max. Wartezeit in s auf das Ende der Client-Jobs

    ----------------------------------------------------------------------
    function ms_since(p_ts timestamp) return number is
        l_d interval day(9) to second(6) := systimestamp - p_ts;
    begin
        return round(extract(day from l_d) * 86400000 + extract(hour from l_d) * 3600000
                   + extract(minute from l_d) * 60000 + extract(second from l_d) * 1000, 1);
    end;

    ----------------------------------------------------------------------
    function begin_run(p_test varchar2, p_mode varchar2, p_params varchar2 default null, p_parent number default null) return number is
        pragma autonomous_transaction;
        l_id number;
    begin
        insert into lt_run(test_name, mode_name, params, parent_run_id) values (p_test, p_mode, p_params, p_parent)
        returning run_id into l_id;
        commit;
        g_check_no := 0;
        dbms_output.put_line('=== ' || p_test || ' (' || p_mode || ')  run_id=' || l_id);
        if p_params is not null then dbms_output.put_line('    Parameter: ' || p_params); end if;
        return l_id;
    end;

    function run_started(p_run_id number) return timestamp is
        l_ts timestamp;
    begin
        select started into l_ts from lt_run where run_id = p_run_id;
        return l_ts;
    end;

    ----------------------------------------------------------------------
    procedure check_that(p_run_id number, p_name varchar2, p_ok boolean, p_detail varchar2 default null) is
        pragma autonomous_transaction;
    begin
        g_check_no := g_check_no + 1;
        insert into lt_check(run_id, check_no, check_name, ok, detail)
        values (p_run_id, g_check_no, p_name, case when p_ok then 1 else 0 end, p_detail);
        commit;
        dbms_output.put_line(case when p_ok then 'OK     ' else 'FEHLER ' end || p_name
                             || case when p_detail is not null then '  [' || p_detail || ']' end);
    end;

    procedure metric(p_run_id number, p_name varchar2, p_value number, p_unit varchar2 default null, p_client number default null) is
        pragma autonomous_transaction;
    begin
        insert into lt_metric(run_id, metric, value, unit, client_no) values (p_run_id, p_name, p_value, p_unit, p_client);
        commit;
    end;

    procedure joblog(p_run_id number, p_client number, p_phase varchar2, p_info varchar2) is
        pragma autonomous_transaction;
    begin
        insert into lt_joblog(run_id, client_no, phase, info) values (p_run_id, p_client, p_phase, substr(p_info, 1, 4000));
        commit;
    end;

    procedure end_run(p_run_id number) is
        pragma autonomous_transaction;
        l_ok number; l_fail number;
        l_dur interval day to second;
    begin
        select nvl(sum(ok), 0), count(*) - nvl(sum(ok), 0) into l_ok, l_fail from lt_check where run_id = p_run_id;
        select systimestamp - started into l_dur from lt_run where run_id = p_run_id;
        update lt_run set ended = systimestamp, status = case when l_fail = 0 then 'PASSED' else 'FAILED' end
         where run_id = p_run_id;
        commit;
        dbms_output.put_line('--- Messwerte');
        for m in (select metric, round(avg(value), 2) v, unit, count(*) n from lt_metric where run_id = p_run_id
                   group by metric, unit order by metric) loop
            dbms_output.put_line('    ' || rpad(m.metric, 32) || m.v || ' ' || m.unit || case when m.n > 1 then '  (Mittel aus ' || m.n || ')' end);
        end loop;
        dbms_output.put_line('    ' || rpad('Gesamtlaufzeit Test', 32)
                             || to_char(round(extract(day from l_dur) * 86400 + extract(hour from l_dur) * 3600
                                              + extract(minute from l_dur) * 60 + extract(second from l_dur), 1), 'FM999999990.0')
                             || ' s  ('
                             || to_char(extract(hour from l_dur) + extract(day from l_dur) * 24, 'FM00') || ':'
                             || to_char(extract(minute from l_dur), 'FM00') || ':'
                             || to_char(trunc(extract(second from l_dur)), 'FM00') || ')');
        dbms_output.put_line('=== Ergebnis run_id=' || p_run_id || ': ' || l_ok || ' OK, ' || l_fail || ' FEHLER  -> '
                             || case when l_fail = 0 then 'BESTANDEN' else 'NICHT BESTANDEN' end);
    end;

    ----------------------------------------------------------------------
    -- Server
    ----------------------------------------------------------------------
    procedure start_server(p_pipe varchar2, p_dispatcher pls_integer default 0) is
        l_msg varchar2(4000);
    begin
        -- Alle Test-Server mit Leistungsstufe MID (1.500 Nachrichten/s je Prozess)
        l_msg := lilam.create_server(p_pipe, c_group, c_pw, p_dispatcher, p_perfServer => lilam.C_SERVER_PERF_MID);
        dbms_output.put_line('    ' || l_msg);
    end;

    procedure wait_servers_ready(p_pipes sys.odcivarchar2list, p_max_sec number default 20) is
        l_cnt number := 0; l_waited number := 0;
    begin
        loop
            begin
                execute immediate
                   'select count(*) from lilam_server_registry where is_active = 1
                       and last_activity > systimestamp - interval ''10'' second
                       and pipe_name in (select column_value from table(:1))'
                   into l_cnt using p_pipes;
            exception when others then l_cnt := 0;
            end;
            exit when l_cnt = p_pipes.count or l_waited >= p_max_sec;
            dbms_session.sleep(0.5); l_waited := l_waited + 0.5;
        end loop;
        dbms_output.put_line('    Server bereit: ' || l_cnt || '/' || p_pipes.count);
    end;

    function stop_server(p_pipe varchar2) return boolean is
        l_chan varchar2(60) := 'LT_SHUT_' || sys_context('USERENV', 'SID') || '_' || to_char(systimestamp, 'SSFF3');
        l_st   pls_integer;
        l_cnt  number := 1;
        l_waited number := 0;
    begin
        dbms_pipe.reset_buffer;
        dbms_pipe.pack_message('{"header":{"msg_type":"API_CALL","request":"SERVER_SHUTDOWN","response":"' || l_chan
                               || '"},"payload":{"pipe_name":"' || p_pipe || '","shutdown_password":"' || c_pw || '"}}');
        l_st := dbms_pipe.send_message(p_pipe, timeout => 2);
        l_st := dbms_pipe.receive_message(l_chan, timeout => 10);
        l_st := dbms_pipe.remove_pipe(l_chan);
        loop
            select count(*) into l_cnt from user_scheduler_jobs where job_name = upper(p_pipe);
            exit when l_cnt = 0 or l_waited >= 15;
            dbms_session.sleep(0.5); l_waited := l_waited + 0.5;
        end loop;
        return l_cnt = 0;
    end;

    procedure stop_all_servers is
        l_dummy boolean;
    begin
        -- zuerst Dispatcher, dann Worker
        for s in (select job_name from user_scheduler_jobs where job_name like 'LT\_%' escape '\'
                     and job_name not like 'LT\_C%' escape '\'
                   order by case when job_name = c_disp_pipe then 0 else 1 end) loop
            l_dummy := stop_server(s.job_name);
            if not l_dummy then
                begin dbms_scheduler.stop_job(s.job_name); exception when others then null; end;
            end if;
            dbms_output.put_line('    gestoppt: ' || s.job_name);
        end loop;
    end;

    ----------------------------------------------------------------------
    -- Jobs
    ----------------------------------------------------------------------
    procedure run_job(p_name varchar2, p_plsql varchar2) is
    begin
        dbms_scheduler.create_job(job_name => p_name, job_type => 'PLSQL_BLOCK', job_action => p_plsql,
                                  enabled => true, auto_drop => true);
    end;

    function wait_jobs(p_prefix varchar2, p_max_sec number) return boolean is
        l_cnt number; l_waited number := 0;
    begin
        loop
            -- '_' im Praefix woertlich nehmen (sonst passt z.B. LT_C10_ auch auf LT_C100_1)
            select count(*) into l_cnt from user_scheduler_jobs
             where job_name like replace(p_prefix, '_', '\_') || '%' escape '\';
            exit when l_cnt = 0 or l_waited >= p_max_sec;
            dbms_session.sleep(1); l_waited := l_waited + 1;
        end loop;
        return l_cnt = 0;
    end;

    ----------------------------------------------------------------------
    -- Zaehlen
    ----------------------------------------------------------------------
    function count_lilam(p_prefix varchar2, p_what varchar2) return number is
        l_sql varchar2(1000);
        l_n   number;
        l_p   varchar2(200) := replace(p_prefix, '_', '\_') || '%';
    begin
        l_sql := case upper(p_what)
            when 'PROC'        then 'select count(*) from lilam_proc where process_name like :1 escape ''\'''
            when 'PROC_CLOSED' then 'select count(*) from lilam_proc where process_name like :1 escape ''\'' and process_end is not null'
            when 'LOG'         then 'select count(*) from lilam_log l join lilam_proc p on p.id = l.process_id where p.process_name like :1 escape ''\'''
            when 'TRACE'       then 'select count(*) from lilam_mon m join lilam_proc p on p.id = m.process_id where p.process_name like :1 escape ''\'' and m.mon_type = 1'
            when 'EVENT'       then 'select count(*) from lilam_mon m join lilam_proc p on p.id = m.process_id where p.process_name like :1 escape ''\'' and m.mon_type = 0'
            when 'STEPS'       then 'select nvl(sum(steps_done), 0) from lilam_proc where process_name like :1 escape ''\'''
            when 'ROUTES'      then 'select count(*) from lilam_process_route r join lilam_proc p on p.id = r.process_id where p.process_name like :1 escape ''\'''
            when 'BASELINE'    then 'select nvl(sum(b.action_count), 0) from lilam_baselines b join lilam_scopes s on s.scope_id = b.scope_id where s.scope_name like upper(:1) escape ''\'' and b.action_name = ''LT_ACTION'''
        end;
        execute immediate l_sql into l_n using l_p;
        return l_n;
    exception
        when others then return -1;
    end;

    function wait_count(p_prefix varchar2, p_what varchar2, p_expected number, p_max_sec number) return number is
        l_t0 timestamp := systimestamp;
    begin
        loop
            exit when count_lilam(p_prefix, p_what) >= p_expected;
            if ms_since(l_t0) > p_max_sec * 1000 then return -1; end if;
            dbms_session.sleep(0.25);
        end loop;
        return ms_since(l_t0);
    end;

    function internal_errors_since(p_ts timestamp) return number is
        l_n number;
    begin
        execute immediate 'select count(*) from lilam_log_internal where log_timestamp >= :1' into l_n using p_ts;
        return l_n;
    exception
        when others then return 0;   -- Tabelle existiert erst nach dem ersten internen Fehler
    end;

    ----------------------------------------------------------------------
    -- Speicher (benoetigt direkte Grants, siehe 00_grants_als_sys.sql)
    ----------------------------------------------------------------------
    function my_pga_kb return number is
        l_n number;
    begin
        execute immediate 'select round(m.value / 1024) from v$mystat m join v$statname s on s.statistic# = m.statistic#
                            where s.name = ''session pga memory''' into l_n;
        return l_n;
    exception when others then return null;
    end;

    function server_pga_kb return number is
        l_n number;
    begin
        execute immediate 'select round(sum(p.pga_used_mem) / 1024) from v$session s join v$process p on p.addr = s.paddr
                            where s.module like ''LILAM_SERVER%''' into l_n;
        return l_n;
    exception when others then return null;
    end;

    ----------------------------------------------------------------------
    -- Workloads
    ----------------------------------------------------------------------
    function open_process(p_mode varchar2, p_proc_name varchar2, p_scope varchar2 default null) return number is
    begin
        if p_mode = c_insession then
            return lilam.new_session(p_proc_name, lilam.logLevelInfo, p_baselineScope => p_scope);
        else
            if p_mode = c_dispatcher then
                lilam.set_dispatcher_pipe(c_disp_pipe);
            end if;
            return lilam.server_new_session(p_proc_name, c_group, lilam.logLevelInfo, p_baselineScope => p_scope);
        end if;
    end;

    procedure one_op(p_pid number, p_client number, p_op number) is
    begin
        lilam.info(p_pid, 'c' || p_client || ' op ' || p_op);
        lilam.trace_start(p_pid, 'LT_ACTION');
        lilam.trace_stop(p_pid, 'LT_ACTION');
        lilam.mark_event(p_pid, 'LT_EVENT');
        lilam.proc_step_done(p_pid);
    end;

    procedure workload(
        p_run_id      number,
        p_client      number,
        p_mode        varchar2,
        p_proc_name   varchar2,
        p_processes   number,
        p_ops         number,
        p_sleep_ms    number  default 0,
        p_interleave  boolean default false,
        p_scope       varchar2 default null)
    is
        type t_pids is table of number index by pls_integer;
        l_pids  t_pids;
        l_t0    timestamp := systimestamp;
        l_open  number := 0;
        l_calls number := 0;
        l_t     timestamp;
    begin
        joblog(p_run_id, p_client, 'START', p_mode || ' name=' || p_proc_name || ' scope=' || nvl(p_scope, '(default)')
                                            || ' processes=' || p_processes || ' ops=' || p_ops);
        if p_interleave then
            l_t := systimestamp;
            for p in 1 .. p_processes loop
                l_pids(p) := open_process(p_mode, p_proc_name, p_scope);
            end loop;
            l_open := ms_since(l_t);
            for o in 1 .. p_ops loop
                for p in 1 .. p_processes loop
                    one_op(l_pids(p), p_client, o);
                    l_calls := l_calls + 5;
                end loop;
                if p_sleep_ms > 0 then dbms_session.sleep(p_sleep_ms / 1000); end if;
            end loop;
            for p in 1 .. p_processes loop
                lilam.close_session(l_pids(p));
            end loop;
        else
            for p in 1 .. p_processes loop
                l_t := systimestamp;
                l_pids(p) := open_process(p_mode, p_proc_name, p_scope);
                l_open := l_open + ms_since(l_t);
                for o in 1 .. p_ops loop
                    one_op(l_pids(p), p_client, o);
                    l_calls := l_calls + 5;
                    if p_sleep_ms > 0 then dbms_session.sleep(p_sleep_ms / 1000); end if;
                end loop;
                lilam.close_session(l_pids(p));
            end loop;
        end if;
        metric(p_run_id, 'client_elapsed_ms', ms_since(l_t0), 'ms', p_client);
        metric(p_run_id, 'client_api_calls', l_calls, 'calls', p_client);
        metric(p_run_id, 'client_open_ms_total', l_open, 'ms', p_client);
        joblog(p_run_id, p_client, 'END', 'ok');
    exception
        when others then
            joblog(p_run_id, p_client, 'ERROR', sqlerrm || ' | ' || dbms_utility.format_error_backtrace);
    end;

    procedure endurance(
        p_run_id       number,
        p_client       number,
        p_mode         varchar2,
        p_proc_name    varchar2,
        p_end_ts       timestamp,
        p_ops          number default 20,
        p_max_pause_s  number default 30,
        p_metric_min   number default 10)
    is
        l_pid      number;
        l_t        timestamp;
        l_last_m   timestamp := systimestamp;
        l_cycles   number := 0;
        l_sum_ms   number := 0;
        l_max_ms   number := 0;
        l_cycle_ms number;
        l_pause    number;
    begin
        joblog(p_run_id, p_client, 'START', p_mode || ' bis ' || to_char(p_end_ts, 'DD.MM. HH24:MI'));
        while systimestamp < p_end_ts loop
            begin
                l_t := systimestamp;
                l_pid := open_process(p_mode, p_proc_name);
                for o in 1 .. p_ops loop
                    one_op(l_pid, p_client, o);
                end loop;
                lilam.close_session(l_pid);
                l_cycle_ms := ms_since(l_t);
                l_cycles := l_cycles + 1;
                l_sum_ms := l_sum_ms + l_cycle_ms;
                l_max_ms := greatest(l_max_ms, l_cycle_ms);
            exception
                when others then
                    joblog(p_run_id, p_client, 'ERROR', sqlerrm || ' | ' || dbms_utility.format_error_backtrace);
            end;

            if ms_since(l_last_m) >= p_metric_min * 60000 then
                metric(p_run_id, 'cycles', l_cycles, 'count', p_client);
                metric(p_run_id, 'cycle_avg_ms', round(l_sum_ms / greatest(l_cycles, 1), 1), 'ms', p_client);
                metric(p_run_id, 'cycle_max_ms', l_max_ms, 'ms', p_client);
                metric(p_run_id, 'client_pga_kb', my_pga_kb, 'KB', p_client);
                metric(p_run_id, 'server_pga_kb', server_pga_kb, 'KB', p_client);
                l_cycles := 0; l_sum_ms := 0; l_max_ms := 0; l_last_m := systimestamp;
            end if;

            -- zufaellige Pause, gelegentlich laenger als 15 s (Ruhezustand des Servers)
            l_pause := round(dbms_random.value(0, p_max_pause_s), 1);
            dbms_session.sleep(l_pause);
        end loop;
        joblog(p_run_id, p_client, 'END', 'ok');
    exception
        when others then
            joblog(p_run_id, p_client, 'ERROR', sqlerrm || ' | ' || dbms_utility.format_error_backtrace);
    end;

    procedure lifecycle(
        p_run_id        number,
        p_client        number,
        p_mode          varchar2,
        p_proc_name     varchar2,
        p_processes     number,
        p_ops           number,
        p_window        number default 3,
        p_max_pause_ms  number default 20)
    is
        type t_slot is record (pid number, proc_no number, ops_done number := 0);
        type t_slots is table of t_slot index by pls_integer;
        l_slots    t_slots;
        l_started  number := 0;
        l_closed   number := 0;
        l_open     number := 0;
        l_t0       timestamp := systimestamp;
        l_t        timestamp;
        l_open_ms  number := 0;
        l_close_ms number := 0;
        l_read_ms  number := 0;
        l_idx      pls_integer;
        l_steps    number;

        procedure start_in(p_slot pls_integer) is
        begin
            l_started := l_started + 1;
            l_t := systimestamp;
            if p_mode = c_insession then
                l_slots(p_slot).pid := lilam.new_session(p_processName => p_proc_name, p_logLevel => lilam.logLevelInfo,
                                                      p_procStepsToDo => p_ops, p_daysToKeep => null);
            else
                if p_mode = c_dispatcher then lilam.set_dispatcher_pipe(c_disp_pipe); end if;
                l_slots(p_slot).pid := lilam.server_new_session(p_proc_name, c_group, lilam.logLevelInfo, p_ops, null, 'LILAM');
            end if;
            l_open_ms := l_open_ms + ms_since(l_t);
            l_slots(p_slot).proc_no  := l_started;
            l_slots(p_slot).ops_done := 0;
            lilam.set_process_status(l_slots(p_slot).pid, 1, 'RUNNING');
            l_open := l_open + 1;
        end;

        procedure finish(p_slot pls_integer) is
            l_pid number := l_slots(p_slot).pid;
        begin
            l_t := systimestamp;
            l_steps := lilam.get_proc_steps_done(l_pid);
            l_read_ms := l_read_ms + ms_since(l_t);
            if nvl(l_steps, -1) != p_ops then
                joblog(p_run_id, p_client, 'MISMATCH', 'pid=' || l_pid || ' GET_PROC_STEPS_DONE=' || l_steps || ' erwartet ' || p_ops);
            end if;
            l_t := systimestamp;
            lilam.close_session(l_pid, 'DONE c' || p_client || ' p' || l_slots(p_slot).proc_no, 2, p_ops);
            l_close_ms := l_close_ms + ms_since(l_t);
            l_slots(p_slot).pid := null;
            l_closed := l_closed + 1;
            l_open := l_open - 1;
        end;
    begin
        joblog(p_run_id, p_client, 'START', p_mode || ' processes=' || p_processes || ' ops=' || p_ops || ' window=' || p_window);
        for i in 1 .. least(p_window, p_processes) loop
            start_in(i);
        end loop;

        while l_open > 0 loop
            -- zufaelligen offenen Slot waehlen
            loop
                l_idx := trunc(dbms_random.value(1, least(p_window, p_processes) + 1));
                exit when l_slots(l_idx).pid is not null;
            end loop;

            l_slots(l_idx).ops_done := l_slots(l_idx).ops_done + 1;
            one_op(l_slots(l_idx).pid, p_client, l_slots(l_idx).ops_done);
            if l_slots(l_idx).ops_done = trunc(p_ops / 2) then
                lilam.set_process_status(l_slots(l_idx).pid, 1, 'HALF');
            end if;

            if l_slots(l_idx).ops_done >= p_ops then
                finish(l_idx);
                if l_started < p_processes then
                    start_in(l_idx);
                end if;
            end if;

            if p_max_pause_ms > 0 then
                dbms_session.sleep(round(dbms_random.value(0, p_max_pause_ms)) / 1000);
            end if;
        end loop;

        metric(p_run_id, 'client_elapsed_ms', ms_since(l_t0), 'ms', p_client);
        metric(p_run_id, 'client_processes', l_closed, 'count', p_client);
        metric(p_run_id, 'avg_new_session_ms', round(l_open_ms / greatest(l_started, 1), 1), 'ms', p_client);
        metric(p_run_id, 'avg_close_session_ms', round(l_close_ms / greatest(l_closed, 1), 1), 'ms', p_client);
        metric(p_run_id, 'avg_get_steps_ms', round(l_read_ms / greatest(l_closed, 1), 1), 'ms', p_client);
        joblog(p_run_id, p_client, 'END', 'ok');
    exception
        when others then
            joblog(p_run_id, p_client, 'ERROR', sqlerrm || ' | ' || dbms_utility.format_error_backtrace);
    end;

    procedure wake_call(p_run_id number, p_mode varchar2, p_pid number, p_idle_s number,
                        p_proc_name varchar2, p_new_session boolean default true) is
        l_t   timestamp := systimestamp;
        l_pid number;
    begin
        if p_mode = c_dispatcher then
            lilam.set_dispatcher_pipe(c_disp_pipe);
        end if;
        lilam.info(p_pid, 'wake after ' || p_idle_s || ' s');
        lilam.mark_event(p_pid, 'LT_WAKE');
        metric(p_run_id, 'wake_call_ms_' || p_idle_s || 's', ms_since(l_t), 'ms');
        if p_new_session then
            l_t := systimestamp;
            l_pid := open_process(p_mode, p_proc_name || '_N');
            metric(p_run_id, 'wake_new_session_ms_' || p_idle_s || 's', ms_since(l_t), 'ms');
            if nvl(l_pid, -1) <= 0 then
                joblog(p_run_id, p_idle_s, 'ERROR', 'NEW_SESSION nach ' || p_idle_s || ' s Ruhe lieferte ' || l_pid);
            else
                lilam.info(l_pid, 'new after ' || p_idle_s || ' s');
                lilam.close_session(l_pid);
            end if;
        end if;
    exception
        when others then
            joblog(p_run_id, p_idle_s, 'ERROR', sqlerrm || ' | ' || dbms_utility.format_error_backtrace);
    end;

    procedure verify_standard(
        p_run_id          number,
        p_prefix          varchar2,
        p_processes       number,
        p_ops             number,
        p_check_routes    boolean default false,
        p_max_wait_sec    number  default 120,
        p_baseline_scopes number  default 1)
    is
        l_exp  number := p_processes * p_ops;
        l_ms   number;
        l_n    number;
        l_sc   number;
        l_min  number;
        l_max  number;
        l_per  number;
    begin
        l_ms := wait_count(p_prefix, 'PROC_CLOSED', p_processes, p_max_wait_sec);
        l_n  := count_lilam(p_prefix, 'PROC_CLOSED');
        check_that(p_run_id, 'Alle Prozesse angelegt und geschlossen', l_n = p_processes, l_n || '/' || p_processes);

        for w in (select column_value what from table(sys.odcivarchar2list('LOG', 'TRACE', 'EVENT'))) loop
            l_ms := wait_count(p_prefix, w.what, l_exp, p_max_wait_sec);
            l_n  := count_lilam(p_prefix, w.what);
            check_that(p_run_id, 'Anzahl ' || w.what || ' = ' || l_exp, l_n = l_exp, 'ist ' || l_n);
            if l_ms >= 0 then metric(p_run_id, 'drain_' || lower(w.what) || '_ms', l_ms, 'ms'); end if;
        end loop;

        l_n := count_lilam(p_prefix, 'STEPS');
        check_that(p_run_id, 'Summe steps_done = ' || l_exp, l_n = l_exp, 'ist ' || l_n);

        -- Baseline: Anzahl Scopes und Zaehlung je Scope
        if p_baseline_scopes > 0 then
            l_ms := wait_count(p_prefix, 'BASELINE', l_exp, 10);
        else
            dbms_session.sleep(2);   -- etwaige Baseline-Abgleiche abwarten
        end if;
        execute immediate
           'select count(*), min(cnt), max(cnt), nvl(sum(cnt), 0)
              from (select s.scope_name, sum(b.action_count) cnt
                      from lilam_baselines b join lilam_scopes s on s.scope_id = b.scope_id
                     where s.scope_name like upper(:1) escape ''\'' and b.action_name = ''LT_ACTION''
                     group by s.scope_name)'
           into l_sc, l_min, l_max, l_n using replace(p_prefix, '_', '\_') || '%';
        if p_baseline_scopes = 0 then
            check_that(p_run_id, 'Keine Baseline entstanden (Scope abgeschaltet)', l_sc = 0, l_sc || ' Scopes, ' || l_n || ' Traces');
        else
            l_per := l_exp / p_baseline_scopes;
            check_that(p_run_id, 'Baseline: ' || p_baseline_scopes || ' Scope(s), je ' || l_per || ' Traces',
                       l_sc = p_baseline_scopes and l_min = l_per and l_max = l_per,
                       l_sc || ' Scopes, je ' || l_min || '..' || l_max || ', Summe ' || l_n);
        end if;

        if p_check_routes then
            l_n := count_lilam(p_prefix, 'ROUTES');
            check_that(p_run_id, 'Keine Prozess-Routen uebrig', l_n = 0, 'ist ' || l_n);
        end if;

        select count(*) into l_n from lt_joblog where run_id = p_run_id and phase = 'ERROR';
        check_that(p_run_id, 'Keine Fehler in den Client-Jobs', l_n = 0, l_n || ' Fehler');

        l_n := internal_errors_since(run_started(p_run_id));
        check_that(p_run_id, 'Keine internen LILAM-Fehler', l_n = 0, l_n || ' Eintraege');
    end;

    procedure verify_lifecycle(
        p_run_id       number,
        p_prefix       varchar2,
        p_processes    number,
        p_ops          number,
        p_check_routes boolean default false,
        p_min_servers  number  default 0,
        p_max_wait_sec number  default 180)
    is
        l_exp number := p_processes * p_ops;
        l_ms  number;
        l_n   number;
        l_p   varchar2(200) := replace(p_prefix, '_', '\_') || '%';
        l_det varchar2(4000);
    begin
        l_ms := wait_count(p_prefix, 'PROC_CLOSED', p_processes, p_max_wait_sec);
        l_n  := count_lilam(p_prefix, 'PROC_CLOSED');
        check_that(p_run_id, 'Alle ' || p_processes || ' Prozesse angelegt und geschlossen', l_n = p_processes, 'ist ' || l_n);

        -- Endzustand jedes Prozesses in _PROC
        execute immediate
           'select count(*) from lilam_proc where process_name like :1 escape ''\''
               and status = 2 and steps_todo = :2 and steps_done = :3 and info like ''DONE c%'' and process_end is not null'
           into l_n using l_p, p_ops, p_ops;
        check_that(p_run_id, 'Endzustand korrekt (status 2, steps_todo/done ' || p_ops || ', info DONE)', l_n = p_processes,
                   l_n || '/' || p_processes);
        if l_n != p_processes then
            execute immediate
               'select listagg(id || '':'' || status || ''/'' || steps_todo || ''/'' || steps_done || ''/'' || substr(info, 1, 20), '', '')
                       within group (order by id)
                  from (select id, status, steps_todo, steps_done, info from lilam_proc where process_name like :1 escape ''\''
                           and not (nvl(status, -1) = 2 and nvl(steps_todo, -1) = :2 and nvl(steps_done, -1) = :3
                                    and info like ''DONE c%'' and process_end is not null)
                         fetch first 5 rows only)' into l_det using l_p, p_ops, p_ops;
            dbms_output.put_line('       Beispiele (id:status/todo/done/info): ' || l_det);
        end if;

        for w in (select column_value what from table(sys.odcivarchar2list('LOG', 'TRACE', 'EVENT'))) loop
            l_ms := wait_count(p_prefix, w.what, l_exp, p_max_wait_sec);
            l_n  := count_lilam(p_prefix, w.what);
            check_that(p_run_id, 'Anzahl ' || w.what || ' = ' || l_exp, l_n = l_exp, 'ist ' || l_n);
        end loop;

        select count(*) into l_n from lt_joblog where run_id = p_run_id and phase = 'MISMATCH';
        check_that(p_run_id, 'Rueckleseprobe GET_PROC_STEPS_DONE stimmt immer', l_n = 0, l_n || ' Abweichungen');

        l_n := count_lilam(p_prefix, 'BASELINE');
        check_that(p_run_id, 'Baseline zaehlt alle Traces = ' || l_exp, l_n = l_exp, 'ist ' || l_n);

        if p_check_routes then
            l_n := count_lilam(p_prefix, 'ROUTES');
            check_that(p_run_id, 'Keine Prozess-Routen uebrig', l_n = 0, 'ist ' || l_n);
        end if;

        if p_min_servers > 0 then
            execute immediate 'select count(distinct server_pipe) from lilam_proc where process_name like :1 escape ''\'''
               into l_n using l_p;
            check_that(p_run_id, 'Prozesse auf mindestens ' || p_min_servers || ' Server verteilt', l_n >= p_min_servers, l_n || ' Server');
        end if;

        select count(*) into l_n from lt_joblog where run_id = p_run_id and phase = 'ERROR';
        check_that(p_run_id, 'Keine Fehler in den Client-Jobs', l_n = 0, l_n || ' Fehler');

        l_n := internal_errors_since(run_started(p_run_id));
        check_that(p_run_id, 'Keine internen LILAM-Fehler', l_n = 0, l_n || ' Eintraege');
    end;


