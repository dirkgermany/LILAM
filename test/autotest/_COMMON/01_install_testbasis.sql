    procedure burst(p_run_id number, p_client number, p_mode varchar2, p_proc_name varchar2, p_end_ts timestamp) is
        l_pid number;
        l_ops number := 0;
        l_t0  timestamp;
    begin
        joblog(p_run_id, p_client, 'START', p_mode || ' burst bis ' || to_char(p_end_ts, 'HH24:MI:SS'));
        l_pid := open_process(p_mode, p_proc_name);
        l_t0 := systimestamp;
        while systimestamp < p_end_ts loop
            l_ops := l_ops + 1;
            one_op(l_pid, p_client, l_ops);
        end loop;
        lilam.close_session(l_pid);
        metric(p_run_id, 'client_ops', l_ops, 'ops', p_client);
        metric(p_run_id, 'client_api_calls', l_ops * 5, 'calls', p_client);
        metric(p_run_id, 'client_elapsed_ms', ms_since(l_t0), 'ms', p_client);
        joblog(p_run_id, p_client, 'END', 'ok');
    exception
        when others then
            joblog(p_run_id, p_client, 'ERROR', sqlerrm || ' | ' || dbms_utility.format_error_backtrace);
    end;

    procedure probe(p_run_id number, p_mode varchar2, p_proc_name varchar2, p_ops number) is
        l_pid number;
        l_t0  timestamp := systimestamp;
    begin
        l_pid := open_process(p_mode, p_proc_name);
        metric(p_run_id, 'probe_new_session_ms', ms_since(l_t0), 'ms');
        for i in 1 .. p_ops loop
            one_op(l_pid, 0, i);
        end loop;
        lilam.close_session(l_pid);
        metric(p_run_id, 'probe_ms', ms_since(l_t0), 'ms');
    exception
        when others then
            joblog(p_run_id, 0, 'ERROR', 'Probe: ' || sqlerrm || ' | ' || dbms_utility.format_error_backtrace);
    end;

    function t_lastspitze(p_mode varchar2, p_clients number default 6, p_seconds number default 30,
                          p_manage boolean default true, p_max_wait number default 300, p_parent number default null) return number is
        c_probe_ops constant number := 100;
        l_run    number;
        l_burst  varchar2(60);
        l_probe  varchar2(60);
        l_end    timestamp;
        l_ops    number;
        l_ms     number;
        l_n      number;
        l_t      timestamp;
    begin
        l_run := begin_run('LASTSPITZE', p_mode, 'clients=' || p_clients || ' seconds=' || p_seconds, p_parent);
        l_burst := 'LT_' || l_run || '_SPITZE';
        l_probe := 'LT_' || l_run || '_PROBE';
        if p_mode = c_insession then
            raise_application_error(-20000, 'LASTSPITZE ist nur im Decoupled-Mode sinnvoll');
        end if;
        if p_manage then setup_servers(p_mode, 2); end if;

        -- Spitze: alle Clients senden bis l_end ohne Pause (3 s Vorlauf fuer den Start der Jobs)
        l_end := systimestamp + numtodsinterval(p_seconds + 3, 'SECOND');
        l_t := systimestamp;
        for c in 1 .. p_clients loop
            run_job('LT_C' || l_run || '_' || c,
              'begin lt.burst(' || l_run || ', ' || c || ', ''' || p_mode || ''', ''' || l_burst || ''', '
              || 'to_timestamp(''' || to_char(l_end, 'YYYY-MM-DD HH24:MI:SS.FF3') || ''', ''YYYY-MM-DD HH24:MI:SS.FF3'')); end;');
        end loop;
        check_that(l_run, 'Client-Jobs beendet', wait_jobs('LT_C' || l_run || '_', p_seconds + c_job_wait));
        throughput_metrics(l_run, p_clients, false);
        select nvl(sum(value), 0) into l_ops from lt_metric where run_id = l_run and metric = 'client_ops';

        -- Erholung 1: trotz Ueberlast kommen alle Daten vollstaendig an
        for w in (select column_value what from table(sys.odcivarchar2list('LOG', 'TRACE', 'EVENT'))) loop
            l_ms := wait_count(l_burst, w.what, l_ops, p_max_wait);
            l_n  := count_lilam(l_burst, w.what);
            check_that(l_run, 'Lastspitze: Anzahl ' || w.what || ' = gesendete Operationen', l_n = l_ops, l_n || '/' || l_ops);
            if l_ms >= 0 then metric(l_run, 'drain_' || lower(w.what) || '_ms', l_ms, 'ms'); end if;
        end loop;
        l_n := count_lilam(l_burst, 'PROC_CLOSED');
        check_that(l_run, 'Lastspitze: alle Prozesse geschlossen', l_n = p_clients, l_n || '/' || p_clients);

        -- Erholung 2: ein neuer Prozess arbeitet danach wieder normal (eigene Session)
        run_job('LT_CP' || l_run, 'begin lt.probe(' || l_run || ', ''' || p_mode || ''', ''' || l_probe || ''', ' || c_probe_ops || '); end;');
        check_that(l_run, 'Probe nach der Spitze beendet', wait_jobs('LT_CP' || l_run, 120));
        select max(value) into l_ms from lt_metric where run_id = l_run and metric = 'probe_ms';
        check_that(l_run, 'Probe: neuer Prozess mit ' || c_probe_ops || ' Operationen < 3 s', nvl(l_ms, 99999) < 3000, l_ms || ' ms');
        l_ms := wait_count(l_probe, 'LOG', c_probe_ops, 30);
        check_that(l_run, 'Probe: Daten innerhalb 30 s persistiert', l_ms >= 0, l_ms || ' ms');

        l_n := count_lilam(l_burst, 'ROUTES') + count_lilam(l_probe, 'ROUTES');
        check_that(l_run, 'Keine Prozess-Routen uebrig', l_n = 0, 'ist ' || l_n);
        select count(*) into l_n from lt_joblog where run_id = l_run and phase = 'ERROR';
        check_that(l_run, 'Keine Fehler in den Client-Jobs', l_n = 0, l_n || ' Fehler');
        l_n := internal_errors_since(run_started(l_run));
        check_that(l_run, 'Keine internen LILAM-Fehler', l_n = 0, l_n || ' Eintraege');

        if p_manage then stop_all_servers; end if;
        end_run(l_run);
        return l_run;
    exception
        when others then
            abort_run(l_run, p_manage, sqlerrm || ' ' || dbms_utility.format_error_backtrace);
            if p_manage then raise; end if;
            return l_run;
    end;

