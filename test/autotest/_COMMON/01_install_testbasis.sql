    procedure purge_prefix(p_prefix varchar2) is
        pragma autonomous_transaction;
        l_p varchar2(200) := replace(p_prefix, '_', '\_') || '%';
    begin
        execute immediate 'delete from lilam_log where process_id in (select id from lilam_proc where process_name like :1 escape ''\'')' using l_p;
        execute immediate 'delete from lilam_mon where process_id in (select id from lilam_proc where process_name like :1 escape ''\'')' using l_p;
        execute immediate 'delete from lilam_process_route where process_id in (select id from lilam_proc where process_name like :1 escape ''\'')' using l_p;
        execute immediate 'delete from lilam_baselines where scope_id in (select scope_id from lilam_scopes where scope_name like upper(:1) escape ''\'')' using l_p;
        execute immediate 'delete from lilam_scopes where scope_name like upper(:1) escape ''\''' using l_p;
        execute immediate 'delete from lilam_proc where process_name like :1 escape ''\''' using l_p;
        commit;
    exception
        when others then
            rollback;
            joblog(null, null, 'ERROR', 'purge_prefix ' || p_prefix || ': ' || sqlerrm);
    end;

