    function t_baseline_scope(p_manage boolean default true, p_parent number default null) return number is
        c_action  constant varchar2(30) := 'BS_ACTION';
        c_sleep_s constant number       := 0.2;
        l_run     number;

        function run_app(p_mode varchar2, p_name varchar2, p_scope varchar2, p_traces pls_integer) return number is
            l_pid number;
        begin
            if p_mode = c_insession then
                l_pid := lilam.new_session(p_processName => p_name, p_logLevel => lilam.logLevelInfo, p_baselineScope => p_scope);
            else
                l_pid := lilam.server_new_session(p_processName => p_name, p_groupName => c_group,
                                                  p_logLevel => lilam.logLevelInfo, p_baselineScope => p_scope);
            end if;
            for i in 1 .. p_traces loop
                lilam.trace_start(l_pid, c_action);
                dbms_session.sleep(c_sleep_s);
                lilam.trace_stop(l_pid, c_action);
            end loop;
            lilam.close_session(l_pid);
            return l_pid;
        end;

        function scope_count(p_scope varchar2) return number is
            l_cnt number;
        begin
            execute immediate 'select count(*) from lilam_scopes where scope_name = upper(:1)' into l_cnt using p_scope;
            return l_cnt;
        end;

        function base_count(p_scope varchar2) return number is
            l_cnt number;
        begin
            execute immediate 'select nvl(sum(b.action_count), 0) from lilam_baselines b join lilam_scopes s on s.scope_id = b.scope_id
                                where s.scope_name = upper(:1) and b.action_name = :2' into l_cnt using p_scope, c_action;
            return l_cnt;
        end;

        function base_avg(p_scope varchar2) return number is
            l_avg number;
        begin
            execute immediate 'select max(b.avg_ms) from lilam_baselines b join lilam_scopes s on s.scope_id = b.scope_id
                                where s.scope_name = upper(:1) and b.action_name = :2' into l_avg using p_scope, c_action;
            return l_avg;
        end;

        -- im SERVER-Modus wird die Baseline asynchron abgeglichen
        procedure wait_base(p_scope varchar2, p_expected number, p_max_s number default 15) is
            l_waited number := 0;
        begin
            while base_count(p_scope) < p_expected and l_waited < p_max_s loop
                dbms_session.sleep(0.5); l_waited := l_waited + 0.5;
            end loop;
        end;

        procedure run_mode(p_mode varchar2, p_tag varchar2) is
            l_prefix varchar2(60) := 'LT_' || l_run || '_' || p_tag;
            l_app    varchar2(80) := l_prefix || '_APP';
            l_shared varchar2(80) := l_prefix || '_SHARED';
            l_pid    number;
            l_cnt    number;
            l_avg    number;
            l_mon    number;
        begin
            -- B1: Default-Scope, drei Neustarts mit je 2 Traces
            for r in 1 .. 3 loop l_pid := run_app(p_mode, l_app, null, 2); end loop;
            wait_base(l_app, 6);
            l_cnt := base_count(l_app);
            l_avg := base_avg(l_app);
            check_that(l_run, p_tag || ' B1 Default-Scope: genau 1 Scope fuer den Prozessnamen', scope_count(l_app) = 1, scope_count(l_app));
            check_that(l_run, p_tag || ' B1 Baseline zaehlt alle 6 Messungen aus 3 Prozessen', l_cnt = 6, l_cnt);
            check_that(l_run, p_tag || ' B1 Mittel der Baseline plausibel (150..500 ms)', l_avg between 150 and 500, round(l_avg, 1) || ' ms');
            metric(l_run, lower(p_tag) || '_baseline_avg_ms', l_avg, 'ms');

            -- B2: ACTION_COUNT in _MON zaehlt je Prozess (1, 2), nicht ueber den Scope
            execute immediate 'select nvl(max(m.action_count), 0) from lilam_mon m join lilam_proc p on p.id = m.process_id
                                where p.process_name = :1 and m.action = :2' into l_cnt using l_app, c_action;
            check_that(l_run, p_tag || ' B2 _MON zaehlt prozesslokal (max. 2 je Prozess)', l_cnt = 2, l_cnt);

            -- B3: AVG_MILLIS des letzten Eintrags = Baseline des Scopes
            execute immediate 'select max(m.avg_millis) keep (dense_rank last order by m.stop_time)
                                 from lilam_mon m where m.process_id = :1 and m.action = :2' into l_mon using l_pid, c_action;
            check_that(l_run, p_tag || ' B3 _MON.AVG_MILLIS des letzten Prozesses = Baseline', abs(nvl(l_mon, -1) - l_avg) <= 1,
                       'MON ' || l_mon || ' / Baseline ' || round(l_avg, 1));

            -- B4: #NONE aendert die Baseline nicht
            l_pid := run_app(p_mode, l_app, '#NONE', 2);
            if p_mode != c_insession then dbms_session.sleep(3); end if;
            check_that(l_run, p_tag || ' B4 Scope #NONE: Baseline unveraendert', base_count(l_app) = 6, base_count(l_app));
            check_that(l_run, p_tag || ' B4 Scope #NONE: kein Scope "#NONE" angelegt', scope_count('#NONE') = 0, scope_count('#NONE'));

            -- B5: frei gewaehlter Scope, zwei verschiedene Prozessnamen
            l_pid := run_app(p_mode, l_prefix || '_X', l_shared, 2);
            l_pid := run_app(p_mode, l_prefix || '_Y', l_shared, 2);
            wait_base(l_shared, 4);
            check_that(l_run, p_tag || ' B5 gemeinsamer Scope zaehlt beide Prozesse (4)', base_count(l_shared) = 4, base_count(l_shared));
            check_that(l_run, p_tag || ' B5 keine eigenen Scopes fuer _X/_Y',
                       scope_count(l_prefix || '_X') + scope_count(l_prefix || '_Y') = 0,
                       scope_count(l_prefix || '_X') + scope_count(l_prefix || '_Y'));
        end;
    begin
        l_run := begin_run('BASELINE_SCOPE', 'INSESSION+SERVER', null, p_parent);
        run_mode(c_insession, 'IS');
        if p_manage then setup_servers(c_server, 1); end if;
        run_mode(c_server, 'SV');
        if p_manage then stop_all_servers; end if;
        check_that(l_run, 'B6 Keine internen LILAM-Fehler', internal_errors_since(run_started(l_run)) = 0,
                   internal_errors_since(run_started(l_run)));
        end_run(l_run);
        return l_run;
    exception
        when others then
            abort_run(l_run, p_manage, sqlerrm || ' ' || dbms_utility.format_error_backtrace);
            if p_manage then raise; end if;
            return l_run;
    end;

