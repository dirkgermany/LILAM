create or replace package body lt as

    g_check_no pls_integer := 0;
    c_job_wait constant number := 900;   -- max. Wartezeit in s auf das Ende der Client-Jobs

    ----------------------------------------------------------------------
    function ms_since(p_ts timestamp) return number is
        l_d interval day(9) to second(6) := systimestamp - p_ts;
    begin
        return round(extract(day from l_d) * 86400000 + extract(hour from l_d) * 3600000
                   + extract(minute from l_d) * 60000 + extract(second from l_d) * 1000, 1);
    end;

    ----------------------------------------------------------------------
    function begin_run(p_test varchar2, p_mode varchar2, p_params varchar2 default null, p_parent number default null) return number is
        pragma autonomous_transaction;
        l_id number;
    begin
        insert into lt_run(test_name, mode_name, params, parent_run_id) values (p_test, p_mode, p_params, p_parent)
        returning run_id into l_id;
        commit;
        g_check_no := 0;
        dbms_output.put_line('=== ' || p_test || ' (' || p_mode || ')  run_id=' || l_id);
        if p_params is not null then dbms_output.put_line('    Parameter: ' || p_params); end if;
        return l_id;
    end;

    function run_started(p_run_id number) return timestamp is
        l_ts timestamp;
    begin
        select started into l_ts from lt_run where run_id = p_run_id;
        return l_ts;
    end;

    ----------------------------------------------------------------------
    procedure check_that(p_run_id number, p_name varchar2, p_ok boolean, p_detail varchar2 default null) is
        pragma autonomous_transaction;
    begin
        g_check_no := g_check_no + 1;
        insert into lt_check(run_id, check_no, check_name, ok, detail)
        values (p_run_id, g_check_no, p_name, case when p_ok then 1 else 0 end, p_detail);
        commit;
        dbms_output.put_line(case when p_ok then 'OK     ' else 'FEHLER ' end || p_name
                             || case when p_detail is not null then '  [' || p_detail || ']' end);
    end;

    procedure metric(p_run_id number, p_name varchar2, p_value number, p_unit varchar2 default null, p_client number default null) is
        pragma autonomous_transaction;
    begin
        insert into lt_metric(run_id, metric, value, unit, client_no) values (p_run_id, p_name, p_value, p_unit, p_client);
        commit;
    end;

    procedure joblog(p_run_id number, p_client number, p_phase varchar2, p_info varchar2) is
        pragma autonomous_transaction;
    begin
        insert into lt_joblog(run_id, client_no, phase, info) values (p_run_id, p_client, p_phase, substr(p_info, 1, 4000));
        commit;
    end;

    procedure end_run(p_run_id number) is
        pragma autonomous_transaction;
        l_ok number; l_fail number;
        l_dur interval day to second;
    begin
        select nvl(sum(ok), 0), count(*) - nvl(sum(ok), 0) into l_ok, l_fail from lt_check where run_id = p_run_id;
        select systimestamp - started into l_dur from lt_run where run_id = p_run_id;
        update lt_run set ended = systimestamp, status = case when l_fail = 0 then 'PASSED' else 'FAILED' end
         where run_id = p_run_id;
        commit;
        dbms_output.put_line('--- Messwerte');
        for m in (select metric, round(avg(value), 2) v, unit, count(*) n from lt_metric where run_id = p_run_id
                   group by metric, unit order by metric) loop
            dbms_output.put_line('    ' || rpad(m.metric, 32) || m.v || ' ' || m.unit || case when m.n > 1 then '  (Mittel aus ' || m.n || ')' end);
        end loop;
        dbms_output.put_line('    ' || rpad('Gesamtlaufzeit Test', 32)
                             || to_char(round(extract(day from l_dur) * 86400 + extract(hour from l_dur) * 3600
                                              + extract(minute from l_dur) * 60 + extract(second from l_dur), 1), 'FM999999990.0')
                             || ' s  ('
                             || to_char(extract(hour from l_dur) + extract(day from l_dur) * 24, 'FM00') || ':'
                             || to_char(extract(minute from l_dur), 'FM00') || ':'
                             || to_char(trunc(extract(second from l_dur)), 'FM00') || ')');
        dbms_output.put_line('=== Ergebnis run_id=' || p_run_id || ': ' || l_ok || ' OK, ' || l_fail || ' FEHLER  -> '
                             || case when l_fail = 0 then 'BESTANDEN' else 'NICHT BESTANDEN' end);
    end;

    ----------------------------------------------------------------------
    -- Server
    ----------------------------------------------------------------------
    procedure start_server(p_pipe varchar2, p_dispatcher pls_integer default 0) is
        l_msg varchar2(4000);
    begin
        -- Alle Test-Server mit Leistungsstufe MID (1.500 Nachrichten/s je Prozess)
        l_msg := lilam.create_server(p_pipe, c_group, c_pw, p_dispatcher, p_perfServer => lilam.C_SERVER_PERF_MID);
        dbms_output.put_line('    ' || l_msg);
    end;

    procedure wait_servers_ready(p_pipes sys.odcivarchar2list, p_max_sec number default 20) is
        l_cnt number := 0; l_waited number := 0;
    begin
        loop
            begin
                execute immediate
                   'select count(*) from lilam_server_registry where is_active = 1
                       and last_activity > systimestamp - interval ''10'' second
                       and pipe_name in (select column_value from table(:1))'
                   into l_cnt using p_pipes;
            exception when others then l_cnt := 0;
            end;
            exit when l_cnt = p_pipes.count or l_waited >= p_max_sec;
            dbms_session.sleep(0.5); l_waited := l_waited + 0.5;
        end loop;
        dbms_output.put_line('    Server bereit: ' || l_cnt || '/' || p_pipes.count);
    end;

    function stop_server(p_pipe varchar2) return boolean is
        l_chan varchar2(60) := 'LT_SHUT_' || sys_context('USERENV', 'SID') || '_' || to_char(systimestamp, 'SSFF3');
        l_st   pls_integer;
        l_cnt  number := 1;
        l_waited number := 0;
    begin
        dbms_pipe.reset_buffer;
        dbms_pipe.pack_message('{"header":{"msg_type":"API_CALL","request":"SERVER_SHUTDOWN","response":"' || l_chan
                               || '"},"payload":{"pipe_name":"' || p_pipe || '","shutdown_password":"' || c_pw || '"}}');
        l_st := dbms_pipe.send_message(p_pipe, timeout => 2);
        l_st := dbms_pipe.receive_message(l_chan, timeout => 10);
        l_st := dbms_pipe.remove_pipe(l_chan);
        loop
            select count(*) into l_cnt from user_scheduler_jobs where job_name = upper(p_pipe);
            exit when l_cnt = 0 or l_waited >= 15;
            dbms_session.sleep(0.5); l_waited := l_waited + 0.5;
        end loop;
        return l_cnt = 0;
    end;

    procedure stop_all_servers is
        l_dummy boolean;
    begin
        -- zuerst Dispatcher, dann Worker
        for s in (select job_name from user_scheduler_jobs where job_name like 'LT\_%' escape '\'
                     and job_name not like 'LT\_C%' escape '\'
                   order by case when job_name = c_disp_pipe then 0 else 1 end) loop
            l_dummy := stop_server(s.job_name);
            if not l_dummy then
                begin dbms_scheduler.stop_job(s.job_name); exception when others then null; end;
            end if;
            dbms_output.put_line('    gestoppt: ' || s.job_name);
        end loop;
    end;

    ----------------------------------------------------------------------
    -- Jobs
    ----------------------------------------------------------------------
    procedure run_job(p_name varchar2, p_plsql varchar2) is
    begin
        dbms_scheduler.create_job(job_name => p_name, job_type => 'PLSQL_BLOCK', job_action => p_plsql,
                                  enabled => true, auto_drop => true);
    end;

    function wait_jobs(p_prefix varchar2, p_max_sec number) return boolean is
        l_cnt number; l_waited number := 0;
    begin
        loop
            -- '_' im Praefix woertlich nehmen (sonst passt z.B. LT_C10_ auch auf LT_C100_1)
            select count(*) into l_cnt from user_scheduler_jobs
             where job_name like replace(p_prefix, '_', '\_') || '%' escape '\';
            exit when l_cnt = 0 or l_waited >= p_max_sec;
            dbms_session.sleep(1); l_waited := l_waited + 1;
        end loop;
        return l_cnt = 0;
    end;

    ----------------------------------------------------------------------
    -- Zaehlen
    ----------------------------------------------------------------------
    function count_lilam(p_prefix varchar2, p_what varchar2) return number is
        l_sql varchar2(1000);
        l_n   number;
        l_p   varchar2(200) := replace(p_prefix, '_', '\_') || '%';
    begin
        l_sql := case upper(p_what)
            when 'PROC'        then 'select count(*) from lilam_proc where process_name like :1 escape ''\'''
            when 'PROC_CLOSED' then 'select count(*) from lilam_proc where process_name like :1 escape ''\'' and process_end is not null'
            when 'LOG'         then 'select count(*) from lilam_log l join lilam_proc p on p.id = l.process_id where p.process_name like :1 escape ''\'''
            when 'TRACE'       then 'select count(*) from lilam_mon m join lilam_proc p on p.id = m.process_id where p.process_name like :1 escape ''\'' and m.mon_type = 1'
            when 'EVENT'       then 'select count(*) from lilam_mon m join lilam_proc p on p.id = m.process_id where p.process_name like :1 escape ''\'' and m.mon_type = 0'
            when 'STEPS'       then 'select nvl(sum(steps_done), 0) from lilam_proc where process_name like :1 escape ''\'''
            when 'ROUTES'      then 'select count(*) from lilam_process_route r join lilam_proc p on p.id = r.process_id where p.process_name like :1 escape ''\'''
            when 'BASELINE'    then 'select nvl(sum(b.action_count), 0) from lilam_baselines b join lilam_scopes s on s.scope_id = b.scope_id where s.scope_name like upper(:1) escape ''\'' and b.action_name = ''LT_ACTION'''
        end;
        execute immediate l_sql into l_n using l_p;
        return l_n;
    exception
        when others then return -1;
    end;

    function wait_count(p_prefix varchar2, p_what varchar2, p_expected number, p_max_sec number) return number is
        l_t0 timestamp := systimestamp;
    begin
        loop
            exit when count_lilam(p_prefix, p_what) >= p_expected;
            if ms_since(l_t0) > p_max_sec * 1000 then return -1; end if;
            dbms_session.sleep(0.25);
        end loop;
        return ms_since(l_t0);
    end;

    function internal_errors_since(p_ts timestamp) return number is
        l_n number;
    begin
        execute immediate 'select count(*) from lilam_log_internal where log_timestamp >= :1' into l_n using p_ts;
        return l_n;
    exception
        when others then return 0;   -- Tabelle existiert erst nach dem ersten internen Fehler
    end;

    ----------------------------------------------------------------------
    -- Speicher (benoetigt direkte Grants, siehe 00_grants_als_sys.sql)
    ----------------------------------------------------------------------
    function my_pga_kb return number is
        l_n number;
    begin
        execute immediate 'select round(m.value / 1024) from v$mystat m join v$statname s on s.statistic# = m.statistic#
                            where s.name = ''session pga memory''' into l_n;
        return l_n;
    exception when others then return null;
    end;

    function server_pga_kb return number is
        l_n number;
    begin
        execute immediate 'select round(sum(p.pga_used_mem) / 1024) from v$session s join v$process p on p.addr = s.paddr
                            where s.module like ''LILAM_SERVER%''' into l_n;
        return l_n;
    exception when others then return null;
    end;

    ----------------------------------------------------------------------
    -- Workloads
