    function t_parallel(p_mode varchar2, p_variants varchar2 default 'ABCD', p_clients number default null,
                        p_processes number default 2, p_ops number default 200,
                        p_manage boolean default true, p_max_wait number default 300, p_parent number default null) return number is
        l_clients number := nvl(p_clients, case when p_mode = c_insession then 8 else 10 end);
        l_run     number;
        l_prefix  varchar2(60);
        l_name    varchar2(100);
        l_scope   varchar2(100);
        l_scopes  pls_integer;
        l_var     varchar2(1);
        l_title   varchar2(100);
    begin
        if p_manage then setup_servers(p_mode, 2); end if;

        for v in 1 .. length(p_variants) loop
            l_var := upper(substr(p_variants, v, 1));
            l_title := case l_var
                         when 'A' then 'A gleicher Name, Default-Scope'
                         when 'B' then 'B eigene Namen, Default-Scope'
                         when 'C' then 'C eigene Namen, gemeinsamer Scope'
                         when 'D' then 'D gleicher Name, Scope #NONE'
                       end;
            l_run := begin_run('PARALLELBETRIEB', p_mode,
                       'variante=' || l_title || ' clients=' || l_clients || ' processes=' || p_processes || ' ops=' || p_ops, p_parent);
            l_prefix := 'LT_' || l_run || '_PAR' || l_var;

            for c in 1 .. l_clients loop
                l_name  := case when l_var in ('B', 'C') then l_prefix || '_C' || c else l_prefix end;
                l_scope := case l_var when 'C' then l_prefix || '_SHARED' when 'D' then '#NONE' end;
                run_job('LT_C' || l_run || '_' || c,
                  'begin lt.workload(' || l_run || ', ' || c || ', ''' || p_mode || ''', ''' || l_name || ''', '
                                       || p_processes || ', ' || p_ops || ', 0, false, '
                                       || case when l_scope is null then 'null' else '''' || l_scope || '''' end || '); end;');
            end loop;

            check_that(l_run, 'Client-Jobs innerhalb ' || c_job_wait || ' s beendet', wait_jobs('LT_C' || l_run || '_', c_job_wait));
            throughput_metrics(l_run, l_clients, false);

            l_scopes := case l_var when 'A' then 1 when 'B' then l_clients when 'C' then 1 when 'D' then 0 end;
            verify_standard(l_run, l_prefix, l_clients * p_processes, p_ops, p_mode != c_insession, p_max_wait, l_scopes);
            end_run(l_run);
        end loop;

        if p_manage then stop_all_servers; end if;
        return l_run;
    exception
        when others then
            abort_run(l_run, p_manage, sqlerrm || ' ' || dbms_utility.format_error_backtrace);
            if p_manage then raise; end if;
            return l_run;
    end;

