-- =====================================================================
-- LILAM Testbasis: Tabellen und Package LT
-- Ausfuehren als Testschema (z.B. LILAM_TEST), nach der Installation von LILAM.
-- Mehrfach ausfuehrbar (Tabellen bleiben erhalten, Package wird ersetzt).
--
-- LT_RUN     ein Testlauf (Name, Modus, Parameter, Status)
-- LT_CHECK   Pruefungen eines Laufs (OK / FEHLER)
-- LT_METRIC  Messwerte eines Laufs (z.B. Laufzeiten, Durchsatz, Speicher)
-- LT_JOBLOG  Meldungen und Fehler der Client-Jobs
-- =====================================================================
set serveroutput on size unlimited

declare
  l_cnt number;
  procedure ddl(p_name varchar2, p_sql varchar2) is
    l_cnt number;
  begin
    select count(*) into l_cnt from user_tables where table_name = p_name;
    if l_cnt = 0 then execute immediate p_sql; dbms_output.put_line('angelegt: ' || p_name); end if;
  end;
begin
  ddl('LT_RUN', 'create table lt_run (
      run_id     number generated by default as identity primary key,
      test_name  varchar2(100) not null,
      mode_name  varchar2(30),
      params     varchar2(1000),
      started    timestamp(6) default systimestamp,
      ended      timestamp(6),
      status     varchar2(10) default ''RUNNING'')');
  ddl('LT_CHECK', 'create table lt_check (
      run_id     number not null,
      check_no   number,
      check_name varchar2(200),
      ok         number(1),
      detail     varchar2(1000),
      ts         timestamp(6) default systimestamp)');
  ddl('LT_METRIC', 'create table lt_metric (
      run_id     number not null,
      metric     varchar2(100),
      value      number,
      unit       varchar2(20),
      client_no  number,
      ts         timestamp(6) default systimestamp)');
  ddl('LT_JOBLOG', 'create table lt_joblog (
      run_id     number,
      client_no  number,
      phase      varchar2(30),
      info       varchar2(4000),
      ts         timestamp(6) default systimestamp)');

  -- Teiltests eines Dauertests verweisen auf den Dauertest-Lauf
  select count(*) into l_cnt from user_tab_columns where table_name = 'LT_RUN' and column_name = 'PARENT_RUN_ID';
  if l_cnt = 0 then
    execute immediate 'alter table lt_run add parent_run_id number';
    dbms_output.put_line('ergaenzt: LT_RUN.PARENT_RUN_ID');
  end if;
end;
/

create or replace package lt authid definer as
    -- Gemeinsame Konstanten
    c_group     constant varchar2(10) := 'LT';        -- Servergruppe aller Tests
    c_pw        constant varchar2(20) := 'LtTestPw';  -- Shutdown-Passwort aller Testserver
    c_disp_pipe constant varchar2(20) := 'LT_DISP';   -- Pipe des Test-Dispatchers

    -- Modi fuer die Workloads
    c_insession  constant varchar2(20) := 'INSESSION';
    c_server     constant varchar2(20) := 'SERVER';
    c_dispatcher constant varchar2(20) := 'DISPATCHER';

    -- Testlauf
    function  begin_run(p_test varchar2, p_mode varchar2, p_params varchar2 default null, p_parent number default null) return number;
    procedure check_that(p_run_id number, p_name varchar2, p_ok boolean, p_detail varchar2 default null);
    procedure metric(p_run_id number, p_name varchar2, p_value number, p_unit varchar2 default null, p_client number default null);
    procedure joblog(p_run_id number, p_client number, p_phase varchar2, p_info varchar2);
    procedure end_run(p_run_id number);
    function  run_started(p_run_id number) return timestamp;

    -- Server
    procedure start_server(p_pipe varchar2, p_dispatcher pls_integer default 0);
    procedure wait_servers_ready(p_pipes sys.odcivarchar2list, p_max_sec number default 20);
    function  stop_server(p_pipe varchar2) return boolean;
    procedure stop_all_servers;

    -- Jobs (parallele Clients, jeder Job = eigene Session mit leerem PGA)
    procedure run_job(p_name varchar2, p_plsql varchar2);
    function  wait_jobs(p_prefix varchar2, p_max_sec number) return boolean;

    -- Zaehlen in den LILAM-Tabellen (Prozesse ueber Namenspraefix)
    --   p_what: PROC, PROC_CLOSED, LOG, TRACE, EVENT, STEPS, ROUTES, BASELINE
    function  count_lilam(p_prefix varchar2, p_what varchar2) return number;
    function  wait_count(p_prefix varchar2, p_what varchar2, p_expected number, p_max_sec number) return number;
    function  internal_errors_since(p_ts timestamp) return number;

    -- Hilfen
    function  ms_since(p_ts timestamp) return number;
    function  my_pga_kb return number;           -- NULL ohne Grants (siehe 00_grants_als_sys.sql)
    function  server_pga_kb return number;       -- Summe PGA aller LILAM-Server; NULL ohne Grants

    -- Standard-Workload je Prozess und Operation:
    --   INFO, TRACE_START/TRACE_STOP (LT_ACTION), MARK_EVENT (LT_EVENT), PROC_STEP_DONE
    -- Erwartung je Prozess: LOG = TRACE = EVENT = STEPS = p_ops
    procedure workload(
        p_run_id      number,
        p_client      number,
        p_mode        varchar2,
        p_proc_name   varchar2,
        p_processes   number,
        p_ops         number,
        p_sleep_ms    number  default 0,
        p_interleave  boolean default false,   -- TRUE: erst alle Prozesse oeffnen, dann Operationen reihum
        p_scope       varchar2 default null);  -- p_baselineScope fuer NEW_SESSION (NULL = Default: Prozessname)

    -- Dauerlauf: wiederholt kurze Prozesszyklen bis p_end_ts, mit Pausen und Messwerten
    procedure endurance(
        p_run_id       number,
        p_client       number,
        p_mode         varchar2,
        p_proc_name    varchar2,
        p_end_ts       timestamp,
        p_ops          number default 20,
        p_max_pause_s  number default 30,
        p_metric_min   number default 10);

    -- Prozesszyklen: viele Prozesse mit vollstaendigem Lebenszyklus, p_window davon gleichzeitig offen.
    -- Je Prozess: NEW_SESSION (steps_todo = p_ops), SET_PROCESS_STATUS 'RUNNING',
    --   p_ops Operationen (INFO, TRACE, EVENT, PROC_STEP_DONE), zur Haelfte Status 'HALF',
    --   am Ende Rueckleseprobe GET_PROC_STEPS_DONE = p_ops, CLOSE_SESSION mit Steps, Info 'DONE ...', Status 2.
    -- Operationen werden zufaellig auf die offenen Prozesse verteilt, mit kurzen Zufallspausen.
    procedure lifecycle(
        p_run_id        number,
        p_client        number,
        p_mode          varchar2,
        p_proc_name     varchar2,
        p_processes     number,
        p_ops           number,
        p_window        number default 3,
        p_max_pause_ms  number default 20);

    -- Pruefung nach lifecycle: alle Prozesse mit korrektem Endzustand in _PROC,
    -- vollstaendige Logs/Traces/Events, keine Abweichungen beim Rueckleseprobe,
    -- optional Verteilung auf mindestens p_min_servers Server
    procedure verify_lifecycle(
        p_run_id       number,
        p_prefix       varchar2,
        p_processes    number,
        p_ops          number,
        p_check_routes boolean default false,
        p_min_servers  number  default 0,
        p_max_wait_sec number  default 180);

    -- Ein einzelner "Weck-Aufruf" nach einer Ruhephase des Servers:
    --   INFO + MARK_EVENT fuer einen bestehenden Prozess, optional neuer Prozess (oeffnen/schliessen)
    --   Laeuft im Modus DISPATCHER als Job (frische Session), im Modus SERVER in der aufrufenden Session
    procedure wake_call(p_run_id number, p_mode varchar2, p_pid number, p_idle_s number,
                        p_proc_name varchar2, p_new_session boolean default true);

    -- Standard-Pruefung nach einer Workload (wartet, bis alle Daten persistiert sind):
    --   Prozesse vorhanden und geschlossen, LOG/TRACE/EVENT/STEPS je = processes * ops,
    --   Baseline: genau p_baseline_scopes Scopes (Name beginnt mit p_prefix), jeder zaehlt
    --   processes * ops / p_baseline_scopes Traces; 0 = es darf keine Baseline entstehen,
    --   keine Routen uebrig (decoupled), keine Job- und internen Fehler
    procedure verify_standard(
        p_run_id          number,
        p_prefix          varchar2,
        p_processes       number,
        p_ops             number,
        p_check_routes    boolean default false,
        p_max_wait_sec    number  default 120,
        p_baseline_scopes number  default 1);

    -- ==================================================================
    -- Tests als Funktionen (die Skripte unter INSESSION/, DECOUPLED/, FEATURES/ rufen diese auf)
    --
    -- Gemeinsame Parameter:
    --   p_mode      c_insession | c_server | c_dispatcher
    --   p_manage    TRUE: der Test startet und stoppt seine Server selbst (Einzeltest)
    --               FALSE: die Server laufen bereits (z.B. im Dauertest)
    --   p_max_wait  max. Wartezeit in s je Pruefung auf vollstaendige Daten
    --   p_parent    run_id eines uebergeordneten Laufs (Dauertest), sonst NULL
    -- Rueckgabe: run_id des Testlaufs (bei PARALLELBETRIEB die der letzten Variante)
    -- ==================================================================
    function t_lasttest(p_mode varchar2, p_ops number default 5000,
                        p_manage boolean default true, p_max_wait number default 300, p_parent number default null) return number;

    function t_massentest(p_mode varchar2, p_processes number default 200, p_ops number default 20,
                          p_manage boolean default true, p_max_wait number default 300, p_parent number default null) return number;

    -- p_variants: Folge aus A, B, C, D; p_clients NULL = 8 (INSESSION) bzw. 10 (decoupled)
    function t_parallel(p_mode varchar2, p_variants varchar2 default 'ABCD', p_clients number default null,
                        p_processes number default 2, p_ops number default 200,
                        p_manage boolean default true, p_max_wait number default 300, p_parent number default null) return number;

    -- p_clients NULL = 8 (INSESSION) bzw. 10 (decoupled)
    function t_zyklen(p_mode varchar2, p_clients number default null, p_processes number default 30, p_ops number default 20,
                      p_window number default 3, p_pause_ms number default 20,
                      p_manage boolean default true, p_max_wait number default 300, p_parent number default null) return number;

    -- nur decoupled
    function t_wakeup(p_mode varchar2, p_idle sys.odcinumberlist default sys.odcinumberlist(5, 16, 30, 65),
                      p_manage boolean default true, p_parent number default null) return number;

    -- INSESSION und SERVER in einem Lauf
    function t_logtext(p_manage boolean default true, p_parent number default null) return number;
    function t_baseline_scope(p_manage boolean default true, p_parent number default null) return number;
    -- Sichtbarkeit vor CLOSE_SESSION: reine Monitoring-Prozesse (ohne Log) schreiben zeitgesteuert zurueck
    function t_rueckschreibung(p_manage boolean default true, p_parent number default null) return number;
    -- Baustein von t_rueckschreibung (laeuft als Job = fremde Session): Tabellenstand als Messwerte festhalten
    procedure rs_peek(p_run_id number, p_prefix varchar2, p_key varchar2);

    -- Regeln (Rules Engine) im SERVER- und INSESSION-Modus: Laden, Operatoren, Alerts. Nur einzeln (aendert das Rule Set der Gruppe LT)
    function t_regeln(p_manage boolean default true, p_parent number default null) return number;
    -- Kosten der Regelpruefung je Signaltyp (EVENT, TRACE, LOG, STEP) und Variante, SERVER und INSESSION; nur einzeln
    function t_regeln_last(p_n number default 2000, p_n_fire number default 200, p_reps number default 5,
                           p_manage boolean default true, p_parent number default null) return number;

    -- Speicher: PGA-Wachstum je Prozess in Client, Workern und Dispatcher (INSESSION, SERVER, DISPATCHER)
    -- sowie Fallback beim Schreiben (fehlerhafte Zeile wird uebersprungen, die uebrigen bleiben erhalten)
    function t_speicher(p_procs number default 5000, p_manage boolean default true, p_parent number default null) return number;

    -- Lastspitze: p_clients senden p_seconds lang so schnell wie moeglich; danach muessen alle Daten
    -- vollstaendig ankommen und ein neuer Prozess wieder normal arbeiten (Erholung). Nur decoupled.
    function t_lastspitze(p_mode varchar2, p_clients number default 6, p_seconds number default 30,
                          p_manage boolean default true, p_max_wait number default 300, p_parent number default null) return number;

    -- Bausteine der Lastspitze (laufen als Jobs)
    procedure burst(p_run_id number, p_client number, p_mode varchar2, p_proc_name varchar2, p_end_ts timestamp);
    procedure probe(p_run_id number, p_mode varchar2, p_proc_name varchar2, p_ops number);

    -- ==================================================================
    -- Dauertest als Kombination der Tests
    --   dauertest_start  startet Server, Hintergrund-Clients und den Steuer-Job; kehrt sofort zurueck
    --   dauertest_run    Steuer-Job: fuehrt bis p_end_ts Teiltests aus (je als eigener Job),
    --                    loescht die LILAM-Daten bestandener Teiltests, legt Pausen ein
    --   dauertest_auswertung  nach Ablauf: Teiltests, Stabilitaet, Hintergrund-Clients
    --
    --   p_modes   Komma-Liste aus INSESSION, SERVER, DISPATCHER
